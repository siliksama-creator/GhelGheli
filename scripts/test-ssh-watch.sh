#!/usr/bin/env bash
#
# ═══════════════════════════════════════════════════════════════════════════
#  آزمونِ ایزولهٔ نگهبانِ امنیت — بدونِ تلگرامِ واقعی، بدونِ لاگِ واقعی
# ═══════════════════════════════════════════════════════════════════════════
#
# چرا: این نگهبان روی «مسیرِ هشدار» کار می‌کند و اگر خراب باشد، کسی نمی‌فهمد
# (دقیقاً همان تلهٔ نگهبانِ سلامت که آلارمش هرگز «برطرف شد» نمی‌گفت). این
# آزمون پنج رفتار را قفل می‌کند:
#
#   ۱) اجرای اول: پایه‌گذاریِ ساکت (هیچ پیامِ الکی).
#   ۲) تغییرِ فایلِ حساس: پیام با نامِ دقیقِ فایل.
#   ۳) اجرای بی‌تغییر: کاملاً ساکت (نه اسپم).
#   ۴) ≥۳ بنِ متفاوت در ۱۵ دقیقه: پیامِ «کمپینِ ورودِ ناموفق» — و تکرارش ساکت.
#   ۵) آی‌پی‌ای که هم تلاشِ ناموفق داشته و هم ورودِ موفق: پیامِ «نفوذ».
#   ۶) خالصهٔ روزانه و --refresh هم کار می‌کنند.
#
# اجرا: bash scripts/test-ssh-watch.sh
#
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
WATCH="$REPO/monitor/ssh-watch.sh"
[ -f "$WATCH" ] || { echo "monitor/ssh-watch.sh پیدا نشد" >&2; exit 1; }

PASS=0; FAIL=0
ok()   { printf '  \033[32m✅ %s\033[0m\n' "$*"; PASS=$((PASS+1)); }
bad()  { printf '  \033[31m❌ %s\033[0m\n' "$*"; FAIL=$((FAIL+1)); }
head() { printf '\n\033[1;36m%s\033[0m\n' "$*"; }

ROOT="$(mktemp -d /tmp/ggssh.XXXXXX)"
cleanup() { if [ "${KEEP:-0}" = "1" ]; then echo "\n[آزمون] پوشهٔ موقت: $ROOT"; else rm -rf "$ROOT"; fi; }
trap cleanup EXIT

NOW="$(date +%s)"
mkdir -p "$ROOT/state" "$ROOT/etc"
printf 'secret-v1\n' > "$ROOT/etc/shadow"
printf 'root ALL=(ALL) ALL\n' > "$ROOT/etc/sudoers"
printf '%s\n%s\n' "$ROOT/etc/shadow" "$ROOT/etc/sudoers" > "$ROOT/paths.txt"
: > "$ROOT/auth.log"; : > "$ROOT/fail2ban.log"

ts_auth() { TZ=Asia/Tehran date -d "@$1" '+%Y-%m-%dT%H:%M:%S+03:30'; }
ts_f2b()  { TZ=Asia/Tehran date -d "@$1" '+%Y-%m-%d %H:%M:%S'; }

run() {
  AUTH_LOG="$ROOT/auth.log" F2B_LOG="$ROOT/fail2ban.log" \
  STATE_DIR="$ROOT/state" STATE_LOG="$ROOT/sshwatch.log" \
  INTEGRITY_PATHS_FILE="$ROOT/paths.txt" NOW_EPOCH="$NOW" \
  TG_CONF="$ROOT/no.conf" TG_CONF_ALT="$ROOT/no2.conf" \
  bash "$WATCH" "$@" 2>&1
}

# ═══════════════════════════════════════════════════════════════════════════
head "۱) اجرای اول — پایه‌گذاریِ ساکت"
# ═══════════════════════════════════════════════════════════════════════════
OUT="$(run --dry-run)"
printf '%s' "$OUT" | grep -q 'پیامِ تلگرام' && bad "اجرای اول هشدارِ الکی داد" || ok "اجرای اول هیچ پیامی نفرستاد"
grep -q 'baseline یکپارچگی' "$ROOT/sshwatch.log" && ok "پایه‌گذاری در لاگ ثبت شد" || bad "پایه‌گذاری ثبت نشد"
[ "$(grep -c . "$ROOT/state/integrity.sha256" 2>/dev/null)" = "2" ] && ok "اثرِ انگشتِ هر دو فایل ثبت شد" \
  || bad "اثرِ انگشت ناقص است: $(grep -c . "$ROOT/state/integrity.sha256" 2>/dev/null)"

# ═══════════════════════════════════════════════════════════════════════════
head "۲) تغییرِ فایلِ حساس — باید با نامِ فایل خبر بدهد"
# ═══════════════════════════════════════════════════════════════════════════
printf 'secret-v2-BACKDOOR\n' > "$ROOT/etc/shadow"
OUT="$(run --dry-run)"
printf '%s' "$OUT" | grep -q 'فایل‌های حساسِ سرور تغییر کرده' && ok "هشدارِ تغییرِ فایل حساس آمد" || bad "هشدارِ تغییر نیامد"
printf '%s' "$OUT" | grep -q 'shadow' && ok "نامِ فایلِ عوض‌شده در پیام هست" || bad "نامِ فایل در پیام نبود"
grep -q 'INTEGRITY CHANGE' "$ROOT/sshwatch.log" && ok "تغییر در لاگ ثبت شد" || bad "در لاگ ثبت نشد"

# ═══════════════════════════════════════════════════════════════════════════
head "۳) اجرای بی‌تغییر — باید کاملاً ساکت باشد"
# ═══════════════════════════════════════════════════════════════════════════
OUT="$(run --dry-run)"
printf '%s' "$OUT" | grep -q 'پیامِ تلگرام' && bad "اجرای بی‌تغییر اسپم کرد" || ok "اجرای بی‌تغییر ساکت بود"

# ═══════════════════════════════════════════════════════════════════════════
head "۴) کمپینِ بن — سه آی‌پیِ متفاوت در ۱۵ دقیقه"
# ═══════════════════════════════════════════════════════════════════════════
for i in 1 2 3; do
  printf '%s,000 fail2ban.actions [828]: NOTICE [sshd] Ban 203.0.113.%s\n' "$(ts_f2b $((NOW - 100 * i)))" "$i" >> "$ROOT/fail2ban.log"
done
OUT="$(run --dry-run)"
printf '%s' "$OUT" | grep -q 'کمپینِ ورودِ ناموفق' && ok "کمپین تشخیص داده شد" || bad "کمپین تشخیص داده نشد"
printf '%s' "$OUT" | grep -q '203.0.113.1' && ok "آی‌پی‌های کمپین در پیام آمدند" || bad "آی‌پی‌ها در پیام نبودند"
OUT="$(run --dry-run)"
printf '%s' "$OUT" | grep -q 'کمپینِ ورودِ ناموفق' && bad "کمپین دوباره هم هشدار داد (سکوتِ ۳۰ دقیقه‌ای کار نکرد)" \
  || ok "تکرارِ همان کمپین ساکت ماند (ضدِ اسپم)"

# ═══════════════════════════════════════════════════════════════════════════
head "۵) «اول شکست، بعد موفقیت» — الگویِ نفوذ"
# ═══════════════════════════════════════════════════════════════════════════
{
  printf '%s vm sshd[1]: Failed password for root from 198.51.100.9 port 5 ssh2\n' "$(ts_auth $((NOW - 400)))"
  printf '%s vm sshd[2]: Accepted password for root from 198.51.100.9 port 6 ssh2\n' "$(ts_auth $((NOW - 300)))"
} >> "$ROOT/auth.log"
OUT="$(run --dry-run)"
printf '%s' "$OUT" | grep -q 'ورودِ موفق از آی‌پی' && ok "هشدارِ «شکست سپس موفقیت» آمد" || bad "هشدارِ نفوذ نیامد"
printf '%s' "$OUT" | grep -q '198.51.100.9' && ok "آی‌پیِ مشکوک در پیام هست" || bad "آی‌پی در پیام نبود"

# ═══════════════════════════════════════════════════════════════════════════
head "۶) خالصهٔ روزانه و --refresh"
# ═══════════════════════════════════════════════════════════════════════════
OUT="$(run --dry-run --digest)"
printf '%s' "$OUT" | grep -q 'خالصهٔ روزانهٔ امنیتِ سرور' && ok "خالصهٔ روزانه ساخته شد" || bad "خالصهٔ روزانه نیامد"
OUT="$(run --dry-run)"
printf '%s' "$OUT" | grep -q 'خالصهٔ روزانه' && bad "خالصه دوباره فرستاده شد ( باید ۲۴ ساعت ساکت باشد)" \
  || ok "خالصه در همان روز تکرار نشد"
printf 'root ALL=(ALL) NOPASSWD: ALL\n' > "$ROOT/etc/sudoers"
OUT="$(run --dry-run --refresh)"
printf '%s' "$OUT" | grep -q 'از نو ثبت شد' && ok "--refresh اثرِ انگشت را تازه کرد" || bad "--refresh کار نکرد"
printf '%s' "$OUT" | grep -q 'فایل‌های حساسِ سرور تغییر کرده' && bad "--refresh باز هم هشدارِ تغییر داد" \
  || ok "با --refresh هشدارِ تغییر نیامد (عمدی)"
OUT="$(run --dry-run)"
printf '%s' "$OUT" | grep -q 'پیامِ تلگرام' && bad "بعد از --refresh هم اسپم کرد" || ok "بعد از --refresh ساکت ماند"

printf '\n\033[1m════════════════════════════════════════════\033[0m\n'
printf '  نتیجه: \033[32m%d موفق\033[0m' "$PASS"
[ "$FAIL" -gt 0 ] && printf ' / \033[31m%d ناموفق\033[0m' "$FAIL"
printf '\n\033[1m════════════════════════════════════════════\033[0m\n'
[ "$FAIL" = "0" ] || exit 1
