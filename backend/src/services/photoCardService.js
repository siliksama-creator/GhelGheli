/**
 * کد را به شکل متعارف در می‌آورد.
 *
 * چرا نسخهٔ جداگانه و نه استفاده از `normalizeCardCode` سرور:
 * آن تابع فقط trim و uppercase می‌کند. اینجا دو مشکل واقعی‌تر داریم که
 * در مسیر عکس بیشتر پیش می‌آید:
 *
 *   ۱. **ارقام فارسی/عربی.** همان باگی که یک بار در ورود با موبایل
 *      گرفتار شد: کیبورد فارسی اندروید «۷» تایپ می‌کند نه «7». کاربری
 *      که کد را از روی کارت می‌خواند و تایپ می‌کند، دقیقاً در همین
 *      دام می‌افتد.
 *
 *   ۲. **خطاهای رونویسی.** کاربر کد را از روی کارت فیزیکی می‌خواند.
 *      O/0 و I/1 روی چاپ تقریباً یکسان‌اند. به‌جای اینکه کاربر را با
 *      «کد نامعتبر» برگردانیم، به شکل متعارف نگاشت می‌کنیم. این یعنی
 *      بانک کد نباید هم O و هم 0 داشته باشد — که در تولیدکنندهٔ کد
 *      رعایت شده (الفبای بدون کاراکترِ مبهم).
 */
function normalizePhotoCode(raw) {
  let s = String(raw || '').trim().toUpperCase();
  // ارقام فارسی (۰۶F0–۰۶F9) و عربی (۰۶۶۰–۰۶۶۹)
  s = s.replace(/[\u06F0-\u06F9]/g, d => String(d.charCodeAt(0) - 0x06F0));
  s = s.replace(/[\u0660-\u0669]/g, d => String(d.charCodeAt(0) - 0x0660));
  // جداکننده‌های تزئینی: کاربر ممکن است با فاصله یا نقطه تایپ کند.
  s = s.replace(/[\s._]+/g, '-');
  return s.replace(/-{2,}/g, '-').replace(/^-|-$/g, '');
}

/**
 * نسخهٔ «تحملِ خطای خواندن» — فقط برای پیدا کردن، هرگز برای ذخیره.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * چرا این از `normalizePhotoCode` جدا شد
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * نسخهٔ قبلی نگاشتِ O→0 و I/L→1 را **داخل** نرمال‌سازی انجام می‌داد. آن
 * زمان بی‌خطر بود چون سیستم خودش کد می‌ساخت و الفبای تولید این حروف را
 * نداشت.
 *
 * حالا مدیر کدهای چاپ‌شده را وارد می‌کند. کدی مثل `QL-2026-0001` معتبر
 * است، ولی نرمال‌سازیِ قبلی آن را به `Q1-2026-0001` تبدیل می‌کرد و کدِ
 * مدیر بی‌سروصدا خراب می‌شد. در تست واقعی دقیقاً همین رخ داد.
 *
 * تفکیک: کدِ اصلی دست‌نخورده ذخیره و نمایش داده می‌شود؛ این تابع فقط
 * کلیدِ جست‌وجو می‌سازد. کاربری که روی کارت `O` می‌بیند و `0` تایپ
 * می‌کند (یا برعکس) همچنان کدش پیدا می‌شود.
 *
 * ⚠️ باید مو‌به‌مو با ستونِ تولیدشدهٔ `code_fold` در مایگریشن ۰۳۵ یکی
 * بماند: `translate(upper(code), 'OIL', '011')`.
 */
function foldPhotoCode(code) {
  return String(code || '').toUpperCase().replace(/[OIL]/g, ch => (ch === 'O' ? '0' : '1'));
}

/**
 * فرمت کد بانک عکسی.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * چرا این‌قدر بازتر از حدس اولیه است
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * نسخهٔ اول فرض می‌کرد سیستم کد می‌سازد، پس می‌شد قالب سفت‌وسختی
 * (`GHP-XXXX-XXXX`) تحمیل کرد. ولی مالک کدها را **خودش وارد می‌کند** و
 * آن کدها روی کارتِ فیزیکی از قبل چاپ شده‌اند — با هر قالبی که چاپخانه
 * یا طراح انتخاب کرده.
 *
 * تحمیلِ قالبِ ما یعنی مالک باید کدهای واقعی‌اش را دور بریزد. پس فقط
 * چیزهایی محدود می‌شوند که واقعاً مشکل‌سازند:
 *
 *   • طول ۴ تا ۶۴: کوتاه‌تر از ۴ قابل حدس زدن است
 *   • فقط حروف لاتین بزرگ، رقم و خط تیره — بعد از نرمال‌سازی
 *
 * حداقل طول از ۶ به ۴ کاهش یافت: بعضی سری‌های چاپی کد کوتاه دارند و
 * ردشان کردن یعنی مالک نمی‌تواند موجودی فعلی‌اش را وارد کند.
 */
function isValidPhotoCode(code) {
  return /^[A-Z0-9-]{4,64}$/.test(code) && /[A-Z0-9]/.test(code);
}

// ── الفبای پیشنهادی برای چاپ‌های آینده ──
//
// دیگر برای تولید استفاده نمی‌شود (مالک کد را خودش وارد می‌کند)، ولی
// به‌عنوان راهنمای طراحی نگه داشته شده و `suggestCode` از آن استفاده
// می‌کند تا اگر مالک خواست نمونه‌ای ببیند.
//
// بدون O، I، L و U: روی کارتِ چاپی O/0 و I/1/L از هم قابل تشخیص نیستند
// و `normalizePhotoCode` هرحال آن‌ها را یکی می‌کند. اگر چاپ بعدی از این
// الفبا استفاده کند، هیچ کاربری کد را اشتباه نمی‌خواند.
const CODE_ALPHABET = '23456789ABCDEFGHJKMNPQRSTVWXYZ';

/**
 * یک کد نمونه پیشنهاد می‌دهد — فقط برای راهنمایی مالک هنگام طراحیِ چاپ.
 *
 * هیچ‌جای مسیرِ ثبت از این استفاده نمی‌کند؛ کدهای واقعی را مدیر وارد
 * می‌کند.
 */
function suggestCode(rng = Math.random) {
  const pick = n => Array.from({ length: n },
    () => CODE_ALPHABET[Math.floor(rng() * CODE_ALPHABET.length)]).join('');
  return `GHP-${pick(4)}-${pick(4)}`;
}

/** فضای کد اگر از الفبای پیشنهادی استفاده شود: ۳۰^۸ ≈ ۶.۶×۱۰¹¹. */
const CODE_SPACE = Math.pow(CODE_ALPHABET.length, 8);

/**
 * امتیاز و جایزهٔ نقدی را به کاربر می‌دهد و کد را قفل می‌کند.
 *
 * ⚠️ باید داخل یک تراکنش باز (`client`) صدا زده شود. تماس‌گیرنده مسئول
 * BEGIN/COMMIT است، چون در مسیر تأیید مدیر چند کار دیگر هم در همان
 * تراکنش انجام می‌شود.
 *
 * @returns {{ points:number, cash:number, cardTypeName:string, imageUrl:string }}
 */
/**
 * کارت را به حساب کاربر می‌گذارد و کد را مصرف می‌کند.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * چرا `design` می‌تواند null باشد
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * از وقتی کدها می‌توانند **از پیش** به یک نوع کارت گره بخورند
 * (`expected_card_type_id`)، دو حالت وجود دارد:
 *
 *   • کدِ بی‌نام + تطبیقِ تصویر → `design` داریم و `cardTypeId` از آن
 *     می‌آید. رفتارِ قدیمی، بدون تغییر.
 *
 *   • کدِ نام‌دار → نوعِ کارت را از خودِ کد می‌دانیم، حتی اگر هیچ طرحِ
 *     تصویری برای آن آپلود نشده باشد. اینجا `design` می‌تواند null
 *     باشد و `cardTypeId` صریح داده می‌شود.
 *
 * `bound_design_id` هم به همین دلیل nullable می‌ماند: وقتی طرحی در کار
 * نبوده، چیزی برای گره زدن نیست و NULL صادقانه‌تر از یک شناسهٔ ساختگی
 * است.
 */
async function creditSubmission(
  client, { userId, codeId, design = null, cardTypeId = null, adminId = null },
) {
  // نوعِ کارت یا از پارامترِ صریح می‌آید یا از طرحِ تطبیق‌خورده.
  const typeId = cardTypeId || design?.card_type_id || null;
  if (!typeId) {
    throw Object.assign(
      new Error('نوع کارت مشخص نیست'), { status: 400 });
  }
  // قفل ردیف کد. `FOR UPDATE` جلوی حالتی را می‌گیرد که دو درخواست هم‌زمان
  // (کاربر دوبار دکمه بزند، یا مدیر هم‌زمان با خودکار تأیید کند) هر دو
  // ببینند کد آزاد است. بدون این، یک کد دو بار امتیاز می‌داد.
  const codeRow = await client.query(
    `SELECT id, status FROM photo_card_codes WHERE id = $1 FOR UPDATE`,
    [codeId],
  );
  if (!codeRow.rows[0]) {
    throw Object.assign(new Error('کد یافت نشد'), { status: 404 });
  }
  const st = codeRow.rows[0].status;
  if (st === 'used') {
    throw Object.assign(new Error('این کد قبلاً استفاده شده است'), { status: 409 });
  }
  if (st === 'voided') {
    throw Object.assign(new Error('این کد باطل شده است'), { status: 409 });
  }

  const typeRow = await client.query(
    `SELECT id, name, point_value, cash_amount, is_active, image_url
       FROM card_types WHERE id = $1`,
    [typeId],
  );
  const type = typeRow.rows[0];
  if (!type) {
    throw Object.assign(new Error('نوع کارت یافت نشد'), { status: 404 });
  }
  if (!type.is_active) {
    throw Object.assign(new Error('نوع این کارت غیرفعال است'), { status: 400 });
  }

  const points = Number(type.point_value || 0);
  const cash = Number(type.cash_amount || 0);

  // کد را به طرحی که تصویرش تطبیق خورد **می‌بندیم**.
  //
  // این تمام هدف این قابلیت است: قبلاً معلوم نبود کدام کد مالِ کدام کارت
  // است، پس کسی که فقط کد را می‌دانست هر کارتی را می‌توانست ادعا کند.
  // حالا کد در لحظهٔ مصرف به یک طرح مشخص گره می‌خورد و در لاگ می‌ماند.
  await client.query(
    `UPDATE photo_card_codes
        SET status = 'used', used_by_user_id = $1, used_at = NOW(),
            bound_design_id = $2, updated_at = NOW()
      WHERE id = $3`,
    [userId, design?.id ?? null, codeId],
  );

  if (points > 0) {
    await client.query(
      `UPDATE users
          SET current_points = current_points + $1,
              lifetime_points = lifetime_points + $1,
              monthly_league_points = monthly_league_points + $1,
              updated_at = NOW()
        WHERE id = $2`,
      [points, userId],
    );
    // کمیسیون ۵٪ معرف — همان قاعدهٔ مسیر ثبت کد، روی همین تراکنش تا اگر
    // چیزی برگشت، امتیازی از هوا ساخته نشود.
    await referrals.payCommission(client, userId, points, 'card');
  }

  // اینونتوری: **عکس مدیر** ثبت می‌شود، نه عکس کاربر.
  //
  // خواستهٔ صریح مالک. منطقی هم هست: عکس کاربر تار و کج است و در گالریِ
  // «کارت‌های من» زشت دیده می‌شود؛ ضمن اینکه نگه‌داشتن عکس شخصی کاربر
  // بار حریم خصوصی دارد بدون اینکه فایده‌ای داشته باشد.
  //
  // چون `card_type_id` همان کاتالوگ فعلی است، این ردیف دقیقاً مثل کارتی
  // که با کد ثبت شده رفتار می‌کند و جوایز پلکانی بدون تغییر کار می‌کنند.
  // ── انتخابِ تصادفیِ رو یا پشت، برای زیباییِ اینونتوری ──
  //
  // خواستهٔ مالک: «وقتی کاربر کارت رو ثبت میکنه بصورت تصادفی پشت و یا
  // روی کارت انتخاب بشه، اینطوری زیبایی اینونتوری بیشتر میشه».
  //
  // ⚠️ چرا انتخاب **اینجا** انجام می‌شود و نه هنگامِ خواندنِ اینونتوری
  //
  // راهِ ساده‌تر این بود که در کوئریِ خواندن `ORDER BY random() LIMIT 1`
  // بزنیم. آن راه دو چیز را می‌شکند:
  //
  //   ۱. کارت هر بار که کاربر صفحه را باز کند ورق می‌خورد. صبح «رو»،
  //      ظهر «پشت». این حسِ خرابی می‌دهد نه زیبایی.
  //   ۲. **کشِ سمتِ گوشی را بی‌اثر می‌کند** — که هدفِ دیگرِ همین جلسه
  //      است. URL متغیر یعنی هر بار دانلودِ دوباره.
  //
  // پس انتخاب یک بار در لحظهٔ ثبت انجام و در `display_design_id` ثابت
  // می‌شود.
  //
  // ── چرا `ORDER BY random()` اینجا بی‌خطر است ──
  //
  // یک کارت حداکثر دو طرح دارد (رو و پشت). حتی اگر روزی ده تا شود،
  // `random()` روی ده ردیفِ ایندکس‌شده هزینه‌ای ندارد. نگرانیِ معمولِ
  // «random() روی جدولِ بزرگ کند است» اینجا مصداق ندارد چون
  // `card_type_id` فیلتر شده.
  //
  // اگر هیچ طرحی نباشد (کدِ نام‌دار بدونِ عکس)، NULL می‌ماند و
  // خواننده به `card_types.image_url` برمی‌گردد — همان رفتارِ قبلی.
  const pick = await client.query(
    `SELECT id FROM photo_card_designs
      WHERE card_type_id = $1 AND is_active = true
      ORDER BY random() LIMIT 1`,
    [typeId],
  );
  const displayDesignId = pick.rows[0]?.id ?? null;

  // ═══════════════════════════════════════════════════════════════════════
  // UPSERT اتمیک — و باگی که جایگزینش شد
  // ═══════════════════════════════════════════════════════════════════════
  //
  // ── الگوی قبلی و چرا خراب بود ──
  //
  //     SELECT id FROM user_card_inventory WHERE user_id=.. AND card_type_id=..
  //     if (found) UPDATE ... else INSERT ...
  //
  // این الگو با دو درخواستِ هم‌زمان روی **اولین** نسخهٔ یک کارت می‌شکند:
  // هر دو تراکنش SELECT می‌زنند و هیچ ردیفی نمی‌بینند، پس هر دو شاخهٔ
  // INSERT را می‌گیرند و دومی به ایندکسِ یکتای `uq_inventory_active`
  // می‌خورد:
  //
  //     ERROR: duplicate key value violates unique constraint
  //            "uq_inventory_active"
  //
  // ⚠️ این **بازتولید شد**، نه حدس زده: دو `psql` هم‌زمان با همان الگو
  //    روی جدولی با همان ایندکس، دقیقاً همین خطا را دادند.
  //
  // نتیجه‌اش برای کاربر: تراکنش برمی‌گردد، کد مصرف‌نشده می‌ماند ولی او
  // پیامِ خطای مبهم می‌بیند و فکر می‌کند کدش سوخته.
  //
  // ── چرا تستِ سرتاسری آن را نگرفت ──
  //
  // `SELECT ... FOR UPDATE` روی ردیفِ کد (بالاتر در همین تابع) عملاً دو
  // درخواست را پشت‌سرِهم می‌کند، چون هر کدام کدِ خودشان را قفل می‌کنند
  // ولی زمان‌بندی‌شان به‌هم می‌ریزد. یعنی باگ **گاهی** رخ می‌دهد، نه
  // همیشه — بدترین نوعِ باگ. تکیه بر آن سریال‌سازیِ تصادفی درست نیست:
  // اتفاقی است، نه تضمین‌شده.
  //
  // ── راه‌حل ──
  //
  // `ON CONFLICT` کارِ اتمیکی است که دیتابیس تضمینش می‌کند. شرطِ ایندکس
  // (`WHERE consumed_in_reward = false`) باید در `ON CONFLICT` هم بیاید،
  // وگرنه Postgres نمی‌داند کدام ایندکسِ جزئی را هدف بگیرد.
  //
  // `COALESCE(display_design_id, EXCLUDED...)`: نسخهٔ دوم طرحِ نمایشی را
  // عوض نمی‌کند. کاربری که پنج نسخه دارد یک خانه با «×۵» می‌بیند؛ اگر
  // هر ثبت دوباره قرعه بیندازد، آن خانه جلوی چشمش ورق می‌خورد و کشِ
  // گوشی هم باطل می‌شود.
  //
  // استثنا: ردیفی که هنوز طرحی ندارد (قبل از مایگریشنِ ۰۴۴ ساخته شده،
  // یا آن موقع طرحی آپلود نشده بود) همین حالا یکی می‌گیرد — پس
  // کارت‌های قدیمی بدونِ backfill جداگانه به‌مرور زیبا می‌شوند.
  await client.query(
    `INSERT INTO user_card_inventory
       (user_id, card_type_id, quantity, consumed_in_reward, display_design_id)
     VALUES($1, $2, 1, false, $3)
     ON CONFLICT (user_id, card_type_id) WHERE consumed_in_reward = false
     DO UPDATE SET
       quantity = user_card_inventory.quantity + 1,
       display_design_id = COALESCE(
         user_card_inventory.display_design_id, EXCLUDED.display_design_id),
       updated_at = NOW()`,
    [userId, typeId, displayDesignId],
  );

  if (cash > 0) {
    // مرجع = شناسهٔ کد. ایندکس یکتای دفتر کل مانع واریز دوم می‌شود حتی
    // اگر این مسیر به هر دلیلی دوبار اجرا شود.
    await walletService.credit(client, {
      userId,
      amount: cash,
      source: 'card_cash',
      referenceType: 'photo_card_codes',
      referenceId: codeId,
      description: `جایزهٔ نقدی کارت «${type.name}» (ثبت با عکس)`,
    });
  }

  return {
    points, cash,
    cardTypeName: type.name,
    cardTypeId: type.id,
    // ── چرا تصویرِ نوعِ کارت جایگزینِ طرح می‌شود ──
    //
    // وقتی کد از پیش گره خورده ولی هیچ طرحِ تصویری آپلود نشده،
    // `design` نداریم. بدونِ این fallback، کاربر بعد از ثبتِ موفق یک
    // کارتِ بدونِ عکس در کلکسیون می‌دید — که شبیهِ خرابی است.
    //
    // `card_types.image_url` همان تصویری است که سیستمِ قدیمیِ «ثبت کد»
    // هم استفاده می‌کند، پس ظاهرِ کارت در هر دو مسیر یکی می‌ماند.
    imageUrl: design?.image_url || type.image_url || null,
    adminId,
  };
}

// ═══════════════════════════════════════════════════════════════════════════
// تصمیمِ ثبت — قلبِ ادغامِ دو سیستم
// ═══════════════════════════════════════════════════════════════════════════
//
// خواستهٔ مالک، کلمه به کلمه:
//
//   «اگه ما کد رو برای کارتی دقیقا در قسمت ادمین ثبت کردیم … وقتی فرد
//    عکس گرفت و کدش رو وارد کرد، اگه کد درست بود و عکس فقط ۲۰٪ هم به
//    عکس مرجع شباهت داشت اتوماتیک تایید بشه.
//    ولی اگه کد صحیحه ولی هیچ عکس بخصوصی براش تعیین نشده و سیستم
//    تشخیص داده کارت شبیهش وجود داره، مثل قبل اتوماتیک ثبت کنه.
//    و اگر زیاد هم شبیه نبود و کد درست بود، مثل قبل بره برای تایید مدیر.»
//
// ───────────────────────────────────────────────────────────────────────────
// چرا آستانه برای کدِ نام‌دار می‌تواند این‌قدر پایین باشد
// ───────────────────────────────────────────────────────────────────────────
//
// چون نقشِ عکس عوض می‌شود.
//
//   • کدِ بی‌نام: عکس باید **هویتِ کارت را تعیین کند**. اگر اشتباه
//     تشخیص دهد، کاربر امتیازِ کارتِ گران‌تری می‌گیرد. پس آستانه باید
//     سخت‌گیر بماند (۰.۵۵ + حاشیه + نسبت).
//
//   • کدِ نام‌دار: هویتِ کارت را **خودِ کد** می‌گوید. عکس فقط باید
//     نشان دهد کاربر واقعاً کارتِ فیزیکی را در دست دارد و عکسِ یک
//     دیوارِ خالی نفرستاده. این کارِ بسیار ساده‌تری است.
//
// بدترین حالتِ سوءاستفاده در حالتِ دوم: کسی که کد را دارد ولی کارت را
// ندارد، عکسی می‌فرستد که ۲۰٪ شبیه است. ولی او **قبلاً کد را دارد** —
// و کد فقط روی همان کارتِ فیزیکی چاپ شده. یعنی یا کارت را دارد، یا
// کسی که کارت را دارد کد را به او داده. در هر دو حالت کارت واقعی است
// و یک بار مصرف می‌شود. ضرری متوجه سیستم نیست.
//
// ───────────────────────────────────────────────────────────────────────────
// چرا حتی ۲۰٪ هم شرط است و صفر نه
// ───────────────────────────────────────────────────────────────────────────
//
// اگر هیچ شرطی نگذاریم، کاربر می‌تواند عکسِ سقفِ اتاق را بفرستد و
// کارت بگیرد. آن‌وقت «ثبت با عکس» عملاً همان «ثبت با کد» می‌شود و
// دلیلِ وجودش از بین می‌رود — کارتِ فیزیکی دیگر لازم نیست، فقط رشتهٔ
// کد کافی است که با پیامک هم منتقل می‌شود.
//
// ۰.۲۰ عمداً پایین است تا عکسِ تار، کج، در نورِ ضعیف و با گوشیِ قدیمی
// هم رد شود، ولی عکسِ چیزی که اصلاً کارت نیست نه.
const BOUND_ACCEPT_SCORE = 0.20;

// ═══════════════════════════════════════════════════════════════════════════
// آستانهٔ کدِ بی‌نام — ۴۰٪
// ═══════════════════════════════════════════════════════════════════════════
//
// خواستهٔ صریح مالک:
//
//   «اگه آنالیز تونست کارت مرتبط با عکسی که کاربر فرستاده رو پیدا کنه و
//    کد توی دیتابیس ذخیره بوده و اگه درصد تطبیق بیش از ۴۰ درصد بود
//    کارت اتوماتیک در اینونتوریش ثبت میشه. اگه درصد کمتر از ۴۰ درصد
//    بود ادمین دستی چک میکنه.»
//
// این جایگزینِ آستانهٔ قبلیِ ۰.۵۵ می‌شود.
//
// ⚠️ ولی شرط‌های «حاشیه» و «نسبت» حذف **نمی‌شوند** و این عمدی است.
//
// دلیل: در مسیرِ بی‌نام، عکس باید **هویتِ کارت را تعیین کند**. اگر دو
// طرح هر دو نمرهٔ ۰.۴۲ بگیرند، ۴۰٪ رد شده ولی موتور واقعاً نمی‌داند
// کدام‌یک است — و انتخابِ تصادفی یعنی کاربر امتیازِ کارتِ اشتباه
// می‌گیرد. اندازه‌گیریِ قبلی نشان داد بدونِ شرطِ نسبت، ۶ تطبیقِ غلط
// روی مجموعهٔ سختِ ۲۴ طرحی رخ می‌دهد.
//
// پس: نمره ≥ ۴۰٪ **و** رتبهٔ اول قاطعانه بهتر از دوم. اگر نمره کافی
// است ولی دو گزینه هم‌تراز‌ند، پرونده به مدیر می‌رود تا خودش انتخاب
// کند — دقیقاً همان چیزی که مالک برای حالتِ «کمتر از ۴۰٪» خواست.
const FREE_ACCEPT_SCORE = 0.40;

/**
 * تصمیم می‌گیرد یک ثبتِ «عکس + کد» چه سرنوشتی دارد.
 *
 * تابعِ **خالص** است: هیچ I/O ندارد و مستقیم تست می‌شود. کلِ منطقِ
 * شاخه‌بندی اینجاست تا در مسیرِ HTTP پخش نشود.
 *
 * @param {object}  a
 * @param {?string} a.expectedTypeId  نوعِ کارتی که کد از پیش به آن گره خورده
 * @param {object}  a.match           خروجی `imageFingerprint.matchAgainst`
 * @param {boolean} a.hasReference    آیا طرحِ فعالی برای `expectedTypeId` هست؟
 * @param {number}  a.boundThreshold  آستانهٔ نرم برای کدِ نام‌دار (۲۰٪)
 * @param {number}  a.freeThreshold   آستانهٔ کدِ بی‌نام (۴۰٪)
 * @returns {{ action, cardTypeId, design, path, reason }}
 *   action = 'approve' | 'review'
 *   path   = 'code_bound' | 'image_match'
 */
function decideSubmission({
  expectedTypeId = null,
  match,
  hasReference = true,
  boundThreshold = BOUND_ACCEPT_SCORE,
  freeThreshold = FREE_ACCEPT_SCORE,
} = {}) {
  const best = match?.design || null;
  const score = Number(match?.score || 0);

  // ── مسیرِ ۱: کد از پیش گره خورده ──
  if (expectedTypeId) {
    // ── آیا اصلاً طرحی برای **این** کارت در کاتالوگ هست؟ ──
    //
    // این سؤال با «آیا موتور چیزی پیدا کرد؟» فرق دارد، و تفاوتش یک
    // باگِ واقعی ساخت که فقط تستِ زنده گرفت:
    //
    // موتور همیشه بهترینِ **کلِ کاتالوگ** را برمی‌گرداند. اگر مدیر
    // برای کارتِ «بی‌عکس» هزار کد ثبت کرده ولی طرحش را آپلود نکرده،
    // موتور طرحِ یک کارتِ **دیگر** را به‌عنوان نزدیک‌ترین می‌دهد.
    //
    // نتیجه: `matchesExpected` می‌شد false و اگر آن نمره بالای ۰.۵۵
    // بود، پرونده با علتِ «type_mismatch» به صف می‌رفت — برای کارتی
    // که اصلاً عکسِ مرجعی ندارد و مقایسه بی‌معنی است.
    //
    // پس اول می‌پرسیم: آیا مرجعی برای مقایسه وجود دارد؟ اگر نه، هیچ
    // قضاوتِ تصویری ممکن نیست و کد حرفِ آخر را می‌زند.
    //
    // ⚠️ `hasReference` از **فراخوان** می‌آید، نه از `match.ranked`.
    //    `ranked` فقط سه تای اول را دارد؛ اگر کاتالوگ ۵۰ طرح داشته
    //    باشد و طرحِ این کارت رتبهٔ دهم شود، `ranked` آن را نشان
    //    نمی‌دهد و ما اشتباهاً «مرجعی نیست» نتیجه می‌گرفتیم.
    //    مسیرِ HTTP کلِ کاتالوگ را در دست دارد و صریح جواب می‌دهد.
    // آیا بهترین تطبیق **همان** کارتی است که انتظار داشتیم؟
    //
    // این ظرافت مهم است: اگر کاربر عکسِ کارتِ B را با کدِ کارتِ A
    // بفرستد و موتور با اطمینان B را بشناسد، نباید بی‌سروصدا A را
    // بدهیم. کد می‌گوید A، عکس می‌گوید B — این تناقض است و آدم باید
    // ببیندش.
    const matchesExpected = best && best.card_type_id === expectedTypeId;

    // ⚠️ چرا وقتی `best` نداریم آستانه اصلاً بررسی نمی‌شود
    //
    // اگر هیچ طرحی در کاتالوگ نباشد (یا همه غیرفعال باشند)، موتور
    // `score = 0` برمی‌گرداند — نه چون عکس بد است، بلکه چون **چیزی
    // برای مقایسه وجود ندارد**.
    //
    // نسخهٔ اول همان صفر را با آستانهٔ ۰.۲۰ می‌سنجید و رد می‌کرد. یعنی
    // مدیری که ۱۰۰۰ کد برای کارتی ثبت کرده ولی هنوز عکسِ مرجعش را
    // آپلود نکرده، **همهٔ** ثبت‌ها را در صف بررسی می‌دید — دقیقاً
    // برعکسِ هدفِ این قابلیت. تستِ «بدونِ هیچ طرحِ مرجع» همین را گرفت.
    //
    // منطق: نمرهٔ صفر در نبودِ مرجع، «شواهدی علیه کاربر» نیست؛ فقط
    // «شواهدی نیست». و کد به‌تنهایی مدرکِ کافی است.
    if (!best || !hasReference) {
      return {
        action: 'approve',
        cardTypeId: expectedTypeId,
        design: null,
        path: 'code_bound',
        reason: null,
      };
    }

    if (score >= boundThreshold && matchesExpected) {
      // تصویر همان کارتی را نشان می‌دهد که کد می‌گوید.
      return {
        action: 'approve',
        cardTypeId: expectedTypeId,
        design: best,
        path: 'code_bound',
        reason: null,
      };
    }

    // ── تناقض: عکس کارتِ دیگری را نشان می‌دهد ──
    //
    // شرط دو بخش دارد و هر دو لازم‌اند:
    //
    //   • نمره از آستانهٔ نرم گذشته — یعنی عکس واقعاً یک کارت است، نه
    //     نویز. اگر زیرِ آستانه باشد، «کیفیتِ پایین» توضیحِ محتمل‌تری
    //     است تا «کارتِ اشتباه».
    //
    //   • موتور قاطع است — یعنی رتبهٔ اول محسوس بهتر از دوم است. اگر
    //     دو گزینه هم‌تراز باشند، موتور در واقع نمی‌داند کدام است و
    //     ادعای «کارتِ دیگری است» بی‌پایه می‌شود.
    //
    // ⚠️ آستانهٔ ثابتِ ۰.۵۵ که اینجا بود اشتباه بود: عکسی که از زاویهٔ
    //    کمی متفاوت گرفته شده نمره‌اش می‌افتد ولی هنوز واضح کارتِ B
    //    است. آن حالت با پیامِ «کیفیت پایین» به کاربر می‌رفت — پیامی
    //    که او را به گرفتنِ عکسِ بهتر تشویق می‌کرد، در حالی که مشکل
    //    اصلاً کیفیت نبود و هر بار همان نتیجه را می‌گرفت.
    if (matchesExpected === false && best
        && score >= boundThreshold && match?.decisive !== false) {
      return {
        action: 'review',
        cardTypeId: expectedTypeId,
        design: best,
        path: 'code_bound',
        reason: 'type_mismatch',
      };
    }

    // شباهت حتی به ۲۰٪ هم نرسید → احتمالاً عکسِ کارت نیست.
    return {
      action: 'review',
      cardTypeId: expectedTypeId,
      design: best,
      path: 'code_bound',
      reason: 'low_confidence',
    };
  }

  // ── مسیرِ ۲: کدِ بی‌نام — تشخیص کاملاً بر عهدهٔ تصویر ──
  //
  // آستانه ۴۰٪ است (خواستهٔ مالک)، ولی شرطِ «قاطعیت» هم لازم است:
  // موتور باید بتواند بین گزینه‌ها **انتخاب** کند، نه فقط شبیه بودن را
  // تشخیص دهد. `decisive` را خودِ موتور بر پایهٔ حاشیه و نسبتِ رتبهٔ
  // اول به دوم تعیین می‌کند.
  if (best && score >= freeThreshold && match?.decisive !== false) {
    return {
      action: 'approve',
      cardTypeId: best.card_type_id,
      design: best,
      path: 'image_match',
      reason: null,
    };
  }
  return {
    action: 'review',
    cardTypeId: null,
    design: best,
    path: 'image_match',
    // تفکیکِ علت برای مدیر: «اصلاً چیزی شبیهش نیست» با «شبیه هست ولی
    // مطمئن نیستم کدام» دو کارِ متفاوت می‌طلبد.
    reason: !best || score < 0.15 ? 'image_unknown'
      : (match?.decisive === false ? 'ambiguous' : 'low_confidence'),
  };
}

