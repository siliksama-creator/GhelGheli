/**
 * OCR token extraction and text-token similarity for photo-card matching.
 * Kept separate from the calibrated pixel fingerprint maths so optional
 * Tesseract process/file handling cannot obscure the hot similarity code.
 */
const sharp = require('sharp');

// ═══════════════════════════════════════════════════════════════════════════
// خواندنِ متنِ روی کارت — قطعی‌ترین سیگنال
// ═══════════════════════════════════════════════════════════════════════════
//
// ── چرا این لازم شد ──
//
// خواستهٔ صریح مالک: «کاش سیستمی که شباهت عکس رو داره پیدا میکنه، متن‌های
// روی عکس رو زمان آپلود ادمین و آپلود کاربر سعی کنه بخونه که اینطوری
// درصد اشتباه کمتر شه».
//
// اندازه‌گیری روی عکسِ واقعیِ یک کاربر (کارتِ دمبله روی میزِ چوبی):
//
//     مرجع      شباهتِ تصویری
//     Hakimi-B      ۰.۵۳۳   ← برنده شد!
//     Dembélé-B     ۰.۵۰۰
//     Hakimi-A      ۰.۳۶۷
//     Dembélé-A     ۰.۳۱۵
//
// حاشیه فقط ۰.۰۳۳ بود و **کارتِ اشتباه** برنده شد. علتش سه چیزِ هم‌زمان:
// قالبِ مشترکِ کارت‌ها، میزِ چوبی که ۴۰٪ کادر را گرفته بود، و رنگِ طلاییِ
// مشترکِ هر دو طرح.
//
// همان عکس با OCR:
//
//     Hakimi   ۰.۰۰۰
//     Dembélé  ۱.۰۰۰   ← قاطع
//
// ── چرا OCR اینجا جواب می‌دهد ولی برای **کد** نداد ──
//
// قبلاً امتحان شد که کدِ چاپ‌شده را از عکس بخوانیم و شکست خورد: کد با
// فونتِ ریز روی لبهٔ کارت است و حتی در کیفیت عالی درست خوانده نمی‌شد.
//
// نامِ بازیکن کاملاً فرق دارد: با حروفِ درشتِ چند سانتی‌متری وسطِ کارت
// چاپ می‌شود. حتی روی عکسِ تارِ گوشی هم خوانده می‌شود.
//
// ── تحملِ خطا ──
//
// خروجیِ خام پر از نویز است (`~EMBELE`, `PR AN oc.`). دو تدبیر:
//
//   ۱. فقط رشته‌های ≥۴ حرف نگه داشته می‌شوند — تکه‌های تصادفی حذف
//      می‌شوند و نامِ بازیکن می‌ماند.
//   ۲. تطبیق با تحملِ زیررشته: `EMBELE` با `DEMBELE` یکی شمرده می‌شود.
//      حرفِ اول اغلب در لبهٔ برش یا سایه گم می‌شود.
//
// ── چرا شکست کاملاً بی‌صداست ──
//
// اگر tesseract نصب نباشد یا کرش کند، آرایهٔ خالی برمی‌گردد و موتور
// دقیقاً مثلِ قبل کار می‌کند. این قابلیت **افزودنی** است نه وابستگیِ
// حیاتی؛ سرورِ بدونِ tesseract نباید ثبتِ کارت را از کار بیندازد.
const { execFile } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

/** آیا tesseract در دسترس است؟ یک بار سنجیده و کش می‌شود. */
let _ocrReady = null;

function ocrAvailable() {
  if (_ocrReady !== null) return Promise.resolve(_ocrReady);
  return new Promise((resolve) => {
    execFile('tesseract', ['--version'], { timeout: 5000 }, (err) => {
      _ocrReady = !err;
      if (!_ocrReady) {
        console.warn('[fingerprint] tesseract نصب نیست — تطبیقِ متنی خاموش است');
      }
      resolve(_ocrReady);
    });
  });
}

/** آیا بستهٔ فارسی (fas) نصب است؟ یک بار سنجیده و کش می‌شود. */
let _fasReady = null;

function fasAvailable() {
  if (_ocrReady === false) return Promise.resolve(false);
  if (_fasReady !== null) return Promise.resolve(_fasReady);
  return new Promise((resolve) => {
    execFile('tesseract', ['--list-langs'], { timeout: 5000 }, (err, stdout) => {
      _fasReady = !err
        && String(stdout || '').split('\n').some((l) => l.trim() === 'fas');
      resolve(_fasReady);
    });
  });
}

/**
 * متنِ لاتینِ روی تصویر را می‌خواند و به توکن‌های معنادار می‌شکند.
 *
 * @returns {Promise<string[]>} توکن‌های یکتا، یا [] اگر چیزی خوانده نشد
 */
async function readText(buf) {
  if (process.env.GG_DISABLE_OCR === '1') return [];
  if (!(await ocrAvailable())) return [];

  // ── زبان‌ها: فارسی فقط وقتی اضافه می‌شود که واقعاً نصب باشد ──
  //
  // درخواستِ `-l eng+fas` روی سروری که fas ندارد کلِ tesseract را خطا
  // می‌دهد و **هر دو** زبان از کار می‌افتد — نه فقط فارسی. پس زبانِ
  // فارسی شرطِ حضورِ واقعیِ بستهٔ `tesseract-ocr-fas` است. با فعال‌شدن
  // فارسی، حروفِ الفبای فارسی هم به whitelist اضافه می‌شود؛ وگرنه
  // tesseract آن‌ها را «خارج از الفبا» می‌شمارد و متنِ فارسی باز هم
  // خوانده نمی‌شود.
  const HAS_FAS = await fasAvailable();
  const LANGS = HAS_FAS ? 'eng+fas' : 'eng';
  const WHITELIST = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'
    + (HAS_FAS ? 'ابپتجچحخدذرزسشصضطظعغفقکگلمنوهی' : '');

  // ══════════════════════════════════════════════════════════════════════
  // OCR روی **چند ناحیه**، نه فقط کلِ تصویر
  // ══════════════════════════════════════════════════════════════════════
  //
  // ── باگی که این را لازم کرد ──
  //
  // مالک اسکرین‌شات فرستاد: عکسِ کارتِ Hakimi، حدسِ سیستم «Haaland».
  //
  // بررسیِ تصاویر نشان داد پشتِ هر دو کارت **تقریباً یکسان طراحی شده**:
  // پیراهنِ قرمز، بازیکن از پشت، همان ژست، همان چیدمانِ طلایی، همان
  // استادیوم. تنها تفاوتِ واقعی نامِ چاپ‌شده است.
  //
  // ولی OCR روی پشتِ Haaland **هیچ چیزی نمی‌خواند** با اینکه «HAALAND»
  // با حروفِ درشتِ طلایی نوشته شده. سه پیش‌پردازشِ متفاوت امتحان شد
  // (normalise، threshold، negate) و هر سه صفر دادند.
  //
  // علت: وقتی کلِ کارت به ۱۴۰۰ پیکسل کوچک می‌شود، نوارِ نامِ بازیکن
  // فقط ~۱۵٪ ارتفاع را می‌گیرد و در انبوهِ جزئیاتِ پس‌زمینه (شعله،
  // استادیوم، پرچم) گم می‌شود. tesseract با `--psm 11` دنبالِ متنِ
  // پراکنده می‌گردد و آن ناحیه را نادیده می‌گیرد.
  //
  // ── راه‌حل: نوارِ پایین جداگانه هم اسکن می‌شود ──
  //
  // نامِ بازیکن روی کارتِ فوتبالی تقریباً همیشه در نیمهٔ پایین است.
  // وقتی همان نوار به‌تنهایی به ۱۶۰۰ پیکسل بزرگ شود، حروف چند برابر
  // بزرگ‌تر می‌شوند و tesseract می‌بیندشان.
  //
  // اندازه‌گیری روی همان کارت‌ها:
  //
  //     پشتِ Haaland — کلِ تصویر : []
  //     پشتِ Haaland — نوارِ ۷۰–۱۰۰٪ : ["PNORWAY"]   ← پیدا شد
  //     پشتِ Hakimi  — نوارِ ۵۵–۹۵٪  : ["WORLD","MOROCCO"]
  //
  // ⚠️ هزینه: سه اجرای tesseract به‌جای یکی (~۸۵۰ms → ~۲.۲s). روی
  //    آپلودِ ادمین قابل قبول است چون یک‌بار در عمرِ کارت رخ می‌دهد، و
  //    برای کاربر هم لودینگِ مرحله‌ای همین را نشان می‌دهد.
  //
  // ⚠️ ناحیه‌ها **هم‌پوشان**اند (۵۵–۹۵ و ۷۰–۱۰۰): متنی که دقیقاً روی
  //    مرز بیفتد در یکی از دو ناحیه کامل دیده می‌شود.
  const REGIONS = [
    null,           // کلِ تصویر — برای متنِ بالا و آمارِ کناری
    [0.55, 0.95],   // نیمهٔ پایین — جایی که نامِ بازیکن است
    [0.70, 1.00],   // نوارِ انتهایی — نامِ تیم و کشور
  ];
  const stamp = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
  const temps = [];
  try {
    const meta = await sharp(buf, { failOn: 'none' }).metadata();
    const H = meta.height || 0;
    let raw = '';

    for (let i = 0; i < REGIONS.length; i++) {
      const region = REGIONS[i];
      // ناحیهٔ نامعتبر روی تصویرِ خیلی کوتاه رد می‌شود.
      if (region && H < 200) continue;

      const tmpI = path.join(os.tmpdir(), `gg-ocr-${stamp}-${i}.png`);
      temps.push(tmpI);
      try {
        let pipe = sharp(buf, { failOn: 'none' }).rotate().removeAlpha();
        if (region) {
          const top = Math.round(H * region[0]);
          const h = Math.min(H - top, Math.round(H * (region[1] - region[0])));
          if (h < 40) continue;
          pipe = pipe.extract({ left: 0, top, width: meta.width, height: h });
        }
        // ── چرا این پیش‌پردازش ──
        //
        // خاکستری + بزرگ‌نمایی + نرمال‌سازیِ کنتراست + تیزی. روی عکسِ
        // گوشی این ترکیب تفاوتِ «هیچ» و «DEMBELE» را می‌سازد:
        // tesseract روی متنِ کم‌کنتراستِ فشرده‌شده عملاً کور است.
        //
        // نوارها به ۱۶۰۰ بزرگ می‌شوند نه ۱۴۰۰: چون ارتفاعشان کمتر است،
        // همان عرض یعنی حروفِ درشت‌تر.
        await pipe
          .greyscale()
          .resize(region ? 1600 : 1400, null,
            { fit: 'inside', withoutEnlargement: false })
          .normalise()
          .sharpen()
          .png()
          .toFile(tmpI);

        // eslint-disable-next-line no-await-in-loop
        const part = await new Promise((resolve) => {
          execFile('tesseract',
            [tmpI, '-', '--psm', '11', '-l', LANGS, '-c',
              `tessedit_char_whitelist=${WHITELIST}`],
            { timeout: 20000, maxBuffer: 1 << 20 },
            (err, stdout) => resolve(err ? '' : String(stdout || '')));
        });
        raw += `\n${part}`;
      } catch {
        // یک ناحیهٔ خراب نباید بقیه را از کار بیندازد.
      }
    }

    // ══════════════════════════════════════════════════════════════════
    // دو جنسِ توکن: کلمه و عدد
    // ══════════════════════════════════════════════════════════════════
    //
    // ── چرا عدد جدا شمرده می‌شود ──
    //
    // نسخهٔ اول فقط `[A-Z]{4,}` را نگه می‌داشت و **همهٔ عددها را دور
    // می‌ریخت**. برای جدا کردنِ «رونالدو» از «مسی» کافی بود، ولی برای
    // سه کارتِ رونالدو با شماره‌های ۷ و ۹ و ۱۷ هیچ کمکی نمی‌کرد:
    //
    //     رونالدو-۷   → ["RONALDO","PORTUGAL"]
    //     رونالدو-۹   → ["RONALDO","PORTUGAL"]   ← دقیقاً یکی!
    //     رونالدو-۱۷  → ["RONALDO","PORTUGAL"]
    //
    // نتیجه: حاشیهٔ ۰.۰۰۲ بین سه کارت — یعنی انتخاب عملاً تصادفی.
    //
    // مالک صریح گفت «اعداد و کلماتی که روی عکس هست»، و شمارهٔ پیراهن
    // دقیقاً همان چیزی است که دو کارتِ یک بازیکن را از هم جدا می‌کند.
    //
    // ── چرا آستانهٔ عدد ۱ رقم است ولی کلمه ۴ حرف ──
    //
    // نویزِ OCR روی حروف زیاد است (`ti`, `~~`, `Ui`) پس آستانهٔ بلند
    // لازم است. ولی عددها روی کارت کم‌اند و معنادار: شمارهٔ پیراهن،
    // سالِ تولد، آمار. حتی «۷» تک‌رقمی اطلاعاتِ واقعی دارد.
    //
    // ⚠️ عددهای بلندتر از ۴ رقم رد می‌شوند: آن‌ها معمولاً کدِ سریال یا
    //    نویزِ به‌هم‌چسبیدهٔ OCR اند، نه شمارهٔ بازیکن.
    const words = new Set();
    const digits = new Set();
    const up = raw.toUpperCase();
    for (const t of (up.match(/[A-Z]{4,}/g) || [])) {
      if (words.size < 40) words.add(t);
    }
    // ── کلمه‌های فارسی ──
    //
    // کارت (یا پشتِ کارت) ممکن است نامِ فارسی داشته باشد. قبل از این
    // تغییر حتی با نصبِ `tesseract-ocr-fas` هم خروجیِ فارسی در `raw`
    // بود ولی ریگکسِ [A-Z]{4,} همهٔ آن را دور می‌ریخت — سیگنالِ متنی
    // برای نام‌های فارسی عملاً صفر بود و همین یکی از دلایلِ «حاشیهٔ
    // کمِ تشخیص کارت‌های هم‌طرح» بود.
    //
    // محدودهٔ U+0600–U+06FF حرف‌های عربی/فارسی را پوشش می‌دهد؛ آستانهٔ
    // ۴ حرف همان قاعدهٔ لاتین است (نویزِ کوتاه حذف می‌شود). بعد از
    // کلمه‌های لاتین اضافه می‌شوند تا هر دو جا داشته باشند؛ سقفِ ۶۰
    // فقط وقتی فارسی هم باشد باز می‌شود و حالتِ لاتینِ خالص دست
    // نمی‌خورد. تطبیق مجموعه‌ای و بی‌فرهنگ است: `textSimilarity`
    // فارسی را با همان تحملِ زیررشته می‌سنجد که برای
    // `EMBELE`/`DEMBELE` ساخته شده.
    for (const t of (raw.match(/[\u0600-\u06FF]{4,}/g) || [])) {
      if (words.size < 60) words.add(t);
    }
    for (const t of (up.match(/[0-9]{1,4}/g) || [])) {
      // صفرهای ابتدایی حذف می‌شوند تا «07» و «7» یکی شمرده شوند.
      const n = String(Number(t));
      if (n !== 'NaN' && digits.size < 20) digits.add(`#${n}`);
    }

    // ══════════════════════════════════════════════════════════════════
    // عدد فقط وقتی معتبر است که **کلمه‌ای هم** خوانده شده باشد
    // ══════════════════════════════════════════════════════════════════
    //
    // ── رگرسیونی که بنچ گرفت ──
    //
    // افزودنِ عدد به تنهایی، تطبیقِ غلطِ تأییدشده را از صفر به ۲ برد.
    // نمونهٔ دقیق:
    //
    //     d16 → d17 تأیید شد (۰.۶۶۴)
    //     متنِ عکسِ کاربر: []      متنِ مرجعِ d17: ["#177"]
    //
    // آن `#177` نویز بود: OCR رقمِ «۱۷» را روی پس‌زمینهٔ شلوغ سه بار
    // دید. ولی مهم‌تر از خودِ نویز، **نامتقارنی** است که ساخت.
    //
    // وقتی بعضی طرح‌ها عدد دارند و بعضی نه، جفت‌های مختلف با فرمول‌های
    // مختلف سنجیده می‌شوند: یکی `combinedSimilarity` با جابه‌جایی
    // می‌گیرد و دیگری فقط تصویر. رتبه‌بندی آن‌وقت بی‌معنی می‌شود، چون
    // اعداد قابل مقایسه نیستند.
    //
    // اندازه‌گیری: از ۲۴ طرحِ آزمایشی فقط ۱۳ تا عدد خوانده شد — یعنی
    // نیمی از کاتالوگ با معیارِ متفاوت سنجیده می‌شد.
    //
    // ── چرا این شرط مسئله را حل می‌کند ──
    //
    // عددِ تنها روی کارتِ واقعی تقریباً همیشه نویز است: کارتِ واقعی
    // نامِ بازیکن را هم دارد و اگر OCR آن را نخوانده، یعنی کیفیت
    // آن‌قدر بد بوده که به عددش هم نمی‌شود اعتماد کرد.
    //
    // بالعکس وقتی نام خوانده شده، عدد هم قابل اتکاست — و همان‌جاست که
    // برای جدا کردنِ «رونالدو ۷» از «رونالدو ۱۷» لازمش داریم.
    // پیشوندِ `#` عمدی است: عدد و کلمه نباید با هم برخورد کنند. بدونِ
    // آن `includes` در `textSimilarity` می‌توانست «7» را داخل
    // «PORTUGAL7» پیدا کند و شباهتِ کاذب بسازد.
    if (!words.size) return [];
    return [...words, ...digits];
  } catch {
    return [];
  } finally {
    for (const t of temps) fs.promises.unlink(t).catch(() => {});
  }
}

/**
 * شباهتِ دو مجموعه توکنِ متنی.
 *
 * @returns {?number} عددی در [۰,۱]، یا null اگر یکی از دو طرف متنی نداشت
 *   — که با «صفر» فرق دارد: «نخواندم» در برابر «خواندم و فرق داشت».
 */
function textSimilarity(a, b) {
  if (!Array.isArray(a) || !Array.isArray(b) || !a.length || !b.length) {
    return null;
  }

  // ── چرا عدد و کلمه جدا سنجیده می‌شوند ──
  //
  // سه کارتِ یک بازیکن با شماره‌های متفاوت **کلماتِ کاملاً یکسان**
  // دارند (RONALDO، PORTUGAL). اگر همه با هم میانگین گرفته شوند، تفاوتِ
  // شماره در انبوهِ کلماتِ مشترک گم می‌شود.
  //
  // اندازه‌گیری روی سه کارتِ رونالدو با شمارهٔ ۷/۹/۱۷:
  //
  //     میانگینِ ساده  → حاشیهٔ ۰.۰۰۲  (انتخاب عملاً تصادفی)
  //     عدد جدا        → حاشیهٔ ۰.۲۸۰
  //
  // شماره روی کارت **یکتاست**؛ کلمات مشترک‌اند. پس وقتی هر دو طرف عدد
  // دارند، عدد حرفِ اصلی را می‌زند.
  const isNum = (t) => t.charCodeAt(0) === 35;      // '#'
  const wA = a.filter(t => !isNum(t));
  const wB = b.filter(t => !isNum(t));
  const nA = a.filter(isNum);
  const nB = b.filter(isNum);

  const overlap = (xs, ys, fuzzy) => {
    if (!xs.length || !ys.length) return null;
    let hit = 0;
    for (const x of xs) {
      for (const y of ys) {
        // تحملِ زیررشته فقط برای کلمات: حرفِ اول اغلب در لبهٔ برش یا
        // سایه گم می‌شود، پس `EMBELE` باید با `DEMBELE` یکی شمرده شود.
        //
        // ⚠️ برای عدد **عمداً** خاموش است: «۷» زیررشتهٔ «۱۷» است ولی
        //    دو کارتِ کاملاً متفاوت‌اند. تحملِ زیررشته اینجا دقیقاً
        //    همان تمایزی را از بین می‌برد که برایش اضافه شده.
        const same = fuzzy
          ? (x === y || x.includes(y) || y.includes(x))
          : x === y;
        if (same) { hit += 1; break; }
      }
    }
    return hit / Math.min(xs.length, ys.length);
  };

  const wordSim = overlap(wA, wB, true);
  const numSim = overlap(nA, nB, false);

  if (numSim === null) return wordSim;      // یکی از دو طرف عددی نداشت
  if (wordSim === null) return numSim;

  // ── وزنِ ۵۵٪ برای عدد ──
  //
  // بیشتر از کلمه، چون شماره یکتاست و کلمات (WORLDCUP، RIGHT، نامِ
  // تیم) بین کارت‌ها مشترک‌اند. ولی نه آن‌قدر بیشتر که یک OCRِ غلطِ
  // عدد بتواند نامِ درست را نادیده بگیرد.
  return 0.45 * wordSim + 0.55 * numSim;
}


