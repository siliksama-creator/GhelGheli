// سیستم لول‌بندیِ دائمیِ بازیکن.
//
// ═══════════════════════════════════════════════════════════════════════════
// چه چیزی را می‌شمارد و چرا
// ═══════════════════════════════════════════════════════════════════════════
//
// درخواست مالک: «یک سیستم لول بندی هم در قسمت بازی ها اضافه کن که این
// سیستم مجموع exp دریافتی از همه بازی های آنلاین با کاربر واقعی رو نشون
// بده. و کاربر لول آپ بشه و چندتا لول اول راحت باشه ولی بعد خیلی بیشتر
// طول بکشه و ماکسیمم لول ۱۰۰ هستش ولی رسیدن بهش خیلی سخت و کاری طولانی
// باشه».
//
// سه قید که همه‌جا رعایت شده‌اند:
//
//   ۱. **فقط بازیِ آنلاین با آدمِ واقعی.** بازی مقابل ربات فوری شروع
//      می‌شود و در چند ثانیه تمام؛ اگر XP می‌داد، لول معنایش را از
//      دست می‌داد. همان قانونی که برای گذر نبرد هم هست.
//   ۲. **دائمی، بدون فصل.** «مجموعِ همهٔ بازی‌ها» یعنی هرگز صفر نشود.
//   ۳. **بدون سقفِ روزانه.** گذر نبرد سقف دارد تا کسی یک‌شبه تمامش
//      نکند؛ ولی لول یک نمایشِ افتخار است، نه یک جایزه. سقف گذاشتن
//      یعنی بازیکنِ پرکار بعد از بازیِ ششم پیشرفتی نبیند.
//
// ═══════════════════════════════════════════════════════════════════════════
// چرا این با XP گذر نبرد قاطی نشد
// ═══════════════════════════════════════════════════════════════════════════
//
// گذر نبرد از قبل XP دارد، ولی فصلی است، سقفِ روزانه دارد، و از منابعِ
// غیربازی (چرخش، دعوت، ورودِ روزانه) هم تغذیه می‌شود. هر سه با آنچه
// مالک خواست در تضادند. جزئیات در migrations/033_player_level.sql.

// ═══════════════════════════════════════════════════════════════════════════
// چرا `pool` تنبل (lazy) بارگذاری می‌شود
// ═══════════════════════════════════════════════════════════════════════════
//
// منحنیِ لول یک تابعِ ریاضیِ محض است و باید بدون دیتابیس قابل تست
// باشد — تستِ منحنی نباید به یک Postgresِ در حالِ اجرا نیاز داشته
// باشد، وگرنه در CI و روی ماشینِ توسعه‌دهنده اجرا نمی‌شود.
//
// با `require` در بالای فایل، صرفِ import کردنِ این ماژول تلاش
// می‌کرد به دیتابیس وصل شود. حالا فقط توابعی که واقعاً کوئری می‌زنند
// آن را می‌خواهند.
let _pool = null;
function db() {
  _pool ??= require('../db').pool;
  return _pool;
}

// ═══════════════════════════════════════════════════════════════════════════
// منحنیِ لول
// ═══════════════════════════════════════════════════════════════════════════
//
// خواستهٔ مالک: «چندتا لول اول راحت باشه ولی بعد خیلی بیشتر طول بکشه».
//
// فرمولِ نیازِ لول n به n+1:
//
//     BASE + LIN·n + BASE·(min(n, KNEE) − 1)^EXP   [+ (n − KNEE)·TAIL]
//
// سه جمله، هر کدام یک کار:
//
//   • `BASE + LIN·n` — رشدِ خطیِ ملایم، تا لول‌های پایین هم صفر نباشند.
//   • `BASE·(n−1)^EXP` — رشدِ نمایی، موتورِ اصلیِ «بعد خیلی بیشتر».
//   • `(n−KNEE)·TAIL` — بعد از لول ۳۵ نمایی **متوقف** و خطیِ سنگین
//     می‌شود.
//
// ═══════════════════════════════════════════════════════════════════════════
// چرا «زانو» (KNEE) لازم بود — یک اشتباهِ طراحی که با محاسبه پیدا شد
// ═══════════════════════════════════════════════════════════════════════════
//
// نسخهٔ اول فقط نمایی بود (بدون KNEE). محاسبهٔ زمانِ رسیدن نشان داد:
//
//     لول ۱۰۰ برای فعال‌ترین بازیکنِ ممکن ≈ ۴۰ سال
//
// این «سخت» نیست، **غیرممکن** است — و یک سقفِ غیرممکن انگیزه نمی‌سازد،
// از بین می‌برد. با زانو در ۳۵، رشد از آنجا به بعد خطی می‌شود و عددها
// معقول:
//
//     بازیکن گاه‌به‌گاه (۵ بازی/روز):  لول ۱۰ در ۴۵ روز
//     بازیکن معمولی    (۱۲ بازی/روز): لول ۲۵ در ۷ ماه
//     بازیکن پرکار     (۲۵ بازی/روز): لول ۵۰ در ۱۹ ماه
//     بازیکن حرفه‌ای   (۴۵ بازی/روز): لول ۱۰۰ در ~۴.۶ سال
//
// یعنی لول ۱۰۰ همچنان یک هدفِ نمادین است که تقریباً هیچ‌کس نمی‌رسد، ولی
// **در افقِ دید** هست. این تفاوتِ «سخت» و «بی‌معنی» است.
// ═══════════════════════════════════════════════════════════════════════════
// چرا لول از **صفر** شروع می‌شود و نه یک
// ═══════════════════════════════════════════════════════════════════════════
//
// مالک نمونهٔ نمایش را صریح داد: «در قسمت بازی ها هم Level 0».
//
// یعنی کاربرِ تازه‌وارد `Level 0` می‌بیند، نه `Level 1`. این با
// قراردادِ رایجِ بازی‌ها هم می‌خواند (لولِ صفر = هنوز شروع نکرده) و
// اولین لول‌آپ را به یک رخدادِ واقعی تبدیل می‌کند: ۰ → ۱ حس می‌شود،
// ۱ → ۲ نه.
//
// نتیجهٔ عملی: سقف ۱۰۰ یعنی ۱۰۱ حالتِ ممکن (۰ تا ۱۰۰).
const MIN_LEVEL = 0;
const MAX_LEVEL = 100;
// ═══════════════════════════════════════════════════════════════════════════
// چرا BASE از ۵۵ به ۳۵ کم شد
// ═══════════════════════════════════════════════════════════════════════════
//
// تستِ «بعد از ۳ بازی دست‌کم لول ۱» شکست خورد: با BASE=55 اولین لول
// ۷۵ XP می‌خواست، یعنی چهار بازی.
//
// این مهم‌تر از آن است که به‌نظر می‌رسد. کاربرِ تازه‌وارد در همان
// نشستِ اولش باید **یک بار** لول‌آپ را ببیند، وگرنه نمی‌فهمد این
// سیستم اصلاً وجود دارد. سه بازی تقریباً همان چیزی است که یک نفر در
// اولین باز کردنِ اپ انجام می‌دهد.
//
// اثرش روی بالای منحنی ناچیز است چون آنجا جملهٔ نمایی و TAIL غالب‌اند
// — با محاسبه تأیید شد: زمانِ رسیدن به ۱۰۰ برای بازیکنِ حرفه‌ای عملاً
// تغییر نکرد.
const BASE = 35;
const LIN = 20;
const EXP = 1.5;
const KNEE = 35;
const TAIL = 520;

/** XP لازم برای رفتن از لول [n] به [n+1]. */
function xpForLevel(n) {
  if (n < 1) return 0;
  const e = Math.min(n, KNEE);
  let v = BASE + LIN * n + BASE * Math.pow(e - 1, EXP);
  if (n > KNEE) v += (n - KNEE) * TAIL;
  return Math.round(v);
}

// ═══════════════════════════════════════════════════════════════════════════
// جدولِ تجمعی — یک بار ساخته می‌شود
// ═══════════════════════════════════════════════════════════════════════════
//
// `levelFromXp` در هر پاسخِ API صدا زده می‌شود (لیگ، چت، نوار حریف...)،
// گاهی برای ده‌ها کاربر در یک درخواست. محاسبهٔ `Math.pow` در حلقه برای
// هر بار، کارِ بی‌دلیلی است.
//
// جدول ۱۰۱ عدد است: ~۸۰۰ بایت، یک بار در عمرِ پروسه.
// `CUMULATIVE[k]` = کل XP لازم برای **رسیدن** به لول k.
// ایندکس ۰ یعنی لول صفر که با صفر XP شروع می‌شود.
const CUMULATIVE = (() => {
  const out = [0];
  let total = 0;
  for (let n = 0; n < MAX_LEVEL; n++) {
    // `xpForLevel(n)` هزینهٔ رفتن از n به n+1 است. برای n=0 هم
    // معنادار است: اولین لول‌آپ باید ارزان باشد.
    total += xpForLevel(n + 1);
    out[n + 1] = total;
  }
  return out;
})();

/** کل XP لازم برای رسیدن به لول [level]. */
function totalXpFor(level) {
  if (level <= MIN_LEVEL) return 0;
  if (level >= MAX_LEVEL) return CUMULATIVE[MAX_LEVEL];
  return CUMULATIVE[level];
}

/**
 * لول و پیشرفتِ یک مقدارِ XP.
 *
 * خروجی همانی است که کلاینت برای کشیدنِ نوار پیشرفت لازم دارد، پس
 * محاسبه یک بار سمتِ سرور انجام می‌شود نه در هر کلاینت — و مهم‌تر،
 * منحنی می‌تواند بدون انتشارِ نسخهٔ جدیدِ اپ تنظیم شود.
 */
function levelFromXp(xp) {
  const total = Math.max(0, Number(xp) || 0);

  // جست‌وجوی دودویی روی جدولِ تجمعی. با ۱۰۰ عنصر تفاوتِ عملی با
  // جست‌وجوی خطی ندارد، ولی وقتی برای هر ردیفِ جدولِ لیگ صدا زده
  // می‌شود، ۷ مقایسه بهتر از ۱۰۰ است.
  let lo = MIN_LEVEL;
  let hi = MAX_LEVEL;
  while (lo < hi) {
    const mid = Math.ceil((lo + hi) / 2);
    if (CUMULATIVE[mid] <= total) lo = mid;
    else hi = mid - 1;
  }
  const level = lo;

  if (level >= MAX_LEVEL) {
    return {
      level: MAX_LEVEL,
      xp: total,
      into: 0,
      needed: 0,
      progress: 1,
      isMax: true,
    };
  }

  const floor = CUMULATIVE[level];
  const next = CUMULATIVE[level + 1];
  const span = next - floor;
  const into = total - floor;
  return {
    level,
    xp: total,
    into,
    needed: span,
    // بین ۰ و ۱، برای نوار پیشرفت.
    progress: span > 0 ? Math.min(1, into / span) : 0,
    isMax: false,
  };
}

// ═══════════════════════════════════════════════════════════════════════════
// XP هر رخداد
// ═══════════════════════════════════════════════════════════════════════════
//
// چرا بردن فقط ۱.۷۵ برابرِ باختن است و نه بیشتر:
//
// اگر بردن خیلی بیشتر می‌داد، بازیکنانِ ضعیف‌تر عملاً هیچ پیشرفتی
// نمی‌دیدند و بازی را رها می‌کردند. لول باید پاداشِ **بازی کردن** باشد
// نه فقط پاداشِ قهرمان شدن — به‌خصوص در اپی که مخاطبش نوجوان است.
//
// ولی اگر برابر بود، انگیزهٔ برد از بین می‌رفت. ۲۰ و ۳۵ تعادلِ این دو.
const XP_PLAY = 20;
const XP_WIN_BONUS = 15;

/**
 * XP یک بازیِ تمام‌شده را ثبت می‌کند.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * چرا هرگز پرتاب نمی‌کند
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * این از داخلِ گردانندهٔ پایانِ بازی صدا زده می‌شود، پس از اعلامِ نتیجه.
 * اگر شکست بخورد و پرتاب کند، خطا به حلقهٔ رویدادِ Socket.IO می‌رود و
 * می‌تواند اتاق‌های دیگر را هم بشکند.
 *
 * از دست رفتنِ XP یک بازی ناخوشایند است؛ شکستنِ نشستِ بازیِ چند نفر
 * فاجعه است. پس همه‌چیز داخل try است و شکست فقط لاگ می‌شود.
 */
async function grantGameXp(userId, { gameId, won, opponentId }) {
  try {
    const amount = XP_PLAY + (won ? XP_WIN_BONUS : 0);
    const client = await db().connect();
    try {
      await client.query('BEGIN');

      // سقفِ XP: فراتر از لول ۱۰۰ جمع کردن بی‌معنی است و فقط عددِ
      // بی‌مصرف در دیتابیس می‌سازد. `LEAST` این را در خودِ SQL انجام
      // می‌دهد تا یک رفت‌وبرگشتِ اضافه لازم نباشد.
      const cap = CUMULATIVE[MAX_LEVEL];
      const { rows } = await client.query(
        `UPDATE users
            SET game_xp = LEAST($2::bigint, game_xp + $3::bigint)
          WHERE id = $1
      RETURNING game_xp`,
        [userId, cap, amount],
      );
      if (!rows.length) {
        await client.query('ROLLBACK');
        return null;
      }

      await client.query(
        `INSERT INTO game_xp_log (user_id, game_id, reason, amount, opponent_id)
         VALUES ($1, $2, $3, $4, $5)`,
        [userId, gameId, won ? 'win' : 'play', amount, opponentId || null],
      );

      await client.query('COMMIT');
      return levelFromXp(rows[0].game_xp);
    } catch (e) {
      await client.query('ROLLBACK');
      throw e;
    } finally {
      client.release();
    }
  } catch (e) {
    console.error('[level] grantGameXp failed:', e.message);
    return null;
  }
}

/**
 * لولِ چند کاربر را یک‌جا می‌خواند.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * چرا دسته‌ای و نه تک‌تک
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * درخواست مالک: «این لول رو پروفایل افراد در تمامی قسمت ها دیده بشه و
 * در حین بازی هم لول بقیه رو بشه دید».
 *
 * یعنی جدولِ لیگ (۵۰ ردیف)، فهرست چت (۵۰ پیام)، اعضای باشگاه... اگر
 * برای هر ردیف یک کوئری بزنیم، یک صفحهٔ لیگ ۵۰ رفت‌وبرگشت به دیتابیس
 * می‌شود — همان الگوی N+1 که سریع‌ترین راهِ کند کردنِ یک API است.
 *
 * یک کوئری با `ANY($1)` همه را می‌آورد.
 */
async function levelsFor(userIds) {
  // ═══════════════════════════════════════════════════════════════════════
  // شناسهٔ کاربر در این پروژه UUID است، نه عدد
  // ═══════════════════════════════════════════════════════════════════════
  //
  // نسخهٔ اول `map(Number)` می‌کرد و `::int[]` می‌فرستاد — که هر
  // شناسه‌ای را به NaN تبدیل می‌کرد و کوئری همیشه خالی برمی‌گشت.
  // نتیجه‌اش این بود که هیچ لولی هیچ‌جا نمایش داده نمی‌شد، **بدون
  // هیچ خطایی** — چون تابع خطا را می‌بلعد و شیءِ خالی می‌دهد.
  //
  // این دقیقاً همان دسته باگی است که در تستِ محلی دیده نمی‌شود و فقط
  // روی دادهٔ واقعی ظاهر می‌شود.
  const ids = [...new Set((userIds || []).filter(Boolean).map(String))];
  if (!ids.length) return {};
  try {
    const { rows } = await db().query(
      'SELECT id, game_xp FROM users WHERE id = ANY($1::uuid[])',
      [ids],
    );
    const out = {};
    for (const r of rows) {
      const info = levelFromXp(r.game_xp);
      // فقط چیزی که کلاینت برای نشانِ کوچک لازم دارد — نه کلِ شیء.
      // این در هر پیامِ چت تکرار می‌شود، پس هر بایت مهم است.
      out[r.id] = { level: info.level, isMax: info.isMax };
    }
    return out;
  } catch (e) {
    console.error('[level] levelsFor failed:', e.message);
    // شکستِ نمایشِ لول نباید کلِ صفحه را بشکند؛ نبودِ نشان بهتر از
    // یک صفحهٔ خطاست.
    return {};
  }
}

/** وضعیتِ کاملِ لولِ یک کاربر، برای صفحهٔ بازی‌ها و پروفایل. */
async function statusFor(userId) {
  try {
    const { rows } = await db().query(
      'SELECT game_xp FROM users WHERE id = $1',
      [userId],
    );
    const xp = rows.length ? rows[0].game_xp : 0;
    const info = levelFromXp(xp);
    return {
      ...info,
      maxLevel: MAX_LEVEL,
      // برای نمایشِ «۲۰ XP در هر بازی، ۳۵ در صورت برد» در راهنما.
      xpPerPlay: XP_PLAY,
      xpPerWin: XP_PLAY + XP_WIN_BONUS,
    };
  } catch (e) {
    console.error('[level] statusFor failed:', e.message);
    return { ...levelFromXp(0), maxLevel: MAX_LEVEL, xpPerPlay: XP_PLAY, xpPerWin: XP_PLAY + XP_WIN_BONUS };
  }
}

module.exports = {
  MIN_LEVEL,
  MAX_LEVEL,
  XP_PLAY,
  XP_WIN_BONUS,
  xpForLevel,
  totalXpFor,
  levelFromXp,
  grantGameXp,
  levelsFor,
  statusFor,
};
