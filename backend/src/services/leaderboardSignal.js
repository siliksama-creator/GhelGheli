// ============================================================================
//  سیگنالِ «لیدربورد لیگ عوض شد» — یک نقطهٔ واحد برای بی‌اعتبارسازیِ کش و
//  پخشِ رویدادِ سوکت به همهٔ بیننده‌های جدول.
// ============================================================================
//
// ── چرا هست ──────────────────────────────────────────────────────────
// تا پیش از این، جدولِ لیگ در وب هر ۱۲ ثانیه یک‌بار HTTP می‌زد (poll) تا
// تازه بماند. این یعنی حتی وقتی هیچ رتبه‌ای عوض نمی‌شد، هر کاربرِ بازِ
// صفحه بی‌وقفه به سرور فشار می‌آورد.
//
// حالا فقط وقتی جدول واقعاً تغییر می‌کند یک سیگنال پخش می‌شود و کلاینت‌ها
// در آن لحظه دوباره می‌خوانند. این سرویس همان سیگنال است و دو کار دارد:
//
//   ۱) کشِ مشترکِ `/api/league/current` را (که با کلیدهای متعددِ
//      `lb:league:*` ذخیره شده) یک‌جا بی‌اعتبار می‌کند، تا پاسخِ بعدی
//      رتبه‌های تازه را بدهد نه دادهٔ ۸-ثانیه-کهنه را؛
//   ۲) رویدادِ `leaderboard:update` را به **همهٔ** سوکت‌ها پخش می‌کند.
//      (آداپتورِ Redisِ Socket.IO باعث می‌شود این پخش از هر پروسه‌ای که
//      صادر شود به کلاینت‌های روی هر دو گره برسد.)
//
// مهم: سیگنال فقط «بگو دوباره بخوان» است، نه خودِ داده. کلاینت همان
// `/api/league/current` را می‌زند که رتبهٔ شخصیِ بیننده (`myEntry`) را
// هم دارد؛ پس شکلِ payload ریسک واگرایی ندارد و منطقِ رتبه‌بندی یک‌جا
// (در leagueService) می‌ماند.
//
// تزریقِ io: سرویس‌های دامنه (مثل gameStakeService) در لایه‌های پایین‌تر
// از server ساخته می‌شوند و نباید به io وابستگیِ مستقیم بگیرند؛ پس io یک
// بار از server اینجا attach می‌شود (مثل الگوی presenceService).

const { cacheDelPrefix } = require('../lib/cache');

let ioRef = null;

function attach(io) {
  ioRef = io;
}

/**
 * اعلامِ اینکه لیدربوردِ لیگ تغییر کرده است.
 *
 * @param {object} [opts]
 * @param {string} [opts.prefix='lb:league:'] پیشوندِ کلیدهای کشِ لیگ.
 * @param {boolean} [opts.invalidateCache=true] آیا کشِ فهرست بی‌اعتبار شود.
 *
 * غیرمسدودکننده و best-effort است: نه پاسخِ کاربر را نگه می‌دارد و نه با
 * خطا می‌شکند (خرابیِ Redis/سوکت نباید جلوی ثبتِ نتیجهٔ بازی را بگیرد).
 */
function leaderboardChanged(opts = {}) {
  const prefix = opts.prefix || 'lb:league:';
  const invalidate = opts.invalidateCache !== false;

  if (invalidate) {
    cacheDelPrefix(prefix).catch(() => {});
  }
  if (ioRef) {
    try {
      // رویداد بدونِ داده؛ کلاینت خودش `/api/league/current` را می‌زند.
      ioRef.emit('leaderboard:update', { at: Date.now() });
    } catch { /* سوکت اختیاری است */ }
  }
}

module.exports = { attach, leaderboardChanged };
