//
//     امتیاز ۰.۵۵ + نسبت ۱.۰۵  →  ۶۰  /  ۰  ← انتخاب‌شده
//     امتیاز ۰.۵۵ + نسبت ۱.۰۶  →  ۵۳  /  ۰
//     امتیاز ۰.۵۵ + نسبت ۱.۱۰  →  ۳۳  /  ۰
