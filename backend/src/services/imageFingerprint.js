// امضای رنگِ فضایی — سیگنالی که «کدام رنگ، کجا» را می‌بیند
// ═══════════════════════════════════════════════════════════════════════════
//
// ── چرا سیگنال‌های قبلی کافی نبودند ──
//
// اندازه‌گیری روی چهار کارتِ واقعیِ قلقلی نشان داد کارتِ Hakimi و کارتِ
// Dembélé نمرهٔ ۰.۶۵ می‌گیرند — بالاتر از آستانهٔ تأیید. علتش وقتی روشن
// شد که خودِ تصاویر کنار هم گذاشته شدند:
//
//   هر دو «روی» کارت‌اند و **قالبِ کاملاً یکسان** دارند: پس‌زمینهٔ سفید،
//   جامِ جهانی در بالا-چپ، نوارِ عمودیِ «LIMITED» در راست، سه خانهٔ آمار
//   در پایین، امضا در گوشه.
//
// تنها تفاوتِ واقعی: **رنگِ پیراهن** (قرمزِ مراکش در برابر آبیِ فرانسه)
// و چهرهٔ بازیکن.
//
// سیگنال‌های قبلی هیچ‌کدام این را نمی‌دیدند:
//   • dHash/pHash روی خاکستری کار می‌کنند — رنگ را کاملاً دور می‌ریزند
//   • colorSig شبکهٔ ۴×۴ دارد و فقط «فام» را می‌شمارد، بدونِ روشنایی
//   • texSig و lumaSig هم قالبِ مشترک را می‌دیدند، نه محتوا را
//
// ── این سیگنال چه می‌کند ──
//
// تصویر به شبکهٔ ۸×۸ خرد می‌شود و از هر خانه **میانگینِ RGB** گرفته
// می‌شود. نتیجه ۱۹۲ عدد است که مستقیماً می‌گوید «خانهٔ وسط-چپ قرمزِ
// تیره است» یا «خانهٔ وسط-چپ آبیِ روشن است».
//
// ⚠️ چرا از `prepared` استفاده نمی‌شود (بدونِ trim)
//
//    `trim` حاشیهٔ یکنواخت را می‌برد. برای هش‌ها خوب است، ولی اینجا
//    موقعیتِ مطلق مهم است: اگر یک عکس trim شود و دیگری نه، شبکهٔ ۸×۸
//    روی نواحیِ متفاوتی می‌افتد و مقایسه بی‌معنی می‌شود.
//
// ⚠️ چرا میانگینِ خام و نه نرمال‌شده
//
//    نرمال‌سازیِ کنتراست دقیقاً همان چیزی را حذف می‌کند که اینجا لازم
//    است. عکسِ کاربر ممکن است تاریک‌تر باشد، ولی **نسبتِ** قرمز به آبی
//    ثابت می‌ماند — و `blockSim` چون هر دو بردار را به مجموعِ ۱ نرمال
//    می‌کند، خودش این تفاوتِ شدت را خنثی می‌کند.
const RGB_GRID = 8;

async function rgbLayout(buf) {
  const n = RGB_GRID;
  const S = n * 8;                 // ۶۴×۶۴ — هر خانه ۸×۸ پیکسل
  let data;
  try {
    ({ data } = await sharp(buf, { failOn: 'none' })
      .rotate().removeAlpha()
      .resize(S, S, { fit: 'fill', kernel: 'lanczos3' })
      .raw()
      .toBuffer({ resolveWithObject: true }));
  } catch {
    return [];
  }
  const step = S / n;
  const out = new Float32Array(n * n * 3);
  const cnt = new Float32Array(n * n);
  for (let y = 0; y < S; y++) {
    const gy = Math.min(n - 1, Math.floor(y / step));
    for (let x = 0; x < S; x++) {
      const gx = Math.min(n - 1, Math.floor(x / step));
      const c = gy * n + gx;
      const i = (y * S + x) * 3;
      out[c * 3] += data[i];
      out[c * 3 + 1] += data[i + 1];
      out[c * 3 + 2] += data[i + 2];
      cnt[c] += 1;
    }
  }
  for (let c = 0; c < n * n; c++) {
    if (!cnt[c]) continue;
    out[c * 3] /= cnt[c] * 255;
    out[c * 3 + 1] /= cnt[c] * 255;
    out[c * 3 + 2] /= cnt[c] * 255;
  }
  return Array.from(out);
}

const { readText, textSimilarity } = require('./imageFingerprintText');

function packBits(bits) {
  const out = Buffer.alloc(Math.ceil(bits.length / 8));
  for (let i = 0; i < bits.length; i++) {
    if (bits[i]) out[i >> 3] |= 0x80 >> (i & 7);
  }
  return out;
}

const POPCOUNT = (() => {
  const t = new Uint8Array(256);
  for (let i = 0; i < 256; i++) t[i] = (i & 1) + t[i >> 1];
  return t;
})();

function hamming(a, b) {
  const n = Math.min(a.length, b.length);
  let d = 0;
  for (let i = 0; i < n; i++) d += POPCOUNT[a[i] ^ b[i]];
  return d;
}

/** اثر انگشت کامل یک تصویر. */
async function fingerprint(buf) {
  const meta = await sharp(buf, { failOn: 'none' }).metadata();
  const [d, p, c, t, l, rgb, txt] = await Promise.all([
    dhash(buf), phash(buf), colorSignature(buf), radialTexture(buf),
    lumaMap(buf), rgbLayout(buf), readText(buf),
  ]);
  return {
    version: FP_VERSION,
    dhash: d,
    phash: p,
    colorSig: c,
    texSig: t,
    lumaSig: l,
    rgbSig: rgb,
    textTokens: txt,
    width: meta.width || 0,
    height: meta.height || 0,
  };
}

/**
 * شباهت دو اثر انگشت، عددی بین ۰ و ۱.
 *
 * وزن‌ها: رنگ ۰.۴۰، dHash ۰.۳۰، pHash ۰.۳۰.
 *
 * چرا رنگ بیشترین وزن را دارد: در آزمایش، رنگ پایدارترین سیگنال روی
 * عکس‌های واقعاً بد بود (۰.۹۲ حتی روی نمونه‌ای که dHash فقط ۰.۵۴ داد).
 * کارت‌های فوتبالی پالت‌های بسیار متمایز دارند — پیراهنِ تیم — و این
 * دقیقاً همان چیزی است که از تاری و کم‌نوری جان سالم به در می‌برد.
 */
// ═══════════════════════════════════════════════════════════════════════════
// چرا کسینوس برای این بردارها **کار نمی‌کند**
// ═══════════════════════════════════════════════════════════════════════════
//
// اندازه‌گیریِ واقعی روی چهار کارتِ قلقلی (دو Hakimi، دو Dembélé):
//
//     جفت              کسینوسِ tex   کسینوسِ luma
//     Hakimi × Hakimi     ۰.۹۲۰        ‑۰.۲۹۴   ← همان بازیکن!
//     Hakimi × Dembélé    ۰.۹۴۲        +۰.۹۶۴   ← بازیکنِ متفاوت!
//
// یعنی هر دو سیگنال **معکوس** جواب می‌دادند. دو علتِ جدا:
//
// ── الف) بردارِ همه‌مثبت ──
//
// `texSig` هیستوگرامِ شعاعی است، پس همهٔ درایه‌هایش ≥ ۰. کسینوسِ دو
// بردارِ همه‌مثبتِ نرمال‌شده تقریباً همیشه بالای ۰.۹ است — ریاضیاتش
// اجازهٔ چیزِ دیگری نمی‌دهد. سیگنالی که برای همه‌چیز ۰.۹۲ می‌دهد هیچ
// اطلاعاتی ندارد؛ فقط نمرهٔ نهایی را مصنوعی کف می‌دهد و همهٔ کارت‌ها
// را شبیهِ هم نشان می‌دهد.
//
// ── ب) بردارِ میانگین‌صفر با clamp ──
//
// `lumaSig` میانگینش کم شده، پس کسینوسش می‌تواند منفی باشد. تابعِ
// `cos` قدیمی با `Math.max(0, …)` منفی را صفر می‌کرد. نتیجه: خروجی یا
// ۰ بود یا ۰.۹۶، هیچ‌وقت وسط — یک کلیدِ دو‌حالته به‌جای یک معیارِ
// پیوسته. و چون نویز هم می‌تواند علامت را برگرداند، آن کلید تصادفی
// روشن و خاموش می‌شد.
//
// ── راه‌حل: فاصلهٔ L1 به‌جای زاویه ──
//
// `blockSim` تفاوتِ **درایه‌به‌درایه** را جمع می‌زند. دو هیستوگرام که
// در همان سلول‌ها مقدارِ مشابه دارند نمرهٔ بالا می‌گیرند؛ دو هیستوگرام
// که وزنشان در سلول‌های متفاوتی نشسته نمرهٔ پایین — حتی اگر زاویهٔ
// بینشان کوچک باشد.
//
// این دقیقاً همان چیزی است که «کارتِ Hakimi با پیراهنِ قرمز در بالا»
// را از «کارتِ Dembélé با پیراهنِ آبی در بالا» جدا می‌کند.
//
// ⚠️ ضریبِ ۰.۵: مجموعِ |تفاوت| برای دو بردارِ نرمال‌شدهٔ کاملاً متفاوت
//    به ۲ می‌رسد، پس نصفش می‌کنیم تا خروجی در بازهٔ [۰,۱] بماند.
function blockSim(x, y) {
  if (!Array.isArray(x) || !Array.isArray(y)) return 0;
  const n = Math.min(x.length, y.length);
  if (!n) return 0;
  let sx = 0; let sy = 0;
  for (let i = 0; i < n; i++) { sx += Math.abs(x[i]); sy += Math.abs(y[i]); }
  if (sx < 1e-9 || sy < 1e-9) return 0;
  // هر دو به مجموعِ ۱ نرمال می‌شوند تا مقایسه از شدتِ کلی مستقل باشد.
  let diff = 0;
  for (let i = 0; i < n; i++) diff += Math.abs(x[i] / sx - y[i] / sy);
  return Math.max(0, 1 - diff * 0.5);
}

