const PHASH_N = 32;      // ورودی DCT
const PHASH_K = 8;       // ۸×۸ ضریب پایین → ۶۳ بیت مفید
const COLOR_GRID = 4;    // شبکهٔ ۴×۴
const COLOR_BINS = 12;   // ۱۲ سطل hue → ۱۹۲ عدد

// ── آستانه‌های تصمیم ──
//
// ═══════════════════════════════════════════════════════════════════════════
// از داده، نه از حدس
// ═══════════════════════════════════════════════════════════════════════════
//
// روی ۱۰۰ عکسِ شبیه‌سازی‌شدهٔ گوشی (۱۰ سناریو × ۱۰ طرح، شاملِ زاویه،
// تاری، فلاشِ سوخته، تاریکیِ شدید و برشِ نامتقارن) در برابر کاتالوگِ
