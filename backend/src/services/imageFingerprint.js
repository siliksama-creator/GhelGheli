// شباهتِ چیدمانِ رنگ — با جریمهٔ «تصویرِ تخت»
// ═══════════════════════════════════════════════════════════════════════════
//
// ── رگرسیونی که این را لازم کرد ──
//
// `blockSim` به‌تنهایی روی `rgbSig` نمرهٔ متورم می‌داد:
//
//     عکسِ کاغذِ راه‌راهِ سفید × کارتِ نارنجی → ۰.۸۰۰
//     عکسِ گوشی از همان کارت  × خودِ کارت    → ۰.۹۲۷
//
// یعنی «چیزی که اصلاً کارت نیست» تقریباً همان‌قدر شبیه بود که «عکسِ
// واقعیِ خودِ کارت». نمرهٔ نهایی به ۰.۴۴۹ می‌رسید — بالای آستانهٔ ۰.۴۰
// کدِ بی‌نام، پس کاربر می‌توانست عکسِ دیوار بفرستد و کارت بگیرد.
//
// ── چرا `blockSim` اینجا شکست می‌خورد ──
//
// آن تابع هر دو بردار را به مجموعِ ۱ نرمال می‌کند تا از شدتِ نور مستقل
// باشد. برای دو تصویر با محتوای واقعی درست کار می‌کند، ولی وقتی یکی
// **تخت** است (همهٔ ۱۹۲ درایه تقریباً برابر) نرمال‌سازی تفاوت‌ها را
// می‌شوید و هر تصویرِ تختی به هر چیزی شبیه می‌شود.
//
// ── راه‌حل: نسبتِ تنوعِ فضایی ──
//
// انحرافِ معیارِ درایه‌ها می‌گوید تصویر چقدر «تخت» است:
//
//     کاغذِ راه‌راه  ۰.۰۱۲   ← تقریباً یکنواخت
//     کارتِ آزمایشی ۰.۱۹۷
//     کارتِ واقعی   ۰.۲۷۴
//
// نسبتِ کوچک‌تر به بزرگ‌تر ضریبِ نمره می‌شود. دو تصویری که هر دو تنوعِ
// مشابه دارند ضریبِ نزدیکِ ۱ می‌گیرند؛ تصویرِ تخت در برابرِ تصویرِ پر
// از جزئیات ضریبِ نزدیکِ صفر.
//
//     نویز × کارت      ۰.۸۰۰ → ۰.۰۴۷
//     گوشی × خودِ کارت ۰.۹۲۷ → ۰.۸۹۰
//
// ⚠️ چرا ضرب و نه شرطِ آستانه‌ای: شرطِ سخت یک پرتگاه می‌سازد و عکسی که
//    یک هزارم آن‌طرفِ مرز است رفتارِ کاملاً متفاوتی می‌گیرد. ضرب پیوسته
//    است و عکسِ کم‌جزئیاتِ واقعی را به‌تدریج جریمه می‌کند نه ناگهانی.
function rgbLayoutSim(x, y) {
  const base = blockSim(x, y);
  if (base <= 0) return 0;
  const spread = (v) => {
    const n = v.length;
    if (!n) return 0;
    let m = 0;
    for (let i = 0; i < n; i++) m += v[i];
    m /= n;
    let s = 0;
    for (let i = 0; i < n; i++) s += (v[i] - m) * (v[i] - m);
    return Math.sqrt(s / n);
  };
  const sx = spread(x);
  const sy = spread(y);
  const hi = Math.max(sx, sy);
  if (hi < 1e-9) return 0;          // هر دو کاملاً یکنواخت: بی‌اطلاع
  return base * (Math.min(sx, sy) / hi);
}

// ═══════════════════════════════════════════════════════════════════════════
// وزنِ متن در نمرهٔ نهایی
// ═══════════════════════════════════════════════════════════════════════════
//
// متن **جایگزینِ** تصویر نمی‌شود، بلکه آن را جابه‌جا می‌کند:
//
//   • متنِ هم‌خوان  → نمره بالا می‌رود (تا سقفِ TEXT_BOOST)
//   • متنِ متناقض   → نمره پایین می‌آید (تا کفِ TEXT_PENALTY)
//   • متنی خوانده نشد → هیچ اثری ندارد، فقط تصویر حرف می‌زند
//
// ── چرا جابه‌جایی و نه وزنِ ثابت ──
//
// وزنِ ثابت یعنی هر عکسی که OCR رویش کار نکند (تارِ شدید، نورِ بد) نمرهٔ
// کمتری بگیرد — حتی اگر تصویرش کاملاً واضح باشد. آن کاربر را برای چیزی
// مجازات می‌کند که تقصیرش نیست.
//
// جابه‌جایی فقط وقتی عمل می‌کند که **هر دو طرف** متن داشته باشند. در
// بقیهٔ حالات فرمولِ تصویری دست‌نخورده می‌ماند.
//
// ── اعداد ──
//
// روی عکسِ واقعیِ کاربر (کارتِ دمبله روی میزِ چوبی):
//
//     مرجع       تصویر   متن    نهایی
//     Hakimi-B   ۰.۵۳۳   ۰.۰۰   ۰.۳۸۳  ← از رتبهٔ ۱ به ۳
//     Dembélé-B  ۰.۵۰۰   ۰.۵۰   ۰.۵۵۰
//     Dembélé-A  ۰.۳۱۵   ۱.۰۰   ۰.۴۶۵  ← از رتبهٔ ۴ به ۲
//
// حاشیه از ۰.۰۳۳ به ۰.۰۸۵ رسید و کارتِ **درست** برنده شد.
//
// ⚠️ سقفِ ۰.۱۵: متن نباید بتواند به‌تنهایی یک تطبیقِ ضعیف را به تأیید
//    برساند. عکسی که هیچ شباهتی ندارد ولی اتفاقاً کلمهٔ مشترکی دارد
//    (مثلاً «WORLDCUP» که روی همهٔ کارت‌هاست) نباید کارت بگیرد.
const TEXT_BOOST = 0.15;
const TEXT_PENALTY = 0.15;

function similarity(a, b) {
  const dBits = Math.min(a.dhash.length, b.dhash.length) * 8;
  const pBits = Math.min(a.phash.length, b.phash.length) * 8;

  // ── چرا dHash و pHash بازمقیاس می‌شوند ──
  //
  // هشِ باینری کفِ ۰.۵ دارد، نه ۰: دو تصویرِ کاملاً بی‌ربط هم به‌طور
  // میانگین نیمی از بیت‌هایشان تصادفاً یکی است. پس «۰.۵۵» در عمل یعنی
  // «تقریباً هیچ شباهتی»، ولی در فرمولِ قبلی مثل «نیمی شبیه» وزن
  // می‌گرفت و امتیازِ نهایی را مصنوعی بالا نگه می‌داشت.
  //
  // با بازمقیاس به بازهٔ [۰,۱]، عددی که این دو می‌دهند معنای واقعی
  // پیدا می‌کند: ۰.۵ خام → ۰ نهایی.
  const rescale = v => Math.max(0, (v - 0.5) * 2);
  const dScore = dBits ? rescale(1 - hamming(a.dhash, b.dhash) / dBits) : 0;
  const pScore = pBits ? rescale(1 - hamming(a.phash, b.phash) / pBits) : 0;

  // کسینوسِ علامت‌دار برای بردارهای میانگین‌صفر (فقط lumaSig).
  //
  // بردار از قبل نرمال شده، پس ضربِ داخلی خودش کسینوس است. نگاشتِ
  // (x+1)/2 بازهٔ [-۱,۱] را به [۰,۱] می‌برد بدونِ از دست دادنِ علامت.
  const signedCos = (x, y) => {
    if (!x || !y) return 0;
    let dot = 0;
    const n = Math.min(x.length, y.length);
    for (let i = 0; i < n; i++) dot += x[i] * y[i];
    return Math.max(0, Math.min(1, (Math.max(-1, Math.min(1, dot)) + 1) / 2));
  };
  // رنگ: هیستوگرامِ فامِ ۴×۴ — همه‌مثبت، پس فاصلهٔ بلوکی می‌خواهد.
  //
  // ⚠️ این هم مثل tex بردارِ همه‌مثبت است و با کسینوس نمرهٔ متورم
  //    می‌گرفت (۰.۴۳ برای دو بازیکنِ متفاوت، در حالی که باید نزدیکِ
  //    صفر باشد). فاصلهٔ بلوکی همان تفاوت را درست نشان می‌دهد.
  const cScore = blockSim(a.colorSig, b.colorSig);

  // ── بافتِ شعاعی ──
  //
  // وزنش در نسخهٔ ۴ صفر است (توضیحِ کامل پایین‌تر) ولی محاسبه می‌شود
  // چون مسیرهای بازگشتیِ اثرانگشت‌های قدیمی هنوز از آن استفاده می‌کنند.
  const hasTex = Array.isArray(a.texSig) && Array.isArray(b.texSig)
    && a.texSig.length > 0 && b.texSig.length > 0;
  const tScore = hasTex ? blockSim(a.texSig, b.texSig) : 0;

  const hasRgb = Array.isArray(a.rgbSig) && Array.isArray(b.rgbSig)
    && a.rgbSig.length > 0 && b.rgbSig.length > 0;
  const rScore = hasRgb ? rgbLayoutSim(a.rgbSig, b.rgbSig) : 0;

  // ⚠️ «بردارِ صفر» با «سیگنالِ غایب» یکی شمرده می‌شود و این عمدی است.
  //
  //    `lumaSig` میانگین‌صفر و نرمال‌شده است. برای تصویرِ کاملاً یکدست
  //    (پس‌زمینهٔ تخت، یا عکسی که کاملاً سوخته) همهٔ درایه‌ها صفر
  //    می‌شوند. آن‌وقت `signedCos` ضربِ داخلیِ صفر می‌گیرد و طبقِ
  //    نگاشتِ (x+1)/2 عددِ **۰.۵** برمی‌گرداند — یعنی «نیمه‌شبیه».
  //
  //    نتیجه‌اش یک باگِ ظریف بود که تستِ اتصال گرفت: شباهتِ یک تصویر
  //    با **خودش** ۰.۹۷۵ می‌شد نه ۱.۰۰۰. روی تصویرِ واقعی بی‌اهمیت
  //    است، ولی نشان می‌داد فرمول یک حالتِ مرزی را غلط حساب می‌کند —
  //    و همان حالت روی عکسِ سوختهٔ فلاش واقعاً پیش می‌آید.
  //
  //    درستش این است که وقتی بردار هیچ اطلاعاتی ندارد، وزنش بین بقیهٔ
  //    سیگنال‌ها پخش شود (همان کاری که برای سیگنالِ غایب می‌کنیم).
  const lumaEnergy = v => (Array.isArray(v)
    ? v.reduce((acc, x) => acc + x * x, 0) : 0);
  const hasLuma = Array.isArray(a.lumaSig) && Array.isArray(b.lumaSig)
    && a.lumaSig.length > 0 && b.lumaSig.length > 0
    && lumaEnergy(a.lumaSig) > 1e-6 && lumaEnergy(b.lumaSig) > 1e-6;
  // روشنایی: بردارِ میانگین‌صفر است، پس **کسینوسِ علامت‌دار** درست است
  // — ولی باید از [-۱,۱] به [۰,۱] نگاشت شود نه clamp.
  //
  // clamp قبلی نیمِ منفیِ بازه را به صفر می‌چسباند و اطلاعاتِ «کاملاً
  // برعکس» را با «بی‌ربط» یکی می‌کرد. نگاشتِ خطی هر دو را نگه می‌دارد:
  // ‑۱ → ۰ (نقیضِ هم)، ۰ → ۰.۵ (بی‌ربط)، +۱ → ۱ (یکسان).
  const lScore = hasLuma ? signedCos(a.lumaSig, b.lumaSig) : 0;

  // ── وزن‌ها بعد از افزودنِ rgbSig (نسخهٔ ۴) ──
  //
  // اندازه‌گیری روی کارت‌های واقعیِ قلقلی با ۱۲ عکسِ شبیه‌سازی‌شدهٔ گوشی
  // (سه سناریو × چهار کارت: چرخش ۳–۷ درجه، نور ۰.۷۵–۱.۲۵، تاری،
  // فشرده‌سازی JPEG با کیفیت ۴۵–۷۲).
  //
  // ⚠️ `texSig` وزنش صفر شد و این عمدی است.
  //
  //    اندازه‌گیری نشان داد این سیگنال برای **همهٔ** جفت‌ها عددی بین
  //    ۰.۹۱ و ۰.۹۵ می‌دهد — چه دو عکس از یک کارت، چه دو کارتِ کاملاً
  //    متفاوت. سیگنالی که همیشه یک جواب می‌دهد اطلاعاتی ندارد؛ فقط
  //    نمرهٔ نهایی را به‌طور مصنوعی بالا می‌برد و همه‌چیز را شبیهِ هم
  //    نشان می‌دهد.
  //
  //    از اثرانگشت حذف **نشد** (ستونش در دیتابیس می‌ماند و پر می‌شود)
  //    تا اگر روزی معیارِ بهتری برایش پیدا شد بدونِ مهاجرت برگردد.
  // ── وزن‌های نسخهٔ ۴، از جست‌وجوی شبکه‌ای روی دو مجموعه ──
  //
  //   الف) ۴ کارتِ واقعیِ قلقلی × ۶ سناریوی گوشی           →  ۲۴ نمونه
  //   ب)  همان‌ها + ۸ مشتقِ چرخش‌رنگ (کاتالوگِ سختِ ۱۲تایی) →  ۷۲ نمونه
  //
  // سناریوها: چرخشِ ۳ تا ۱۷ درجه، نورِ ۰.۶۲ تا ۱.۴۵، تاریِ ۰.۵ تا ۳.۲،
  // JPEG با کیفیتِ ۲۸ تا ۸۰، عرضِ ۳۶۰ تا ۸۰۰ پیکسل.
  //
  //     وزن‌ها                         الف     ب     حاشیه
  //     ۰.۲۵/۰.۱۰/۰.۳۵/۰.۱۰/۰.۲۰ (v3) ۲۳/۲۴  ۶۷/۷۲  ۰.۱۱۰
  //     ۰.۲۰/۰.۰۸/۰.۲۲/۰/۰.۱۵ +rgb۰.۳۵ ۲۲/۲۴  ۶۷/۷۲  ۰.۱۱۰
  //     ۰/۰.۱۰/۰.۴۵/۰/۰ +rgb۰.۴۵       ۲۴/۲۴  ۷۲/۷۲  ۰.۱۷۴
  //     ۰.۰۸/۰.۰۷/۰.۴۰/۰/۰.۰۵ +rgb۰.۴۰ ۲۴/۲۴  ۷۲/۷۲  ۰.۱۶۱ ← انتخاب‌شده
  //
  // ⚠️ چرا بهترینِ گرید انتخاب **نشد**
  //
  //    جست‌وجو `dHash = 0` را برنده اعلام کرد. روی این دو مجموعه درست
  //    است، ولی dHash تنها سیگنالی است که **ساختارِ لبه‌ها** را می‌بیند
  //    — و آن دقیقاً چیزی است که دو کارت با پالتِ رنگیِ یکسان و طرحِ
  //    متفاوت را جدا می‌کند. صفر کردنش یعنی ساختنِ یک نقطهٔ کورِ کامل
  //    برای کاتالوگی که هنوز وجود ندارد.
  //
  //    وزنِ کوچکِ ۰.۰۸ روی هر دو مجموعه همان ۱۰۰٪ را می‌دهد (حاشیه فقط
  //    ۰.۰۱۳ کمتر) ولی آن نقطهٔ کور را نمی‌سازد. معاملهٔ روشنی است.
  //
  // ⚠️ چرا `texSig` وزنش صفر است
  //
  //    برای **همهٔ** جفت‌ها عددی بین ۰.۹۱ و ۰.۹۵ می‌داد — چه دو عکس از
  //    یک کارت، چه دو کارتِ کاملاً متفاوت. سیگنالی که همیشه یک جواب
  //    می‌دهد اطلاعاتی ندارد؛ فقط نمرهٔ نهایی را مصنوعی بالا می‌برد.
  //    از اثرانگشت حذف نشد تا اگر روزی معیارِ بهتری پیدا شد برگردد.
  //
  // ⚠️ این اعداد با آستانه‌ها جفت‌اند. تغییرشان بدون اجرای دوبارهٔ
  //    `scripts/benchPhotoMatch.js` یعنی حدس زدن.
  if (hasRgb) {
    // وزنِ روشنایی وقتی غایب است به رنگ و rgb می‌رود تا مجموع ۱ بماند.
    if (!hasLuma) {
      return 0.08 * dScore + 0.07 * pScore + 0.42 * cScore + 0.43 * rScore;
    }
    return 0.08 * dScore + 0.07 * pScore + 0.40 * cScore
         + 0.05 * lScore + 0.40 * rScore;
  }

  if (hasTex && hasLuma) {
    return 0.25 * dScore + 0.10 * pScore + 0.35 * cScore
         + 0.10 * tScore + 0.20 * lScore;
  }
  // ── بازگشتِ تدریجی برای اثرانگشت‌های قدیمی ──
  //
  // وزنِ سیگنالِ غایب بینِ بقیه پخش می‌شود تا مجموع همیشه ۱ بماند.
  // بدون این، طرحی که هنوز backfill نشده امتیازِ کمتری می‌گرفت و
  // بی‌دلیل به صف بررسی می‌رفت — دقیقاً باگی که با texSig رخ داد.
  if (hasTex) {
    return 0.30 * dScore + 0.15 * pScore + 0.40 * cScore + 0.15 * tScore;
  }
  if (hasLuma) {
    return 0.28 * dScore + 0.12 * pScore + 0.35 * cScore + 0.25 * lScore;
  }
  return 0.35 * dScore + 0.18 * pScore + 0.47 * cScore;
}

/**
 * بهترین طرحِ منطبق را پیدا می‌کند و تصمیم می‌گیرد.
 *
 * خروجی: { verdict, design, score, margin, ranked }
 *   verdict = 'accept' | 'review' | 'reject'
 *
 * چرا حاشیه هم شرط است: اگر دو طرح تقریباً هم‌امتیاز باشند، حتی امتیازِ
 * بالا هم قابل اتکا نیست — ممکن است طرحِ اشتباه با اختلاف ناچیز برنده
 * شده باشد و کاربر کارتِ گران‌تری بگیرد که مالِ او نیست.
 */
/**
 * نمرهٔ نهایی: شباهتِ تصویری، جابه‌جا شده با شواهدِ متنی.
 *
 * این تابع همان چیزی است که بقیهٔ سیستم صدا می‌زند؛ `similarity` خام
 * فقط بخشِ تصویری است و برای تست و اشکال‌زدایی باقی مانده.
 */
function combinedSimilarity(a, b) {
  const visual = similarity(a, b);
  const t = textSimilarity(a.textTokens, b.textTokens);

  // ══════════════════════════════════════════════════════════════════════
  // طرحِ بی‌متن نباید مزیتِ ناعادلانه بگیرد
  // ══════════════════════════════════════════════════════════════════════
  //
  // ── باگی که مالک با اسکرین‌شات گرفت ──
  //
  // کاربر عکسِ Hakimi فرستاد، سیستم «Erling Haaland» حدس زد.
  // تفکیکِ نمره‌ها:
  //
  //     Achraf Hakimi  تصویر ۰.۶۰۲  متن ۰.۰۰  →  ۰.۴۵۲
  //     Erling Haaland تصویر ۰.۵۴۳  متن  —    →  ۰.۵۴۳  ← برنده شد
  //
  // آن طرحِ Haaland توکنِ متنی **خالی** داشت (OCR روی پشتِ کارتش چیزی
  // نخواند). پس `textSimilarity` مقدارِ `null` می‌داد و نسخهٔ قبلی
  // نمرهٔ خام را دست‌نخورده برمی‌گرداند.
  //
  // نتیجه: طرحی که متن ندارد **از جریمه معاف می‌شود**، در حالی که
  // رقیبانش جریمه می‌خورند. هرچه OCR روی طرحی بدتر کار کند، شانسِ
  // برنده شدنش بیشتر — دقیقاً برعکسِ چیزی که باید باشد.
  //
  // ── تفکیکِ دو حالتِ `null` ──
  //
  //   الف) **عکسِ کاربر** متن ندارد → واقعاً بی‌اطلاعیم. عکس تار است یا
  //        نورش بد. هیچ طرفی نباید جریمه شود؛ فقط تصویر حرف می‌زند.
  //
  //   ب) عکسِ کاربر متن **دارد** ولی این طرح ندارد → شواهدی هست که
  //        نمی‌شود با آن طرح تطبیقش داد. آن طرح باید همان‌قدر جریمه شود
  //        که طرحی با متنِ کاملاً متناقض.
  //
  // ⚠️ جریمه نصفِ کاملِ `TEXT_PENALTY` است، نه تمامش: «متن نداریم» با
  //    «متن داریم و فرق می‌کند» یکی نیست. اولی ممکن است تقصیرِ کیفیتِ
  //    عکسِ مرجع باشد، دومی شواهدِ مثبتِ ناسازگاری است.
  const queryHasText = Array.isArray(a.textTokens) && a.textTokens.length > 0;
  const refHasText = Array.isArray(b.textTokens) && b.textTokens.length > 0;

  if (t === null) {
    if (queryHasText && !refHasText) {
      return Math.max(0, visual - TEXT_PENALTY * 0.5);
    }
    return visual;      // واقعاً بی‌اطلاع — تصویر تنها قضاوت می‌کند
  }

  // ── چرا نقطهٔ خنثی ۰.۳۵ است و نه ۰.۵ ──
  //
  // کارت‌ها کلماتِ مشترکِ زیادی دارند: WORLDCUP، RIGHT، HEIGHT، FOOT.
  // دو کارتِ کاملاً متفاوت به‌طور طبیعی حدودِ ۰.۲ تا ۰.۳ شباهتِ متنی
  // می‌گیرند. اگر نقطهٔ خنثی ۰.۵ بود، همان اشتراکِ بی‌معنی جریمه
  // می‌شد و کارتِ درست هم پایین می‌آمد.
  //
  // ۰.۳۵ از اندازه‌گیری آمد: بالای آن یعنی «نامِ بازیکن هم‌خوان است»،
  // زیرِ آن یعنی «فقط قالبِ مشترک».
  const NEUTRAL = 0.35;
  const shift = t >= NEUTRAL
    ? TEXT_BOOST * ((t - NEUTRAL) / (1 - NEUTRAL))
    : -TEXT_PENALTY * ((NEUTRAL - t) / NEUTRAL);
  return Math.max(0, Math.min(1, visual + shift));
}

/**
 * «آیا این دو **همان تصویر**اند؟» — برای گاردِ طرحِ تکراری.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * چرا `similarity` خام برای این کار غلط است
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * دو باگِ متضاد که با اندازه‌گیری روی کارت‌های هم‌قالب پیدا شد:
 *
 *   الف) **مثبتِ کاذب.** دو هم‌تیمیِ متفاوت (Mbappé و Griezmann، هر دو
 *        فرانسه، همان قالب) نمرهٔ خامِ ۰.۹۳۱ گرفتند — بالای آستانهٔ
 *        ۰.۹۳. یعنی مدیر نمی‌توانست کارتِ دوم را ثبت کند و پیامِ
 *        «تصویرِ تکراری» می‌گرفت که کاملاً گمراه‌کننده بود.
 *
 *   ب) **منفیِ کاذب.** همان کارت با فشرده‌سازیِ متفاوت (PNG در برابر
 *        JPEG با کیفیت ۹۲) نمرهٔ ۰.۸۹۴ گرفت — زیرِ آستانه. یعنی گاردی
 *        که برای گرفتنِ «همان فایلِ دوبار انتخاب‌شده» ساخته شده بود،
 *        دقیقاً همان حالت را نمی‌گرفت.
 *
 * هر دو یک ریشه دارند: نمرهٔ تصویری برای «کدام کارت است؟» کالیبره شده،
 * نه برای «آیا عیناً همان فایل است؟». آن دو سؤالِ متفاوت‌اند.
 *
 * ── راه‌حل: متن به‌عنوان **جداکننده** ──
 *
 * اگر هر دو تصویر متن دارند و متنشان **فرق می‌کند**، قطعاً دو کارتِ
 * متفاوت‌اند — هرچقدر هم تصویرشان شبیه باشد. نامِ بازیکن روی کارت
 * چاپ شده و دروغ نمی‌گوید.
 *
 * برعکسش را نتیجه نمی‌گیریم: متنِ یکسان به‌تنهایی «همان تصویر» را
 * ثابت نمی‌کند (رو و پشتِ یک کارت هر دو نامِ یکسان دارند). آنجا تصویر
 * حرفِ آخر را می‌زند.
 *
 * @returns {number} نمره‌ای که مستقیم با `DUPLICATE_SIMILARITY` سنجیده
 *   می‌شود؛ اگر متن‌ها متناقض باشند صفر برمی‌گردد.
 */
function sameImageScore(a, b) {
  const t = textSimilarity(a.textTokens, b.textTokens);
  // آستانهٔ ۰.۶ سخت‌گیرانه است: دو کارتِ یکسان باید تقریباً همهٔ
  // توکن‌هایشان مشترک باشد. زیرِ آن یعنی «دو کارتِ متفاوت».
  if (t !== null && t < 0.6) return 0;

  // ── چرا فرمولِ جدا و نه `similarity` ──
  //
  // اندازه‌گیریِ «همان کارت، فقط فرمتِ فایل متفاوت» (PNG → JPEG q92):
  //
  //     dHash ۰.۹۶۱ · pHash ۱.۰۰۰ · rgb ۰.۹۹۹ · luma ۱.۰۰۰
  //     colorSig ۰.۷۴۷   ← متهم
  //     نمرهٔ نهایی ۰.۸۹۵ (زیرِ آستانهٔ ۰.۹۳)
  //
  // `colorSig` هیستوگرامِ **فام** است و روی پس‌زمینهٔ روشن ناپایدار
  // می‌شود: فشرده‌سازیِ JPEG آرتیفکتِ رنگیِ ریز می‌سازد که فامِ
  // پیکسل‌های تقریباً خاکستری را جابه‌جا می‌کند. برای «کدام کارت است؟»
  // مهم نیست (هر دو کارت همان آرتیفکت را دارند)، ولی برای «آیا عیناً
  // همان فایل است؟» نمره را بی‌دلیل پایین می‌آورد.
  //
  // نتیجه در عمل: گاردی که برای گرفتنِ «همان فایلِ دوبار انتخاب‌شده»
  // ساخته شده بود، دقیقاً همان حالت را نمی‌گرفت اگر مدیر یکی را
  // JPEG و دیگری را PNG ذخیره کرده بود.
  //
  // اینجا وزن روی سیگنال‌هایی می‌رود که در برابرِ فشرده‌سازی پایدارند:
  // چیدمانِ رنگ (rgb)، ساختار (هش‌ها) و نقشهٔ روشنایی.
  const dBits = Math.min(a.dhash.length, b.dhash.length) * 8;
  const pBits = Math.min(a.phash.length, b.phash.length) * 8;
  const resc = v => Math.max(0, (v - 0.5) * 2);
  const d = dBits ? resc(1 - hamming(a.dhash, b.dhash) / dBits) : 0;
  const p = pBits ? resc(1 - hamming(a.phash, b.phash) / pBits) : 0;
  const r = (Array.isArray(a.rgbSig) && a.rgbSig.length
    && Array.isArray(b.rgbSig) && b.rgbSig.length)
    ? blockSim(a.rgbSig, b.rgbSig) : 0;

  let dot = 0;
  const ln = Math.min(a.lumaSig?.length || 0, b.lumaSig?.length || 0);
  for (let i = 0; i < ln; i++) dot += a.lumaSig[i] * b.lumaSig[i];
  const l = ln ? Math.max(0, Math.min(1, (Math.max(-1, Math.min(1, dot)) + 1) / 2)) : 0;

  // ⚠️ اگر `rgbSig` نباشد (اثرانگشتِ قدیمیِ backfill‌نشده) به فرمولِ
  //    عمومی برمی‌گردیم — بهتر از نمرهٔ صفرِ ساختگی.
  if (!r) return similarity(a, b);
  return 0.28 * d + 0.20 * p + 0.32 * r + 0.20 * l;
}

function matchAgainst(queryFp, designs) {
  if (!designs.length) {
    return { verdict: 'reject', design: null, score: 0, margin: 0, ranked: [] };
  }
  const ranked = designs
    // `combinedSimilarity` و نه `similarity` خام: شواهدِ متنی باید در
    // رتبه‌بندی اثر بگذارد، وگرنه کلِ OCR بی‌مصرف است.
    .map(d => ({ design: d, score: combinedSimilarity(queryFp, d) }))
    .sort((x, y) => y.score - x.score);

  const best = ranked[0];
  const second = ranked.length > 1 ? ranked[1].score : 0;
  const margin = ranked.length > 1 ? best.score - second : 1;

  // ═══════════════════════════════════════════════════════════════════════
  // چرا حاشیهٔ **نسبی** و نه مطلق
  // ═══════════════════════════════════════════════════════════════════════
  //
  // حاشیهٔ مطلقِ ۰.۰۲ در دو موقعیتِ کاملاً متفاوت یک معنی می‌داد:
  //
  //   امتیاز ۰.۹۵ در برابر ۰.۹۳ → اختلافِ ۲٪ از یک عددِ بزرگ. تصویر
  //   واضح است و موتور واقعاً بین دو گزینه شک دارد؟ نه — هر دو خیلی
  //   شبیه‌اند ولی اولی محسوس بهتر است.
  //
  //   امتیاز ۰.۶۲ در برابر ۰.۶۰ → همان ۰.۰۲، ولی اینجا هر دو ضعیف‌اند
  //   و ۰.۰۲ در محدودهٔ نویز است.
  //
  // اندازه‌گیری این را ثابت کرد: در آزمایشی با ۲۴ طرح که بعضی فقط ۱۰
  // درجه اختلافِ رنگ داشتند، **۶ تطبیقِ غلط** با حاشیهٔ ۰.۰۲۸ تا ۰.۰۵۱
  // تأیید شدند — یعنی از شرطِ مطلق رد شدند ولی همه غلط بودند.
  //
  // این دقیقاً سناریوی واقعیِ خطرناک است: دو کارت از یک تیم با
  // پس‌زمینهٔ یکسان و فقط تفاوتِ جزئی.
  //
  // نسبتِ `best/second` این را می‌گیرد: ۰.۶۰۴/۰.۵۶۸ = ۱.۰۶ (ضعیف)
  // در برابر ۰.۹۵/۰.۷۰ = ۱.۳۶ (قاطع). آستانهٔ ۱.۱۵ یعنی «رتبهٔ اول
  // باید دست‌کم ۱۵٪ بهتر از دوم باشد».
  const ratio = second > 1e-6 ? best.score / second : Infinity;

  let verdict;
  if (best.score >= ACCEPT_SCORE
      && margin >= MIN_MARGIN
      && ratio >= MIN_RATIO) {
    verdict = 'accept';
  } else if (best.score >= REVIEW_SCORE) {
    verdict = 'review';
  } else {
    verdict = 'reject';
  }

  return {
    verdict,
    design: best.design,
    score: best.score,
    margin,
    ratio: Number.isFinite(ratio) ? ratio : 99,
    // ── «آیا موتور می‌تواند انتخاب کند؟» ──
    //
    // این از `verdict` جداست و تفکیکشان مهم است:
    //
    //   verdict  = «چقدر شبیه است؟»  (نمرهٔ مطلق)
    //   decisive = «کدام‌یک؟»         (رتبهٔ اول در برابر دوم)
    //
    // دو طرح می‌توانند هر دو نمرهٔ ۰.۴۵ بگیرند: به‌اندازهٔ کافی شبیه‌اند
    // ولی موتور نمی‌داند کدام‌یک است. تأییدِ خودکار در آن حالت یعنی
    // انتخابِ تصادفی — و کاربر امتیازِ کارتِ اشتباه می‌گیرد.
    //
    // مصرف‌کننده‌اش `decideSubmission` است که آستانهٔ نمره را جدا
    // اعمال می‌کند. اینجا فقط قاطعیت گزارش می‌شود.
    decisive: margin >= MIN_MARGIN && ratio >= MIN_RATIO,
    ranked: ranked.slice(0, 3),
  };
}

