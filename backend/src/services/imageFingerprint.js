//
// با فرمولِ پنج‌سیگناله، ۱.۰۵ همچنان صفر خطا می‌دهد و ۷ موردِ بیشتر
// را خودکار تأیید می‌کند. سخت‌گیرترشدن فقط کاربرانِ درستکار را به صف
