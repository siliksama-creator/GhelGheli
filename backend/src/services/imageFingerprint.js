const MIN_RATIO = 1.05;

/**
 * حذفِ حاشیهٔ یکنواخت دور تصویر.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * چرا این حیاتی است
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * وقتی کاربر عکس را کج می‌گیرد، ما تصویر را می‌چرخانیم و گوشه‌ها با
 * رنگِ پس‌زمینه پر می‌شوند. آن حاشیه‌ها بخشی از کارت نیستند ولی وارد
 * محاسبه می‌شوند و **کلِ شبکه را جابه‌جا می‌کنند**: پیکسلی که باید
 * وسطِ کارت باشد می‌افتد گوشه.
 *
 * اندازه‌گیری روی ۱۰۰ عکسِ آزمایشی نشان داد dHash در سناریوی «زاویهٔ
 * شدید» به ۰.۵۳۸ می‌افتد — یعنی تقریباً تصادفی — در حالی که امضای رنگ
 * ۰.۸۴۸ می‌ماند. علتش همین جابه‌جاییِ شبکه بود، نه از دست رفتنِ اطلاعات.
 *
 * `trim` حاشیهٔ هم‌رنگ را می‌برد و کادر را دوباره روی خودِ کارت می‌بندد.
 * آستانهٔ ۱۲ سخاوتمندانه است چون حاشیهٔ عکسِ واقعی هرگز کاملاً یکدست
 * نیست (نویز دوربین).
 *
 * `failOn:'none'` لازم است: اگر تصویر تماماً یکنواخت باشد trim خطا
 * می‌دهد و ما ترجیح می‌دهیم تصویرِ اصلی را نگه داریم تا کلِ درخواست
 * بشکند.
 */
function prepared(buf) {
  return sharp(buf, { failOn: 'none' })
    .rotate()          // اعمال EXIF؛ عکس گوشی اغلب چرخیده ذخیره می‌شود
    .removeAlpha()
    .trim({ threshold: 12 });
}

/** میانگین‌گیری و نرمال‌سازی روشنایی روی یک تصویرِ خاکستریِ size×size. */
async function grayNormalized(buf, size) {
  let data;
  try {
    ({ data } = await prepared(buf)
      .greyscale()
      .resize(size, size, { fit: 'fill', kernel: 'lanczos3' })
      .raw()
      .toBuffer({ resolveWithObject: true }));
  } catch {
    // trim روی تصویرِ یکنواخت شکست می‌خورد؛ بدونِ آن ادامه بده.
    ({ data } = await sharp(buf, { failOn: 'none' })
      .rotate().removeAlpha().greyscale()
      .resize(size, size, { fit: 'fill', kernel: 'lanczos3' })
      .raw()
      .toBuffer({ resolveWithObject: true }));
  }

  // کشش کنتراست بین صدک ۲ و ۹۸.
  //
  // چرا صدک و نه کمینه/بیشینه: یک پیکسلِ سوختهٔ فلاش یا یک نقطهٔ کاملاً
  // سیاه کلِ بازه را می‌کشد و نرمال‌سازی را بی‌اثر می‌کند. صدک به آن
  // نقاطِ پرت مصون است.
  //
  // این مرحله همان چیزی است که عکسِ تاریکِ کاربر را با عکسِ روشنِ مدیر
  // قابل مقایسه می‌کند. بدون آن، هر معیار فاصله‌ای فقط اختلافِ نور را
  // اندازه می‌گیرد.
  const hist = new Uint32Array(256);
  for (let i = 0; i < data.length; i++) hist[data[i]]++;
  const total = data.length;
  let lo = 0; let hi = 255; let acc = 0;
  for (let v = 0; v < 256; v++) { acc += hist[v]; if (acc >= total * 0.02) { lo = v; break; } }
  acc = 0;
  for (let v = 255; v >= 0; v--) { acc += hist[v]; if (acc >= total * 0.02) { hi = v; break; } }
  const span = Math.max(1, hi - lo);

  const out = new Float32Array(total);
  for (let i = 0; i < total; i++) {
    out[i] = Math.min(1, Math.max(0, (data[i] - lo) / span));
  }
  return out;
}

/** dHash: هر پیکسل با همسایهٔ راستش. خروجی ۳۲ بایت. */
async function dhash(buf) {
  const n = DHASH_N;
  const g = await grayNormalized(buf, n + 1);
  const bits = [];
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      bits.push(g[y * (n + 1) + x + 1] > g[y * (n + 1) + x] ? 1 : 0);
    }
  }
  return packBits(bits);
}

// جدولِ کسینوس از پیش محاسبه‌شده.
//
// DCT دوبعدی روی ۳۲×۳۲ یعنی حدود یک میلیون فراخوانی Math.cos به‌ازای هر
// تصویر. با جدول، این به یک ضرب ماتریسی ساده تبدیل می‌شود. برای ۱۵۰ طرح
// در هر درخواستِ تطبیق، تفاوتش محسوس است.
const DCT_COS = (() => {
  const n = PHASH_N;
  const t = new Float32Array(n * n);
  for (let k = 0; k < n; k++) {
    for (let i = 0; i < n; i++) {
      t[k * n + i] = Math.cos(((2 * i + 1) * k * Math.PI) / (2 * n));
    }
  }
  return t;
})();

/** pHash: ضرایب DCT فرکانس پایین. خروجی ۸ بایت. */
async function phash(buf) {
  const n = PHASH_N;
  const k = PHASH_K;
  const g = await grayNormalized(buf, n);

  // DCT جداشدنی: اول روی سطرها، بعد روی ستون‌ها. O(n³) به‌جای O(n⁴).
  const tmp = new Float32Array(n * n);
  for (let y = 0; y < n; y++) {
    for (let u = 0; u < k; u++) {
      let s = 0;
      for (let x = 0; x < n; x++) s += g[y * n + x] * DCT_COS[u * n + x];
      tmp[y * n + u] = s;
    }
  }
  const coef = new Float32Array(k * k);
  for (let u = 0; u < k; u++) {
    for (let v = 0; v < k; v++) {
      let s = 0;
      for (let y = 0; y < n; y++) s += tmp[y * n + u] * DCT_COS[v * n + y];
      coef[v * k + u] = s;
    }
  }

  // ضریب [0][0] انرژیِ کل (روشناییِ میانگین) است و دور ریخته می‌شود؛
  // وگرنه هش عمدتاً «چقدر روشن است» را کد می‌کند نه «چه شکلی است».
  const vals = Array.from(coef).slice(1);
  const sorted = [...vals].sort((a, b) => a - b);
  const median = sorted[sorted.length >> 1];
  return packBits(vals.map(v => (v > median ? 1 : 0)));
}

/**
 * امضای رنگ: هیستوگرام hue در شبکهٔ ۴×۴، وزن‌دار با اشباع و روشنایی.
 *
 * وزن‌دهی مهم است: پیکسلِ خاکستری یا خیلی تاریک hue بی‌معنایی دارد
 * (نویزِ محاسباتی). بدون وزن، سایه‌های تیرهٔ یک کارت به سطل‌های تصادفی
 * می‌ریزند و امضا را بی‌ثبات می‌کنند.
 */
async function colorSignature(buf) {
  const S = 128;
  let data;
  try {
    ({ data } = await prepared(buf)
      .resize(S, S, { fit: 'fill', kernel: 'lanczos3' })
      .raw()
      .toBuffer({ resolveWithObject: true }));
  } catch {
    ({ data } = await sharp(buf, { failOn: 'none' })
      .rotate().removeAlpha()
      .resize(S, S, { fit: 'fill', kernel: 'lanczos3' })
      .raw()
      .toBuffer({ resolveWithObject: true }));
  }

  const grid = COLOR_GRID;
  const bins = COLOR_BINS;
  const step = S / grid;
  const sig = new Float32Array(grid * grid * bins);

  for (let y = 0; y < S; y++) {
    const gy = Math.min(grid - 1, Math.floor(y / step));
    for (let x = 0; x < S; x++) {
      const i = (y * S + x) * 3;
      const r = data[i] / 255; const g = data[i + 1] / 255; const b = data[i + 2] / 255;
      const max = Math.max(r, g, b); const min = Math.min(r, g, b);
      const d = max - min;
      if (d < 1e-6) continue;                 // خاکستری: hue ندارد
      let h;
      if (max === r) h = ((g - b) / d) % 6;
      else if (max === g) h = (b - r) / d + 2;
      else h = (r - g) / d + 4;
      h = ((h * 60) + 360) % 360;

      const sat = d / max;
      const w = sat * max;                    // اشباع × روشنایی
      if (w < 0.02) continue;

      const gx = Math.min(grid - 1, Math.floor(x / step));
      const cell = (gy * grid + gx) * bins;

      // ── سطل‌بندی نرم و دایره‌ای ──
      //
      // نسخهٔ اول هر پیکسل را در یک سطلِ سخت می‌انداخت. مشکل واقعی
      // (که تست گرفت، نه حدس): تغییر روشنایی hue را کمی جابه‌جا
      // می‌کند، و اگر رنگ نزدیک مرزِ دو سطل باشد کلِ وزنش به سطل
      // بغلی می‌پرد. آن‌وقت دو عکسِ *یک کارت* در نور متفاوت، امضای
      // کاملاً متفاوت پیدا می‌کنند.
      //
      // اندازه‌گیری: عکسِ پرنورِ طرح ۰ به طرح ۱ نزدیک‌تر شد
      // (۰.۷۸۸) تا به خودش (۰.۷۲۶) — یعنی تطبیقِ غلط.
      //
      // راه‌حل: وزن بین دو سطل مجاور تقسیم می‌شود، به نسبت فاصله.
      // جابه‌جایی کوچکِ hue حالا وزن را کمی جابه‌جا می‌کند نه اینکه
      // یکجا پرت کند.
      //
      // «دایره‌ای» چون hue حلقه است: قرمزِ ۳۵۹ درجه و قرمزِ ۱ درجه
      // همسایه‌اند. با `%bins` سطل آخر به سطل اول وصل می‌شود.
      const pos = (h / 360) * bins;
      const b0 = Math.floor(pos) % bins;
      const b1 = (b0 + 1) % bins;
      const frac = pos - Math.floor(pos);
      sig[cell + b0] += w * (1 - frac);
      sig[cell + b1] += w * frac;
    }
  }

  // نرمال‌سازی هر خانه جداگانه: خانهٔ روشن نباید بر خانهٔ تاریک غالب شود.
  for (let c = 0; c < grid * grid; c++) {
    let s = 0;
    for (let b = 0; b < bins; b++) s += sig[c * bins + b];
    if (s > 1e-9) for (let b = 0; b < bins; b++) sig[c * bins + b] /= s;
  }
  // نرمال‌سازی L2 کل بردار تا شباهت کسینوسی معنا داشته باشد.
  let norm = 0;
  for (let i = 0; i < sig.length; i++) norm += sig[i] * sig[i];
  norm = Math.sqrt(norm);
  if (norm > 1e-9) for (let i = 0; i < sig.length; i++) sig[i] /= norm;
  return Array.from(sig);
}


// ═══════════════════════════════════════════════════════════════════════════
// سیگنال چهارم: بافتِ شعاعی (radial gradient histogram)
// ═══════════════════════════════════════════════════════════════════════════
//
// ── چرا سه سیگنالِ قبلی کافی نبودند ──
//
// اندازه‌گیری روی ۱۰۰ عکسِ شبیه‌سازی‌شده نشان داد در سناریوی «زاویهٔ
// شدید» (کاربر از پهلو عکس می‌گیرد):
//
//     dHash ۰.۵۳۸  ·  pHash ۰.۵۷۲  ·  رنگ ۰.۸۴۸
//
// dHash و pHash هر دو روی یک **شبکهٔ ثابت** کار می‌کنند. وقتی تصویر
// می‌چرخد یا کج می‌شود، پیکسل‌ها بین خانه‌ها جابه‌جا می‌شوند و هر دو
// عملاً به تصادف نزدیک می‌شوند (۰.۵ = سکه انداختن).
//
// ── چرا این یکی مقاوم است ──
//
// به‌جای «شدتِ پیکسل در خانهٔ (x,y)»، توزیعِ **اندازهٔ گرادیان** را در
// چند حلقهٔ هم‌مرکز می‌سنجد. چرخش، پیکسل‌ها را داخل همان حلقه جابه‌جا
// می‌کند نه بینِ حلقه‌ها — پس امضا تقریباً ثابت می‌ماند.
//
// و چون گرادیان است (تفاوتِ همسایه‌ها، نه مقدارِ مطلق)، مثل dHash در
// برابر تغییرِ نور مصون است. یعنی نقطهٔ قوتِ dHash را دارد بدون
// نقطه‌ضعفِ شبکهٔ ثابتش.
//
// ۴ حلقه × ۸ سطلِ اندازه = ۳۲ عدد. کوچک است چون فقط نقشِ «داورِ
// شکست» را دارد، نه سیگنالِ اصلی.
const RING_COUNT = 4;
const MAG_BINS = 8;

async function radialTexture(buf) {
  const S = 64;
  const g = await grayNormalized(buf, S);

  const sig = new Float32Array(RING_COUNT * MAG_BINS);
  const cx = (S - 1) / 2;
  const cy = (S - 1) / 2;
  const maxR = Math.hypot(cx, cy);

  for (let y = 1; y < S - 1; y++) {
    for (let x = 1; x < S - 1; x++) {
      // سوبل سادهٔ ۳×۳
      const gx = g[y * S + x + 1] - g[y * S + x - 1];
      const gy = g[(y + 1) * S + x] - g[(y - 1) * S + x];
      const mag = Math.hypot(gx, gy);
      if (mag < 0.02) continue;

      const r = Math.hypot(x - cx, y - cy) / maxR;
      const ring = Math.min(RING_COUNT - 1, Math.floor(r * RING_COUNT));
      // اندازهٔ گرادیان تا ~۲ می‌رود؛ سقف می‌گذاریم تا لبه‌های تیز
      // کلِ هیستوگرام را نبلعند.
      const bin = Math.min(MAG_BINS - 1, Math.floor(Math.min(mag, 1) * MAG_BINS));
      sig[ring * MAG_BINS + bin] += mag;
    }
  }

  // نرمال‌سازی هر حلقه جداگانه: حلقهٔ بیرونی پیکسلِ بیشتری دارد و
  // بدون این، همیشه بر بقیه غالب می‌شد.
  for (let ring = 0; ring < RING_COUNT; ring++) {
    let sum = 0;
    for (let b = 0; b < MAG_BINS; b++) sum += sig[ring * MAG_BINS + b];
    if (sum > 1e-9) {
      for (let b = 0; b < MAG_BINS; b++) sig[ring * MAG_BINS + b] /= sum;
    }
  }
  let norm = 0;
  for (let i = 0; i < sig.length; i++) norm += sig[i] * sig[i];
  norm = Math.sqrt(norm);
  if (norm > 1e-9) for (let i = 0; i < sig.length; i++) sig[i] /= norm;
  return Array.from(sig);
}


// ═══════════════════════════════════════════════════════════════════════════
// سیگنال پنجم: نقشهٔ روشناییِ درشت (coarse luminance map)
// ═══════════════════════════════════════════════════════════════════════════
//
// ── چرا لازم شد ──
//
// اندازه‌گیریِ سهمِ هر سیگنال روی عکس‌های بد این را نشان داد:
//
//     سناریو    dHash  pHash  رنگ    بافت
//     خوب       ۰.۴۲   ۰.۵۱   ۰.۹۸   ۰.۸۳
//     بد        ۰.۱۲   ۰.۲۷   ۰.۹۰   ۰.۶۹
//     فلاش      ۰.۲۳   ۰.۴۰   ۰.۷۸   ۰.۷۱
//
// dHash و pHash روی عکسِ واقعیِ گوشی عملاً بی‌فایده‌اند (زیر ۰.۳).
// علتش این است که هر دو **باینری** هستند: یک بیت یا درست است یا غلط،
// و تاری و فشرده‌سازیِ JPEG آن بیت‌ها را تصادفی می‌کند.
//
// ولی اطلاعاتِ ساختاری هنوز در تصویر هست — فقط نه در قالبِ بیت. اگر
// به‌جای «آیا این پیکسل روشن‌تر از بغلی است؟» بپرسیم «میانگینِ روشناییِ
// این ناحیه چقدر است؟»، جواب در برابر تاری پایدار می‌ماند چون تاری
// دقیقاً همان میانگین‌گیری است.
//
// ── چرا این با pHash فرق دارد ──
//
// pHash هم از روشنایی می‌آید ولی نتیجه را به بیت تبدیل می‌کند و
// اطلاعاتِ «چقدر» را دور می‌ریزد. اینجا مقدارِ پیوسته نگه داشته
// می‌شود و با شباهتِ کسینوسی مقایسه می‌شود — پس اختلافِ کوچک به‌جای
// «غلط» به‌صورت «کمی کمتر» ظاهر می‌شود.
//
// ── چرا نرمال‌سازی به میانگینِ صفر ──
//
// عکسِ تاریک و عکسِ پرنور از یک کارت، نقشهٔ روشناییِ یکسانی دارند که
// فقط جابه‌جا شده. کم کردنِ میانگین آن جابه‌جایی را حذف می‌کند، پس
// «فلاشِ سوخته» و «تاریکِ شدید» هر دو به همان امضا می‌رسند.
//
// شبکهٔ ۸×۸ = ۶۴ عدد. ریزتر از این نویزِ JPEG را می‌گیرد، درشت‌تر
// تمایز را از دست می‌دهد.
const LUMA_GRID = 8;

async function lumaMap(buf) {
  const n = LUMA_GRID;
  const g = await grayNormalized(buf, n);

  // میانگین را کم کن تا نسبت به روشناییِ کلی مصون شود.
  let mean = 0;
  for (let i = 0; i < g.length; i++) mean += g[i];
  mean /= g.length;

  const out = new Float32Array(g.length);
  let norm = 0;
  for (let i = 0; i < g.length; i++) {
    out[i] = g[i] - mean;
    norm += out[i] * out[i];
  }
  norm = Math.sqrt(norm);
  // تصویرِ کاملاً یکنواخت: بردارِ صفر. شباهتش با هر چیزی صفر می‌شود،
  // که درست است — چنین عکسی هیچ اطلاعاتی ندارد.
  if (norm > 1e-9) for (let i = 0; i < out.length; i++) out[i] /= norm;
  return Array.from(out);
}

function packBits(bits) {
  const out = Buffer.alloc(Math.ceil(bits.length / 8));
  for (let i = 0; i < bits.length; i++) {
    if (bits[i]) out[i >> 3] |= 0x80 >> (i & 7);
  }
  return out;
}

const POPCOUNT = (() => {
  const t = new Uint8Array(256);
  for (let i = 0; i < 256; i++) t[i] = (i & 1) + t[i >> 1];
  return t;
})();

function hamming(a, b) {
  const n = Math.min(a.length, b.length);
  let d = 0;
  for (let i = 0; i < n; i++) d += POPCOUNT[a[i] ^ b[i]];
  return d;
}

/** اثر انگشت کامل یک تصویر. */
async function fingerprint(buf) {
  const meta = await sharp(buf, { failOn: 'none' }).metadata();
  const [d, p, c, t, l] = await Promise.all([
    dhash(buf), phash(buf), colorSignature(buf), radialTexture(buf),
    lumaMap(buf),
  ]);
  return {
    version: FP_VERSION,
    dhash: d,
    phash: p,
    colorSig: c,
    texSig: t,
    lumaSig: l,
    width: meta.width || 0,
    height: meta.height || 0,
  };
}

/**
 * شباهت دو اثر انگشت، عددی بین ۰ و ۱.
 *
 * وزن‌ها: رنگ ۰.۴۰، dHash ۰.۳۰، pHash ۰.۳۰.
 *
 * چرا رنگ بیشترین وزن را دارد: در آزمایش، رنگ پایدارترین سیگنال روی
 * عکس‌های واقعاً بد بود (۰.۹۲ حتی روی نمونه‌ای که dHash فقط ۰.۵۴ داد).
 * کارت‌های فوتبالی پالت‌های بسیار متمایز دارند — پیراهنِ تیم — و این
 * دقیقاً همان چیزی است که از تاری و کم‌نوری جان سالم به در می‌برد.
 */
function similarity(a, b) {
  const dBits = Math.min(a.dhash.length, b.dhash.length) * 8;
  const pBits = Math.min(a.phash.length, b.phash.length) * 8;

  // ── چرا dHash و pHash بازمقیاس می‌شوند ──
  //
  // هشِ باینری کفِ ۰.۵ دارد، نه ۰: دو تصویرِ کاملاً بی‌ربط هم به‌طور
  // میانگین نیمی از بیت‌هایشان تصادفاً یکی است. پس «۰.۵۵» در عمل یعنی
  // «تقریباً هیچ شباهتی»، ولی در فرمولِ قبلی مثل «نیمی شبیه» وزن
  // می‌گرفت و امتیازِ نهایی را مصنوعی بالا نگه می‌داشت.
  //
  // با بازمقیاس به بازهٔ [۰,۱]، عددی که این دو می‌دهند معنای واقعی
  // پیدا می‌کند: ۰.۵ خام → ۰ نهایی.
  const rescale = v => Math.max(0, (v - 0.5) * 2);
  const dScore = dBits ? rescale(1 - hamming(a.dhash, b.dhash) / dBits) : 0;
  const pScore = pBits ? rescale(1 - hamming(a.phash, b.phash) / pBits) : 0;

  const cos = (x, y) => {
    if (!x || !y) return 0;
    let dot = 0;
    const n = Math.min(x.length, y.length);
    for (let i = 0; i < n; i++) dot += x[i] * y[i];
    return Math.max(0, Math.min(1, dot));
  };
  const cScore = cos(a.colorSig, b.colorSig);
  // بافتِ شعاعی ممکن است در اثرانگشت‌های قدیمی نباشد (قبل از نسخهٔ ۲).
  // در آن حالت وزنش به رنگ منتقل می‌شود تا مجموع همیشه ۱ بماند و
  // طرح‌های قدیمی بی‌دلیل امتیازِ کمتری نگیرند.
  const hasTex = Array.isArray(a.texSig) && Array.isArray(b.texSig)
    && a.texSig.length > 0 && b.texSig.length > 0;
  const tScore = hasTex ? cos(a.texSig, b.texSig) : 0;

  // ══════════════════════════════════════════════════════════════════════
  // وزن‌ها از جست‌وجوی شبکه‌ای + اعتبارسنجیِ متقاطع روی دو مجموعه
  // ══════════════════════════════════════════════════════════════════════
  //
  // ── چرا هش‌ها وزنِ کمی دارند ──
  //
  // اندازه‌گیریِ سهمِ هر سیگنال روی عکس‌های شبیه‌سازی‌شدهٔ گوشی:
  //
  //     سناریو    dHash  pHash  رنگ    بافت   روشنایی
  //     خوب       ۰.۴۲   ۰.۵۱   ۰.۹۸   ۰.۸۳   ۰.۹۰
  //     بد        ۰.۱۲   ۰.۲۷   ۰.۹۰   ۰.۶۹   ۰.۷۲
  //     فلاش      ۰.۲۳   ۰.۴۰   ۰.۷۸   ۰.۷۱   ۰.۷۵
  //
  // dHash و pHash روی عکسِ واقعی زیر ۰.۳ می‌افتند چون **باینری**اند:
  // یک بیت یا درست است یا غلط، و تاری و فشرده‌سازیِ JPEG آن بیت‌ها را
  // تصادفی می‌کند. سیگنال‌های پیوسته (رنگ، بافت، روشنایی) همان
  // اطلاعات را نگه می‌دارند چون «کمی متفاوت» به‌جای «غلط» ثبت می‌شود.
  //
  // ولی صفر هم نمی‌شوند: روی عکسِ **باکیفیت** هش‌ها دقیق‌ترین سیگنالند
  // (۰.۸۱ و ۰.۹۵) و در تفکیکِ دو طرحِ هم‌رنگ نقشِ تعیین‌کننده دارند.
  //
  // ── دو مجموعهٔ آزمایشی، عمداً متفاوت ──
  //
  //   الف) ۲۴ طرحِ ساختگی که بعضی فقط ۱۰ درجه اختلافِ رنگ دارند
  //   ب)  کارت‌های واقعیِ قلقلی با ۱۱ چرخشِ رنگ
  //
  // نتیجهٔ نامزدها (تأییدِ خودکار، همه با صفر خطا):
  //
  //     وزن‌ها                          الف      ب
  //     ۰.۳۰/۰.۱۵/۰.۴۰/۰.۱۵/۰ (قبلی)   ۵۲٪     ۷۴٪
  //     ۰.۳۰/۰/۰.۴۰/۰/۰.۳۰             ۶۹٪     ۷۷٪
  //     ۰.۲۵/۰.۱۰/۰.۳۵/۰.۱۰/۰.۲۰       ۶۳٪     ۸۰٪  ← انتخاب‌شده
  //
  // ترکیبِ سوم انتخاب شد چون روی هر دو مجموعه بهبود می‌دهد و **هر پنج
  // سیگنال را زنده نگه می‌دارد**. حذفِ کاملِ pHash و بافت (ترکیبِ دوم)
  // روی مجموعهٔ الف کمی بهتر بود ولی نقطهٔ کورِ آن دو را بی‌پوشش
  // می‌گذاشت — و کاتالوگِ واقعیِ آینده ممکن است شبیهِ هیچ‌کدام از این
  // دو مجموعه نباشد.
  //
  // ⚠️ این اعداد با آستانه‌ها جفت‌اند. تغییرشان بدون اجرای دوبارهٔ
  //    `scripts/benchPhotoMatch.js` یعنی حدس زدن.
  const hasLuma = Array.isArray(a.lumaSig) && Array.isArray(b.lumaSig)
    && a.lumaSig.length > 0 && b.lumaSig.length > 0;
  const lScore = hasLuma ? cos(a.lumaSig, b.lumaSig) : 0;

  if (hasTex && hasLuma) {
    return 0.25 * dScore + 0.10 * pScore + 0.35 * cScore
         + 0.10 * tScore + 0.20 * lScore;
  }
  // ── بازگشتِ تدریجی برای اثرانگشت‌های قدیمی ──
  //
  // وزنِ سیگنالِ غایب بینِ بقیه پخش می‌شود تا مجموع همیشه ۱ بماند.
  // بدون این، طرحی که هنوز backfill نشده امتیازِ کمتری می‌گرفت و
  // بی‌دلیل به صف بررسی می‌رفت — دقیقاً باگی که با texSig رخ داد.
  if (hasTex) {
    return 0.30 * dScore + 0.15 * pScore + 0.40 * cScore + 0.15 * tScore;
  }
  if (hasLuma) {
    return 0.28 * dScore + 0.12 * pScore + 0.35 * cScore + 0.25 * lScore;
  }
  return 0.35 * dScore + 0.18 * pScore + 0.47 * cScore;
}

/**
 * بهترین طرحِ منطبق را پیدا می‌کند و تصمیم می‌گیرد.
 *
 * خروجی: { verdict, design, score, margin, ranked }
 *   verdict = 'accept' | 'review' | 'reject'
 *
 * چرا حاشیه هم شرط است: اگر دو طرح تقریباً هم‌امتیاز باشند، حتی امتیازِ
 * بالا هم قابل اتکا نیست — ممکن است طرحِ اشتباه با اختلاف ناچیز برنده
 * شده باشد و کاربر کارتِ گران‌تری بگیرد که مالِ او نیست.
 */
function matchAgainst(queryFp, designs) {
  if (!designs.length) {
    return { verdict: 'reject', design: null, score: 0, margin: 0, ranked: [] };
  }
  const ranked = designs
    .map(d => ({ design: d, score: similarity(queryFp, d) }))
    .sort((x, y) => y.score - x.score);

  const best = ranked[0];
  const second = ranked.length > 1 ? ranked[1].score : 0;
  const margin = ranked.length > 1 ? best.score - second : 1;

  // ═══════════════════════════════════════════════════════════════════════
  // چرا حاشیهٔ **نسبی** و نه مطلق
  // ═══════════════════════════════════════════════════════════════════════
  //
  // حاشیهٔ مطلقِ ۰.۰۲ در دو موقعیتِ کاملاً متفاوت یک معنی می‌داد:
  //
  //   امتیاز ۰.۹۵ در برابر ۰.۹۳ → اختلافِ ۲٪ از یک عددِ بزرگ. تصویر
  //   واضح است و موتور واقعاً بین دو گزینه شک دارد؟ نه — هر دو خیلی
  //   شبیه‌اند ولی اولی محسوس بهتر است.
  //
  //   امتیاز ۰.۶۲ در برابر ۰.۶۰ → همان ۰.۰۲، ولی اینجا هر دو ضعیف‌اند
  //   و ۰.۰۲ در محدودهٔ نویز است.
  //
  // اندازه‌گیری این را ثابت کرد: در آزمایشی با ۲۴ طرح که بعضی فقط ۱۰
  // درجه اختلافِ رنگ داشتند، **۶ تطبیقِ غلط** با حاشیهٔ ۰.۰۲۸ تا ۰.۰۵۱
  // تأیید شدند — یعنی از شرطِ مطلق رد شدند ولی همه غلط بودند.
  //
  // این دقیقاً سناریوی واقعیِ خطرناک است: دو کارت از یک تیم با
  // پس‌زمینهٔ یکسان و فقط تفاوتِ جزئی.
  //
  // نسبتِ `best/second` این را می‌گیرد: ۰.۶۰۴/۰.۵۶۸ = ۱.۰۶ (ضعیف)
  // در برابر ۰.۹۵/۰.۷۰ = ۱.۳۶ (قاطع). آستانهٔ ۱.۱۵ یعنی «رتبهٔ اول
  // باید دست‌کم ۱۵٪ بهتر از دوم باشد».
  const ratio = second > 1e-6 ? best.score / second : Infinity;

  let verdict;
  if (best.score >= ACCEPT_SCORE
      && margin >= MIN_MARGIN
      && ratio >= MIN_RATIO) {
    verdict = 'accept';
  } else if (best.score >= REVIEW_SCORE) {
    verdict = 'review';
  } else {
    verdict = 'reject';
  }

  return {
    verdict,
    design: best.design,
    score: best.score,
    margin,
    ratio: Number.isFinite(ratio) ? ratio : 99,
    ranked: ranked.slice(0, 3),
  };
}

