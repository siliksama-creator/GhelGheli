//
//     تطبیقِ درست : میانگین ۰.۷۷۷ · کمینه ۰.۶۱۵ · صدک۵ ۰.۶۳۴
//     تطبیقِ غلط  : میانگین ۰.۳۷۲ · صدک۹۹ ۰.۷۳۴ · بیشینه ۰.۹۷۷
//
// ── چرا امتیازِ تنها کافی نیست ──
//
// بیشینهٔ «غلط» ۰.۹۷۷ است. یعنی هیچ آستانه‌ای روی امتیاز نمی‌تواند
// تضمین کند تطبیقِ غلط رد شود — دو طرحِ واقعاً شبیه (مثلاً دو بازیکن
// از یک تیم با پس‌زمینهٔ یکسان) ذاتاً امتیازِ بالا می‌گیرند.
//
// **حاشیه** این را حل می‌کند: اگر طرحِ اول و دوم تقریباً هم‌امتیاز
// باشند، موتور نمی‌تواند بینشان تصمیم بگیرد و پرونده به مدیر می‌رود.
// در همان آزمایش، تنها موردِ نادرست حاشیهٔ ۰.۰۰۷ داشت — یعنی شرطِ
// حاشیه دقیقاً همان یکی را گرفت.
//
// جدولِ ترکیبِ دو شرط (تأییدِ خودکار / تطبیقِ غلطِ تأییدشده):
//
//     امتیاز ۰.۶۰ + حاشیه ۰.۰۲  →  ۷۸٪  /  ۰   ← انتخاب‌شده
//     امتیاز ۰.۶۵ + حاشیه ۰.۰۲  →  ۷۱٪  /  ۰
//     امتیاز ۰.۶۰ + حاشیه ۰.۰۵  →  ۴۱٪  /  ۰
//
// ۰.۶۰/۰.۰۲ بیشترین تأییدِ خودکار را با صفر خطا می‌دهد. سخت‌گیرترشدن
// فقط کاربرانِ درستکار را به صف بررسی می‌فرستد بدون اینکه امنیتی
// اضافه کند.
//
// ⚠️ این اعداد به فرمولِ `similarity` گره خورده‌اند. اگر وزن‌ها یا
//    سیگنال‌ها عوض شوند، باید دوباره اندازه‌گیری شوند — نه تنظیمِ
//    دستی. اسکریپت: scripts/benchPhotoMatch.js
const ACCEPT_SCORE = 0.55;   // بالاتر + حاشیهٔ کافی: خودکار بپذیر
const REVIEW_SCORE = 0.45;   // بین این دو: صف بررسی مدیر

// ── چرا آستانهٔ رد این‌قدر پایین است ──
//
// خواستهٔ صریح مالک: وقتی کد **معتبر** است، عکسِ ناشناخته نباید رد
// شود بلکه باید به مدیر برود. پس عملاً مسیرِ کاربر هرگز به `reject`
// نمی‌رسد؛ این آستانه فقط برای تشخیصِ «کاملاً بی‌ربط» (نویز، عکسِ
// سقف) در گزارشِ مدیر به کار می‌آید.

// حاشیه تا رتبهٔ دوم. تنها شرطی که تطبیقِ غلط را واقعاً می‌گیرد.
const MIN_MARGIN = 0.02;

// نسبتِ رتبهٔ اول به دوم. رتبهٔ اول باید دست‌کم ۶٪ بهتر باشد.
//
// این شرط چیزی را می‌گیرد که حاشیهٔ مطلق نمی‌گرفت: دو طرحِ بسیار شبیه
// (مثلاً دو کارت از یک تیم) که هر دو امتیازِ متوسط می‌گیرند و اختلافشان
// در محدودهٔ نویز است.
//
// عدد از جدولِ زیر آمد (روی سخت‌ترین مجموعه، ۲۴ طرح با اختلافِ رنگِ
