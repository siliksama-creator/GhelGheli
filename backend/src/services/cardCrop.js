/**
 * بریدنِ خودکارِ کارت از پس‌زمینه.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * چرا این ماژول لازم شد
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * عکسِ واقعیِ یک کاربر بررسی شد: کارتِ دمبله روی میزِ چوبی، و **حدود ۴۰٪
 * کادر را خودِ میز گرفته بود**. نتیجه‌اش این بود که موتور رنگِ چوب را هم
 * وارد محاسبه می‌کرد و کارتِ اشتباه (Hakimi) با حاشیهٔ ۰.۰۳۳ برنده شد.
 *
 * `trim` که از قبل در `imageFingerprint.prepared` بود این را نمی‌گیرد:
 * آن فقط حاشیهٔ **هم‌رنگِ یکدست** را می‌برد (پس‌زمینهٔ سفیدِ اسکن). میزِ
 * چوبی بافت دارد و از نظر `trim` بخشی از تصویر است.
 *
 * ───────────────────────────────────────────────────────────────────────────
 * روش: پروجکشنِ گرادیان
 * ───────────────────────────────────────────────────────────────────────────
 *
 * تشخیصِ کانتورِ کامل (مثل OpenCV) اینجا در دسترس نیست و آوردنش یعنی یک
 * وابستگیِ سنگینِ بومی روی VPS دو-هسته‌ای. روشِ سبک‌تری که روی کارتِ
 * مستطیلی به‌خوبی کار می‌کند:
 *
 *   ۱. تصویر به خاکستریِ کوچک (۲۵۶px) تبدیل می‌شود
 *   ۲. گرادیانِ افقی و عمودی حساب می‌شود (اختلافِ پیکسل‌های مجاور)
 *   ۳. برای هر ستون، مجموعِ گرادیانِ عمودی → «این ستون چقدر لبه دارد؟»
 *   ۴. لبه‌های کارت جایی‌اند که این مجموع ناگهان می‌پرد
 *
 * چرا این روی کارت جواب می‌دهد: کارت مستطیل است و لبه‌هایش **خطوطِ
 * ممتدِ عمودی و افقی**اند. بافتِ چوب گرادیانِ پراکنده دارد، ولی لبهٔ
 * کارت یک ستونِ کاملِ گرادیانِ قوی می‌سازد.
 *
 * ───────────────────────────────────────────────────────────────────────────
 * چرا محافظه‌کارانه عمل می‌کند
 * ───────────────────────────────────────────────────────────────────────────
 *
 * برشِ اشتباه بدتر از نبریدن است: اگر نصفِ کارت بریده شود، اثرانگشت
 * کاملاً عوض می‌شود و کاربرِ درستکار رد می‌شود.
 *
 * پس چند شرطِ سخت‌گیرانه گذاشته شده و اگر هرکدام برآورده نشود، تصویرِ
 * **اصلی** برگردانده می‌شود:
 *
 *   • ناحیهٔ پیشنهادی باید دستِ‌کم ۲۵٪ مساحتِ تصویر باشد
 *   • نسبتِ ابعادش باید بینِ ۰.۴ و ۱.۲ باشد (کارتِ بازی همیشه بلندتر از
 *     پهناست، ولی حاشیهٔ تشخیص را باز می‌گذاریم)
 *   • باید دستِ‌کم ۸٪ از هر بُعد بریده شود، وگرنه زحمتش نمی‌ارزد
 *
 * «برنگرداندنِ برش» همیشه امن است چون رفتارِ فعلیِ سیستم همان است.
 */
const sharp = require('sharp');

/** اندازهٔ کاری برای تحلیل. کوچک‌تر = سریع‌تر، و لبه‌ها هنوز پیدایند. */
const WORK = 200;

/** پهنای نوارِ حاشیه که به‌عنوان «قطعاً پس‌زمینه» نمونه‌برداری می‌شود. */
const BORDER_RATIO = 0.04;

/** حداقلِ نسبتِ مساحتِ برش به کلِ تصویر. زیرِ این یعنی «چیزی اشتباه است». */
const MIN_AREA_RATIO = 0.20;

/** حداکثر مساحت — بالاتر از این یعنی چیزی بریده نشده، پس بی‌فایده است. */
const MAX_AREA_RATIO = 0.92;

/** بازهٔ مجازِ نسبتِ عرض به ارتفاع برای یک کارتِ بازی (با تحملِ چرخش). */
const MIN_ASPECT = 0.35;
const MAX_ASPECT = 1.45;

/** نسبتِ پوششِ ماسک در یک سطر/ستون تا «بخشی از کارت» شمرده شود. */
const FILL_THRESHOLD = 0.35;

/**
 * مرزهای ناحیهٔ پرمحتوا را از پروفایلِ پوشش پیدا می‌کند.
 *
 * @param {number[]} profile نسبتِ پیکسل‌های غیرِ پس‌زمینه در هر سطر/ستون
 * @returns {[number, number]} [شروع، پایان) — یا [0,0] اگر چیزی نبود
 */
function contentBounds(profile) {
  const n = profile.length;
  let lo = 0;
  while (lo < n && profile[lo] < FILL_THRESHOLD) lo++;
  if (lo >= n) return [0, 0];
  let hi = n - 1;
  while (hi > lo && profile[hi] < FILL_THRESHOLD) hi--;

  // ── چرا کمی گشاد می‌گیریم ──
  //
  // لبهٔ بیرونیِ کارت اغلب سایه دارد و رنگش به پس‌زمینه نزدیک می‌شود،
  // پس چند پیکسلِ اول زیرِ آستانه می‌ماند. بریدنشان یعنی از دست دادنِ
  // بخشی از خودِ کارت — خطای بدتری از نبریدن.
  const pad = Math.round(n * 0.02);
  return [Math.max(0, lo - pad), Math.min(n, hi + 1 + pad)];
}

/**
 * کارت را از پس‌زمینه جدا می‌کند.
 *
 * ⚠️ هرگز استثنا پرتاب نمی‌کند و هرگز تصویرِ خراب برنمی‌گرداند. در هر
 *    تردیدی بافرِ **ورودی** را دست‌نخورده پس می‌دهد — چون رفتارِ فعلیِ
 *    سیستم همان است و «نبریدن» همیشه امن است.
 *
 * @param {Buffer} buf تصویرِ خام
 * @returns {Promise<{buffer: Buffer, cropped: boolean, box: ?object}>}
 */
async function cropCard(buf) {
  const fallback = { buffer: buf, cropped: false, box: null };
  try {
    const meta = await sharp(buf, { failOn: 'none' }).metadata();
    if (!meta.width || !meta.height
        || meta.width < 80 || meta.height < 80) return fallback;

    // ── چرا `rotate()` اول ──
    //
    // عکسِ گوشی اغلب با EXIF چرخیده ذخیره می‌شود. اگر نچرخانیم،
    // مختصاتی که پیدا می‌کنیم روی تصویرِ نچرخیده است و برشِ نهایی جای
    // اشتباهی می‌افتد.
    const norm = await sharp(buf, { failOn: 'none' })
      .rotate().removeAlpha().toBuffer();
    const nm = await sharp(norm).metadata();
    const NW = nm.width;
    const NH = nm.height;

    const { data, info } = await sharp(norm)
      .resize(WORK, WORK, { fit: 'fill' })
      .blur(1)            // نویزِ JPEG پیکسل‌های تکیِ کاذب می‌سازد
      .raw()
      .toBuffer({ resolveWithObject: true });

    const w = info.width;
    const h = info.height;
    const ch = info.channels;
    const at = (x, y) => {
      const i = (y * w + x) * ch;
      return [data[i], data[i + 1], data[i + 2]];
    };

    // ── تخمینِ رنگِ پس‌زمینه از نوارِ حاشیه ──
    //
    // فرض: کاربر کارت را وسطِ کادر می‌گیرد، پس لبه‌های تصویر تقریباً
    // همیشه میز/زمین/دستِ اوست. این فرض روی عکسِ واقعی درست بود و
    // راهنمای کادرِ دوربین آن را تضمین‌شده‌تر می‌کند.
    //
    // میانه و نه میانگین: یک گوشهٔ روشن (بازتابِ نور) میانگین را
    // می‌کشد ولی میانه مقاوم است.
    const b = Math.max(2, Math.round(WORK * BORDER_RATIO));
    const sr = [];
    const sg = [];
    const sb = [];
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        if (x >= b && x < w - b && y >= b && y < h - b) continue;
        const [r, g, bl] = at(x, y);
        sr.push(r); sg.push(g); sb.push(bl);
      }
    }
    if (!sr.length) return fallback;
    const mid = (arr) => {
      const a = Float64Array.from(arr).sort();
      return a[a.length >> 1];
    };
    const bg = [mid(sr), mid(sg), mid(sb)];

    // ── آستانهٔ تطبیقی ──
    //
    // پس‌زمینهٔ بافت‌دار (چوب، فرش) خودش پراکندگی دارد. اگر آستانهٔ
    // ثابت بگذاریم، روی میزِ ساده همه‌چیز «کارت» می‌شود و روی میزِ
    // شلوغ هیچ‌چیز.
    //
    // صدکِ ۷۵ِ فاصلهٔ خودِ نمونه‌های حاشیه از میانه‌شان، دقیقاً همان
    // «چقدر این پس‌زمینه ناهمگون است» را می‌دهد.
    //
    // ⚠️ ضریبِ ۱.۰ از اندازه‌گیری آمد، نه حدس: با ۱.۳ و ۱.۶ ناحیه به
    //    چند تکه می‌شکست و مساحت به ۰.۰۳ می‌افتاد. با ۱.۰ روی صحنهٔ
    //    آزمایشی مساحتِ ۰.۴۱ داد در برابرِ واقعیتِ ~۰.۴۵.
    const dist = [];
    for (let i = 0; i < sr.length; i++) {
      dist.push(Math.abs(sr[i] - bg[0])
        + Math.abs(sg[i] - bg[1]) + Math.abs(sb[i] - bg[2]));
    }
    dist.sort((p, q) => p - q);

    // ── چرا **دو** صدک ──
    //
    // `p50` می‌گوید «پس‌زمینه چقدر یکدست است»، `p75` می‌گوید «آستانهٔ
    // جداسازی کجا باشد». این دو نقشِ متفاوت دارند و یکی‌کردنشان باگ
    // ساخت (پایین‌تر توضیح داده شده).
    const p50 = dist[Math.floor(dist.length * 0.50)];
    const spread = dist[Math.floor(dist.length * 0.75)];

    // ══════════════════════════════════════════════════════════════════
    // آیا اصلاً پس‌زمینه‌ای وجود دارد؟
    // ══════════════════════════════════════════════════════════════════
    //
    // ── باگی که تست گرفت ──
    //
    // وقتی کاربر کارت را **تمام‌کادر** عکس می‌گیرد (یا وقتی مدیر طرحِ
    // تمیز آپلود می‌کند)، نوارِ حاشیه هم بخشی از خودِ کارت است. آن‌وقت
    // «رنگِ پس‌زمینه» می‌شود رنگِ گوشهٔ کارت، و هر چیزی که با آن فرق
    // دارد «کارت» شمرده می‌شود.
    //
    // نتیجه در تست: طرحِ تمیزِ ۶۲۰×۹۳۰ به ۲۹۱×۹۳۰ بریده شد — **نصفِ
    // کارت دور ریخته شد** و اثرانگشت کاملاً عوض می‌شد.
    //
    // ── تشخیص ──
    //
    // پس‌زمینهٔ واقعی (میز، فرش، دیوار) **یکدست** است: فاصلهٔ صدکِ ۷۵
    // از میانه‌اش کوچک می‌ماند. اگر حاشیه خودش پرتنوع باشد، یعنی
    // چیزی جز پس‌زمینه در آن است و برش بی‌معنی می‌شود.
    //
    // ⚠️ معیار `p50` است نه `p75` — و این تفاوت یک باگِ کامل بود.
    //
    // اندازه‌گیریِ واقعی:
    //
    //     صحنه: کارت روی میزِ چوبی   p50=۱۲   p75=۱۵۷
    //     طرحِ تمیزِ تمام‌کادر        p50=۵۹   p75=۶۱
    //     کارت روی میز/فرش/کاغذ      p50=۰    p75=۰
    //
    // در صحنهٔ واقعی `p75` بالاست چون **گوشه‌های خودِ کارت** داخل نوارِ
    // حاشیه می‌افتند (کارت کج است و کادر را پر نکرده). آن عدد دربارهٔ
    // یکدستیِ پس‌زمینه چیزی نمی‌گوید.
    //
    // `p50` یعنی «نیمهٔ آرام‌ترِ حاشیه چقدر یکدست است» — و همان
    // درست تفکیک می‌کند: پس‌زمینهٔ واقعی زیرِ ۱۵، طرحِ تمام‌کادر بالای
    // ۵۰.
    //
    // نسخهٔ اول با `p75 > 55` هر دو را رد می‌کرد و برش عملاً خاموش بود.
    const BORDER_UNIFORM_MAX = 30;
    if (p50 > BORDER_UNIFORM_MAX) return fallback;

    const thr = Math.max(30, spread);

    // ماسکِ «این پیکسل پس‌زمینه نیست»
    const col = new Float64Array(w);
    const row = new Float64Array(h);
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        const [r, g, bl] = at(x, y);
        const d = Math.abs(r - bg[0]) + Math.abs(g - bg[1]) + Math.abs(bl - bg[2]);
        if (d > thr) { col[x] += 1; row[y] += 1; }
      }
    }
    for (let x = 0; x < w; x++) col[x] /= h;
    for (let y = 0; y < h; y++) row[y] /= w;

    const [x0, x1] = contentBounds(Array.from(col));
    const [y0, y1] = contentBounds(Array.from(row));
    const cw = x1 - x0;
    const chh = y1 - y0;
    if (cw < 8 || chh < 8) return fallback;

    // ── شرط‌های ایمنی ──
    //
    // برشِ اشتباه بدتر از نبریدن است: اگر نصفِ کارت بریده شود اثرانگشت
    // کاملاً عوض می‌شود و کاربرِ درستکار رد می‌شود.
    const areaRatio = (cw * chh) / (w * h);
    if (areaRatio < MIN_AREA_RATIO || areaRatio > MAX_AREA_RATIO) return fallback;

    const aspect = cw / chh;
    if (aspect < MIN_ASPECT || aspect > MAX_ASPECT) return fallback;

    const left = Math.round((x0 / w) * NW);
    const top = Math.round((y0 / h) * NH);
    const width = Math.min(NW - left, Math.round((cw / w) * NW));
    const height = Math.min(NH - top, Math.round((chh / h) * NH));
    if (width < 40 || height < 40) return fallback;

    const out = await sharp(norm)
      .extract({ left, top, width, height })
      .toBuffer();

    return {
      buffer: out,
      cropped: true,
      box: { left, top, width, height, ratio: Number(areaRatio.toFixed(3)) },
    };
  } catch {
    // هر خطایی — فرمتِ ناشناخته، حافظه، تصویرِ خراب — یعنی «نبُر».
    return fallback;
  }
}

module.exports = {
  cropCard,
  // برای تست
  _internals: { contentBounds },
  MIN_AREA_RATIO,
  MAX_AREA_RATIO,
  MIN_ASPECT,
  MAX_ASPECT,
};
