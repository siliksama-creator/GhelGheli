// ضربات پنالتی — شوت‌اوت ساده و صادقانه
//
// ۲ بازیکن، تصمیم هم‌زمان:
//   زننده: انتخاب یکی از ۶ ناحیه (۳ ستون × ۲ ردیف)
//   دروازه‌بان: حدس و شیرجه به یک ناحیه
//
// ۵ ضربه برای هر بازیکن + برد زودهنگام + **ضربه‌های اضافه تا رسیدن به برنده**
//
// ── قاعدهٔ کامل بازی، بدون استثنا ──
//
//     ناحیهٔ شوت == ناحیهٔ شیرجه  →  مهار
//     در غیر این صورت             →  گل
//
// همین. هیچ عامل پنهانی نیست: نه قدرت شوت، نه تیرک، نه شانس.
// شانس گل برای زنندهٔ تصادفی مقابل دروازه‌بان تصادفی دقیقاً ۵/۶ است.
//
// ═══════════════════════════════════════════════════════════════════════════
// ⚠️ تاریخچهٔ دو تصمیمِ متضاد — چرا این نسخه این شکلی است
// ═══════════════════════════════════════════════════════════════════════════
//
// ۳ مهر ۱۴۰۵ (نسخهٔ قبلی): مالک صریحاً خواست هر بازیکن **۱۰ ضربه** بزند و
// تساوی یک نتیجهٔ واقعی باشد — «اصلاً چیزی به اسمِ مرگِ ناگهانی نباید
// داشته باشیم». پس `result()` در تساوی `'DRAW'` برمی‌گرداند و شرط‌بندی با
// بازگشتِ ورودی منهای کمسیون تسویه می‌شد.
//
// مهر ۱۴۰۵ (این نسخه): مالک تصمیم را برگرداند —
//
//   «بازی تا ۵ ضربه از هر طرف انجام میشه و اگه در ۵ ۵ مساوی بود ۱ راند
//    دیگه اضافه میشه انقدر ادامه پیدا میکنه تا برنده داشته باشه»
//   «این بازی دیگه حالت مساوی نداره»
//
// یعنی برای پنالتی:
//   • `ROUNDS` از ۱۰ به **۵** برگشت،
//   • تساوی دیگر نتیجه نیست؛ بعد از ضربهٔ پنجمِ هر دو، اگر امتیاز برابر بود
//     بازی وارد **ضربه‌های اضافه** می‌شود (هر راند یک ضربه برای هر طرف) و
//     آن‌قدر ادامه می‌یابد تا یکی از دو طرف در یک راندِ کامل برتری پیدا کند،
//   • `result()` برای پنالتی **هرگز `'DRAW'` نمی‌گرداند**.
//
// ⚠️ `'DRAW'` هنوز قراردادِ معتبرِ موتور است و باید بماند — بازیِ *دوئل کارت*
//    واقعاً مساوی می‌شود و `engine.js` با همین رشته شاخهٔ تسویهٔ تساوی را
//    برمی‌دارد. فقط پنالتی است که دیگر آن را تولید نمی‌کند.
//
// ⚠️ چرا `suddenDeath` نگه داشته شد و دوباره **واقعی** شد:
//    در نسخهٔ ۱۰ ضربه‌ای این کلید فقط برای سازگاری با کلاینت‌های نصب‌شده
//    مانده بود و همیشه `false` بود (اگر نباشد، کلاینت قدیمی `undefined`
//    می‌گیرد). حالا همان کلید معنای واقعی پیدا کرده: «بازی از وقتِ قانونی
//    گذشته و در ضربه‌های اضافه است». دو کلاینت از آن برای نشان دادنِ برچسبِ
//    «راندِ اضافه» استفاده می‌کنند.
//
// ── چرا «پنجرهٔ طلایی» (قدرت شوت) حذف شد ──
//
// نسخه‌ای قدیمی‌تر یک مدل احتمالاتی کامل داشت (`missChance`، `isClean`،
// `SWEET_MIN`/`SWEET_WIDTH`) که در آن قدرتِ شوت و زمان‌بندی روی احتمال خطا
// اثر می‌گذاشت. مشکل این بود که آن مدل **هرگز فراخوانی نمی‌شد**: `resolveKick`
// فقط تطابق ناحیه را می‌سنجید. با ۲۰۰٬۰۰۰ شوت اندازه‌گیری شد — قدرت ۰٫۰۵ و
// قدرت ۰٫۴۷ هر دو ۱۰۰٪ گل می‌شدند.
//
// در همان حال هر دو کلاینت نوار طلایی را رندر می‌کردند و به کاربر می‌گفتند
// «داخل نوار طلایی رها کن — ضربهٔ تمیز!». یعنی کاربر مهارتی را تمرین می‌کرد
// که روی نتیجه هیچ اثری نداشت.
//
// تصمیم (به‌خواستِ مالک محصول): بازی ساده بماند و به‌جای زنده‌کردنِ مدل،
// **وعده از رابط برداشته شود**. کد مرده هم حذف شد تا نفر بعدی فکر نکند این
// مکانیک فعال است. نوار قدرت فقط شدتِ انیمیشن را تعیین می‌کند.

// ── هندسهٔ دروازه ──
//
// ۶ ناحیه = ۳ ستون (چپ/وسط/راست) × ۲ ردیف (بالا/پایین).
//
// شماره‌گذاری سطری است، همان‌طور که در هر دو کلاینت رسم می‌شود:
//
//     ۰  ۱  ۲      بالا
//     ۳  ۴  ۵      پایین
//
// ⚠️ این اعداد باید با `ZONE_COLS`/`ZONE_ROWS` در
//    `userweb/src/penaltyModel.js` و `mobile/.../penalty_board.dart` یکی
//    بمانند. گاردِ `game-parity` هم‌راستاییِ دو کلاینت را می‌سنجد.
const ZONES = 6;
const ZONE_COLS = 3;
const ZONE_ROWS = 2;

// هر بازیکن ۵ ضربه در وقتِ قانونی. بعدش در صورتِ تساوی، ضربه‌های اضافه.
const ROUNDS = 5;

// `col`/`row` با حذف `missChance` بلااستفاده شدند و پاک شدند.
// ناحیه فقط یک عدد ۰..۵ است و هیچ‌جای منطق به سطر/ستونش نیاز ندارد —
// تنها مصرف‌کنندهٔ سطر/ستون، **رندر** در کلاینت است (مرکزِ ناحیه روی دهانهٔ
// دروازه) و آن‌جا هم همین دو ثابت را دارد.

/**
 * تنها قاعدهٔ بازی: تطابق ناحیه.
 *
 * امضا عمداً `power` را نگه داشته چون کلاینت‌ها هنوز آن را می‌فرستند و
 * در بازپخشِ انیمیشن (شدت ضربه) استفاده می‌شود — ولی روی **نتیجه** هیچ
 * اثری ندارد و نباید داشته باشد. اگر روزی خواستید اثر داشته باشد،
 * این تنها جایی است که باید عوض شود.
 */
function resolveKick(shotZone, power, diveZone) {
  if (shotZone === diveZone) {
    return { outcome: 'save', shotZone, diveZone, power, blockedByKeeper: true };
  }
  return { outcome: 'goal', shotZone, diveZone, power };
}

const create = () => ({
  score: { X: 0, O: 0 },
  taken: { X: 0, O: 0 },
  shooter: 'X',
  history: [],
  pending: {},
  round: 1,
  // «بازی از وقتِ قانونی گذشته و در ضربه‌های اضافه است».
  // در شروع همیشه `false`؛ فقط `applyMove` آن را یک‌بار روشن می‌کند و
  // دیگر خاموش نمی‌شود (بعد از ورود به اضافه، راهِ برگشتی نیست).
  //
  // ⚠️ این کلید عمداً حذف نشده: نسخه‌های نصب‌شدهٔ اپ و مرورگرهای کش‌شده
  //    آن را می‌خوانند؛ اگر نباشد `undefined` می‌گیرند.
  suddenDeath: false,
  lastKick: null,
});

function isValidMove(state, move, player) {
  if (!move || typeof move !== 'object') return false;
  const z = Number(move.zone);
  if (!Number.isInteger(z) || z < 0 || z >= ZONES) return false;
  const p = Number(move.power);
  if (player === state.shooter) {
    if (!Number.isFinite(p) || p < 0 || p > 1) return false;
  }
  return !state.pending[player];
}

function applyMove(state, move, player) {
  const z = Number(move.zone);
  const p = player === state.shooter
    ? Math.max(0, Math.min(1, Number(move.power) || 0.5))
    : 0;
  state.pending[player] = { zone: z, power: p };

  const keeper = state.shooter === 'X' ? 'O' : 'X';
  if (!state.pending[state.shooter] || !state.pending[keeper]) return state;

  const shot = state.pending[state.shooter];
  const dive = state.pending[keeper];
  const res = resolveKick(shot.zone, shot.power, dive.zone);

  if (res.outcome === 'goal') state.score[state.shooter] += 1;
  state.taken[state.shooter] += 1;
  state.lastKick = { ...res, shooter: state.shooter, keeper };
  state.history.push({
    shooter: state.shooter,
    outcome: res.outcome,
    shotZone: res.shotZone,
    diveZone: res.diveZone,
  });

  state.pending = {};
  state.shooter = keeper;

  if (state.taken.X === state.taken.O) state.round += 1;

  // ── ورود به ضربه‌های اضافه ──
  //
  // فقط وقتی *هر دو* ضربهٔ پنجم را زده باشند و هنوز برابر باشند. اینجا
  // پرچم را می‌زنیم (نه داخل `result`) چون `result` تابعی خالص است و
  // نباید وضعیت را تغییر دهد — وگرنه صدا زدنش برای «آیا تمام شد؟» خودش
  // بازی را جلو می‌برد.
  if (!state.suddenDeath
    && state.taken.X >= ROUNDS
    && state.taken.O >= ROUNDS
    && state.score.X === state.score.O) {
    state.suddenDeath = true;
  }

  return state;
}

/**
 * نتیجهٔ بازی — تنها منبعِ حقیقت.
 *
 * برای پنالتی دو حالت بیشتر نیست: یک برنده، یا «هنوز تمام نشده» (`null`).
 * **این بازی تساوی ندارد.**
 *
 *   ۱. **ضربه‌های اضافه:** هر راند یک ضربه برای هر طرف. تا وقتی تعدادِ
 *      ضربه‌های زده‌شده برابر نشده، راند کامل نیست و برنده‌ای اعلام
 *      نمی‌شود (اگر X زده و O نه، O هنوز می‌تواند جبران کند). به‌محضِ
 *      برابر شدنِ تعداد و **نابرابر** بودنِ امتیاز → برنده.
 *   ۲. **بردِ زودهنگام (فقط وقتِ قانونی):** اگر حتی با گل‌شدنِ همهٔ
 *      ضربه‌های باقی‌ماندهٔ حریف هم او نتواند برسد، بازی همین‌جا تمام
 *      است. کشیدنِ بازی تا ضربهٔ پنجم فقط آزار است.
 *   ۳. **پایانِ وقتِ قانونی:** هر دو ۵ ضربه زدند → امتیازِ بیشتر برنده؛
 *      برابر → `null` (بازی ادامه دارد و `applyMove` پرچمِ اضافه را زده).
 *
 * ⚠️ در وقتِ اضافه عمداً **هیچ بردِ زودهنگامی** محاسبه نمی‌شود: آنجا
 *    سقفِ ضربه وجود ندارد، پس «ضربه‌های باقی‌ماندهٔ حریف» بی‌معنی است و
 *    فرمولِ بالا برای هر امتیازی نادرست جواب می‌داد.
 */
function result(state) {
  const { X, O } = state.score;
  const tX = state.taken.X, tO = state.taken.O;

  // ۱. ضربه‌های اضافه — تصمیم فقط در پایانِ یک راندِ کامل.
  if (state.suddenDeath) {
    if (tX === tO && X !== O) return X > O ? 'X' : 'O';
    return null;
  }

  // ۲. بردِ زودهنگام در وقتِ قانونی.
  const leftX = Math.max(0, ROUNDS - tX);
  const leftO = Math.max(0, ROUNDS - tO);
  if (X > O + leftO) return 'X';
  if (O > X + leftX) return 'O';

  // ۳. پایانِ وقتِ قانونی. برابری یعنی «ادامه دارد»، نه تساوی.
  if (tX >= ROUNDS && tO >= ROUNDS) {
    if (X === O) return null;
    return X > O ? 'X' : 'O';
  }
  return null;
}

function nextTurn(state) {
  return state.shooter;
}

function publicState(state, forPlayer) {
  const { pending, ...rest } = state;
  return {
    ...rest,
    iChose: forPlayer ? !!pending[forPlayer] : false,
    waitingForOpponent: forPlayer
      ? !!pending[forPlayer] && Object.keys(pending).length === 1
      : false,
    role: forPlayer
      ? (forPlayer === state.shooter ? 'shooter' : 'keeper')
      : null,
  };
}

function botMove(state, me) {
  // ناحیهٔ تصادفیِ یکنواخت. چون قاعده صرفاً تطابق ناحیه است، هر
  // الگوی غیریکنواختی قابل یادگیری می‌شود و ربات را قابل‌سوءاستفاده
  // می‌کند: کاربر می‌فهمد ربات کجا را بیشتر می‌زند و همان‌جا می‌ایستد.
  const zone = Math.floor(Math.random() * ZONES);
  // `power` فقط شدت انیمیشن است و در نتیجه بی‌اثر.
  return { zone, power: state.shooter === me ? 0.5 + Math.random() * 0.4 : 0 };
}

module.exports = {
  id: 'penalty',
  title: 'ضربات پنالتی',
  turnMs: 12000,
  simultaneous: true,
  // کلیدِ ساعتِ هر ضربه: فقط وقتی عوض می‌شود که ضربهٔ قبلی واقعاً حل شده
  // باشد (هر دو طرف انتخاب کرده‌اند). قفلِ زننده یا دروازه‌بان وسطِ ضربه
  // نباید ساعتِ ۱۲ ثانیه‌ای را از نو شروع کند — همان باگی که در دوئل
  // کارت صحنهٔ راندِ قبل را وسطِ راندِ جدید پخش می‌کرد.
  clockKey: state => `${state.round ?? 0}:${state.taken?.X ?? 0}:${state.taken?.O ?? 0}`,
  ZONES, ZONE_COLS, ZONE_ROWS, ROUNDS,
  create, result, isValidMove, applyMove, nextTurn, botMove,
  publicState, resolveKick,
};
