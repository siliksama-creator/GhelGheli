//
// این ماژول یک کار دقیق انجام می‌دهد: وقتی چند پروسهٔ Node بالا باشد، کاری
// می‌کند که `io.to(...)` و `io.emit(...)` رویداد را به کاربرانی که به
// پروسه‌های دیگر وصل‌اند هم برساند. بدون آن، هر پروسه فقط سوکت‌های خودش
// را می‌بیند.
//
// ─────────────────────────────────────────────────────────────────────────
//  چه چیزی را حل می‌کند و چه چیزی را نه — مهم است که این را دقیق بدانیم
// ─────────────────────────────────────────────────────────────────────────
//
//  ✅ حل می‌شود (چون همه از الگوی `io.to('user:<id>')` استفاده می‌کنند):
//     · چت عمومی
//     · اعلان‌ها (notification)
//     · وضعیت آنلاین دوستان
//     · دعوت دوست به بازی
//     · فهرست لابی‌ها (game:lobby_updated با io.emit پخش می‌شود)
//
//  ❌ حل نمی‌شود — و آداپتور به‌تنهایی هرگز حلش نمی‌کند:
//     مسابقه‌های زندهٔ داخل games/engine.js. دلیلش این است که شیء `room`
//     شامل «ارجاع مستقیم به شیء سوکت» (room.seats.X) و «هندل تایمر Node»
//     (room.turnTimer, room.botTimer, room.reconnectTimers) است. هیچ‌کدام
//     قابل serialize شدن به ردیس نیستند: تایمر باید در همان پروسه‌ای بسوزد
//     که ساخته شده، و سوکت اصلاً یک شیء زنده با بافر و رمزنگاری است.
//
//     مهم‌تر اینکه موتور ۴۷ جای مختلف مستقیماً به یک سوکت مشخص emit می‌کند
//     (safeEmit) چون هر بازیکن باید فقط کارت‌های خودش را ببیند — نه پخش
//     همگانی به اتاق. تبدیل اینها به io.to() یعنی بازنویسی کامل موتور و
//     ریسکِ لو رفتن دست حریف.
//
//     ⇒ راهکار درست و امن: مسابقه‌ها روی «یک» پروسهٔ اختصاصی بمانند و
//       بقیهٔ ترافیک بین چند پروسه پخش شود. جزئیات در docs/scaling-fa.md.
//
// اگر REDIS_URL نباشد این ماژول بی‌صدا هیچ کاری نمی‌کند و اپ دقیقاً مثل
// امروز تک‌پروسه بالا می‌آید.

const { redisEnabled, makeClient } = require('./redis');

/**
 * آداپتور ردیس را به io وصل می‌کند.
 * @returns {Promise<boolean>} true اگر واقعاً وصل شد.
 */
async function attachRedisAdapter(io) {
  if (!redisEnabled()) return false;

  let createAdapter;
  try {
    // eslint-disable-next-line global-require
    ({ createAdapter } = require('@socket.io/redis-adapter'));
  } catch {
    console.error('[cluster] REDIS_URL هست ولی @socket.io/redis-adapter نصب نیست — تک‌پروسه ادامه می‌دهیم');
    return false;
  }

  // pub/sub در ردیس دو اتصال جدا می‌خواهد: اتصالی که subscribe کرده
  // نمی‌تواند فرمان معمولی اجرا کند.
  const pub = makeClient('pub');
  const sub = makeClient('sub');
  if (!pub || !sub) return false;

  io.adapter(createAdapter(pub, sub));
  console.log('[cluster] آداپتور ردیس فعال شد — پخش رویداد بین پروسه‌ها برقرار است');
  return true;
}

module.exports = { attachRedisAdapter };
