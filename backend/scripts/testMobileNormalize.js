#!/usr/bin/env node
// تست‌های نرمال‌سازی شمارهٔ موبایل — باگِ «رمزم درست است ولی وارد نمی‌شوم».
//
// ═══════════════════════════════════════════════════════════════════════════
// باگی که این فایل نگهبانش است
// ═══════════════════════════════════════════════════════════════════════════
//
// `normalizeMobile` قبلاً فقط فاصله‌ها را حذف می‌کرد. صفحه‌کلید فارسی اندروید
// به‌طور پیش‌فرض «۰۹۱۲…» تایپ می‌کند نه «0912…»، و آن رشته با ردیفِ لاتینِ
// دیتابیس برابر نمی‌شد. نتیجه روی سرور زنده اثبات شد:
//
//   POST /api/auth/register-password  {mobile:"09131444589"}  → ۲۰۰ ✅
//   POST /api/auth/login              {mobile:"09131444589"}  → ۲۰۰ ✅
//   POST /api/auth/login              {mobile:"۰۹۱۳۱۴۴۴۵۸۹"}  → ۴۰۱ ❌
//
// و پیامِ ۴۰۱ می‌گفت «شماره موبایل یا رمز عبور نادرست است» — که دروغ بود.
// کاربر رمزش را عوض می‌کرد و باز همان پیام را می‌گرفت، چون مشکل از رمز نبود.
//
// ═══════════════════════════════════════════════════════════════════════════
// چرا تابع از روی سورس خوانده می‌شود و دوباره نوشته نشده
// ═══════════════════════════════════════════════════════════════════════════
//
// بقیهٔ اسکریپت‌های تست، پیاده‌سازی را کپی می‌کنند چون `require`ِ server.js
// یک سوکت و استخر دیتابیس باز می‌کند. ولی کپی می‌تواند از اصل جدا بیفتد و
// آن‌وقت تست سبز می‌ماند در حالی که محصول خراب است. اینجا متنِ خودِ تابع از
// server.js استخراج و اجرا می‌شود: نه سروری بالا می‌آید، نه نسخهٔ دومی هست
// که drift کند.
//
//   node scripts/testMobileNormalize.js
const fs = require('fs');
const path = require('path');

let pass = 0, fail = 0;
const ok = (cond, name) => {
  if (cond) { pass++; console.log(`  ✓ ${name}`); }
  else { fail++; console.error(`  ✗ ${name}`); }
};

// ── استخراج تابع واقعی از server.js ────────────────────────────────────────
const src = fs.readFileSync(
  path.join(__dirname, '..', 'src', 'server.js'), 'utf8');
const start = src.indexOf('function normalizeMobile(');
if (start === -1) {
  console.error('normalizeMobile در server.js پیدا نشد — تست نمی‌تواند اجرا شود');
  process.exit(1);
}
// از ابتدای تابع، آکولادها را می‌شماریم تا انتهایش را دقیق پیدا کنیم.
let depth = 0, end = -1, started = false;
for (let i = start; i < src.length; i++) {
  if (src[i] === '{') { depth++; started = true; }
  else if (src[i] === '}') { depth--; if (started && depth === 0) { end = i + 1; break; } }
}
const fnSource = src.slice(start, end);
// eslint-disable-next-line no-new-func
const normalizeMobile = new Function(`${fnSource}; return normalizeMobile;`)();

console.log('\n== ارقام فارسی (باگ اصلی) ==');
{
  ok(normalizeMobile('۰۹۱۲۳۴۵۶۷۸۹') === '09123456789',
    'شمارهٔ تمام‌فارسی به لاتین تبدیل می‌شود');
  ok(normalizeMobile('۰۹۱۲345۶۷۸۹') === '09123456789',
    'شمارهٔ ترکیبی فارسی و لاتین هم درست می‌شود');
  ok(normalizeMobile('٠٩١٢٣٤٥٦٧٨٩') === '09123456789',
    'ارقام عربی-هندی (U+0660) هم پشتیبانی می‌شوند');
}

console.log('\n== شکل‌های دیگری که کاربر واقعی تایپ می‌کند ==');
{
  ok(normalizeMobile('+989123456789') === '09123456789', '+۹۸ به صفر تبدیل می‌شود');
  ok(normalizeMobile('+۹۸۹۱۲۳۴۵۶۷۸۹') === '09123456789', '+۹۸ با ارقام فارسی');
  ok(normalizeMobile('00989123456789') === '09123456789', '۰۰۹۸ به صفر تبدیل می‌شود');
  ok(normalizeMobile('989123456789') === '09123456789', '۹۸ بدون علامت مثبت');
  ok(normalizeMobile('9123456789') === '09123456789', 'صفرِ ابتدایی جا افتاده اضافه می‌شود');
  ok(normalizeMobile('0912-345-6789') === '09123456789', 'خط تیره حذف می‌شود');
  ok(normalizeMobile('(0912) 345 6789') === '09123456789', 'پرانتز و فاصله حذف می‌شوند');
  ok(normalizeMobile('  09123456789  ') === '09123456789', 'فاصلهٔ ابتدا و انتها');
  ok(normalizeMobile('0912\u200c3456789') === '09123456789', 'نیم‌فاصله حذف می‌شود');
  ok(normalizeMobile('\u200f09123456789') === '09123456789', 'نویسهٔ جهت‌دهی RTL حذف می‌شود');
}

console.log('\n== سازگاری با گذشته — هیچ‌کس نباید قفل شود ==');
{
  // ۳۹ ردیفِ موجودِ دیتابیس پیش از استقرار بررسی شد: همه لاتین‌اند.
  ok(normalizeMobile('09123456789') === '09123456789',
    'شمارهٔ لاتینِ درست بدون تغییر عبور می‌کند');
  ok(normalizeMobile('Admin') === 'Admin',
    'نام کاربری مدیر دست‌نخورده می‌ماند — وگرنه ورود مدیر می‌شکند');
  ok(normalizeMobile('diag5760185') === 'diag5760185',
    'نام کاربری الفبا-عددی دست‌نخورده می‌ماند');
  ok(normalizeMobile('cl1785665213d') === 'cl1785665213d',
    'حساب‌های تستِ موجود دست‌نخورده می‌مانند');
}

console.log('\n== ورودی‌های خراب کرش نمی‌کنند ==');
{
  ok(normalizeMobile('') === '', 'رشتهٔ خالی');
  ok(normalizeMobile(null) === '', 'null');
  ok(normalizeMobile(undefined) === '', 'undefined');
  ok(normalizeMobile('   ') === '', 'فقط فاصله');
  ok(typeof normalizeMobile(123456) === 'string', 'ورودی عددی به رشته تبدیل می‌شود');
  ok(normalizeMobile('+') === '+', 'فقط علامت مثبت کرش نمی‌کند');
  ok(normalizeMobile('()-.') === '', 'فقط جداکننده');
}

console.log('\n== ثبت‌نام و ورود همیشه به یک ردیف می‌رسند ==');
{
  // اگر این بشکند، «حساب سایه» ساخته می‌شود: دو کاربر با یک شماره در دو
  // شکلِ نگارشی، که یعنی امتیازها و کیف پول بین دو حساب تقسیم می‌شود.
  const forms = ['09123456789', '۰۹۱۲۳۴۵۶۷۸۹', '+989123456789',
    '0912-345-6789', '9123456789', '  ۰۹۱۲۳۴۵۶۷۸۹  '];
  const normalized = forms.map(normalizeMobile);
  ok(new Set(normalized).size === 1,
    `هر ${forms.length} شکل به یک شماره می‌رسند (${normalized[0]})`);
}

console.log(`\n${fail === 0 ? '✓' : '✗'} ${pass} تست موفق، ${fail} ناموفق`);
process.exit(fail === 0 ? 0 : 1);
