-- پرکردنِ گذشته (backfill)
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ⚠️ عمداً **انجام نمی‌شود** و این یک تصمیم است، نه فراموشی.
--
-- می‌شد از `wallet_transactions` و `pass_xp_log` ردیف ساخت. ولی آن‌ها
-- فقط بخشی از امتیازها را پوشش می‌دهند (پول ≠ امتیاز، و XP گذر با
-- امتیاز فرق دارد). نتیجه دفتری می‌شد که **ناقص است ولی کامل به نظر
-- می‌رسد** — بدترین حالتِ ممکن برای ابزاری که قرار است مرجعِ حل اختلاف
-- باشد.
--
-- در عمل هم بی‌اثر است: دیتابیس همین حالا برای عرضه پاک شده و تنها
-- کاربر، حسابِ خودِ مدیر با صفر امتیاز است. پس دفتر از همان ردیفِ اول
-- کامل خواهد بود.
--
-- ابزارِ ممیزی (`audit_points.py`) کاربرانی را که `current_points`شان با
-- `SUM(delta)` نمی‌خواند گزارش می‌کند. برای کاربرانی که قبل از این
-- مایگریشن امتیاز داشته‌اند، این اختلاف **مورد انتظار** است و ابزار
-- آن‌ها را جدا نشان می‌دهد.
