-- ═══════════════════════════════════════════════════════════════════════════
-- دفترِ ریزِ امتیازات + کسرِ امتیاز توسطِ مدیر
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── خواستهٔ مالک ──
--
--   «در قسمتی جدید ریز امتیازات کاربران و کاربرایی که بیشترین امتیاز رو
--    از کار در اپلیکیشن و وب بدست آوردن قابل دیدنه یعنی ادمین میتونه
--    بفهمه که کاربر بیشترین امتیازی که یدفه بدست اورده حتی از کجاست و
--    کاربر هارو میتونه از شماره موبایلی که ثبت کردن جستجوکنه و ریز
--    امتیازات کاملشون رو ببینه»
--
--   «ادمین امتیاز کاربر رو در صورت نیاز بتونه کم کنه و دلیلیشو بگه به
--    کاربر و دلیلش به کاربر بصورت نوتیفیکشن در زنگوله بره»
--
-- ═══════════════════════════════════════════════════════════════════════════
-- چرا این جدول تا امروز وجود نداشت و چرا نبودش یک نقصِ جدی است
-- ═══════════════════════════════════════════════════════════════════════════
--
-- امتیاز تا امروز فقط سه **شمارنده** روی جدولِ `users` بود:
--
--     current_points · lifetime_points · monthly_league_points
--
-- و هفت مسیرِ جدا آن‌ها را زیاد می‌کنند:
--
--     ۱. ثبتِ کارت با عکس        (photoCardService)
--     ۲. ثبتِ کارت با کدِ تنها   (server.js)
--     ۳. کمیسیونِ معرف            (referralService)
--     ۴. جایزهٔ بازی‌ها           (gameRewardService)
--     ۵. پاداشِ گذرِ نبرد         (passService)
--     ۶. گردونهٔ شانس             (server.js)
--     ۷. تنظیمِ دستیِ مدیر        (server.js خط ۲۸۹۴)
--
-- هیچ‌کدام ردی نمی‌گذاشتند. یعنی وقتی کاربری می‌گفت «امتیازم کم شده» یا
-- «این ۵۰۰۰ امتیاز از کجا آمد؟»، **هیچ راهی برای پاسخ نبود** — نه برای
-- مدیر، نه برای پشتیبانی. تنها راه، حدس زدن از روی جدول‌های پراکنده بود
-- (wallet_transactions فقط پول را دارد، pass_xp_log فقط XP گذر را).
--
-- ⚠️ این دقیقاً همان اشتباهی است که در کیفِ پول **نشد**: آنجا از روزِ
--    اول `wallet_transactions` وجود داشت و دفترِ کل با موجودی مقایسه
--    می‌شود. امتیاز همان‌قدر حساس است — پایهٔ رتبهٔ لیگ و جوایزِ نقدی —
--    ولی دفتری نداشت.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- طراحی
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── چرا `delta` علامت‌دار و نه دو ستونِ credit/debit ──
--
-- `wallet_transactions` از `direction` + `amount` استفاده می‌کند. اینجا
-- عمداً فرق می‌کند: امتیاز برخلافِ پول **کم هم می‌شود** (خرجِ جایزه،
-- کسرِ مدیر) و جمعِ ساده روی یک ستونِ علامت‌دار هم خواناتر است هم
-- کم‌خطاتر. `SUM(delta)` باید دقیقاً برابرِ `current_points` باشد و
-- همین یک عبارت، ابزارِ ممیزی را می‌سازد.
--
-- ── چرا `source` متن و نه ENUM ──
--
-- ENUM در Postgres برای اضافه کردنِ مقدارِ تازه به `ALTER TYPE` نیاز
-- دارد که در تراکنش کار نمی‌کند و مایگریشن را شکننده می‌کند. `CHECK`
-- با فهرست، همان ایمنی را می‌دهد و تغییرش ساده است.
--
-- ── چرا `balance_after` ذخیره می‌شود ──
--
-- افزونگی است و می‌شد محاسبه‌اش کرد. ولی بدونِ آن، برای نشان دادنِ
-- «موجودی بعد از هر تراکنش» در پنل باید کلِ تاریخچه را از اول جمع زد —
-- که با ده‌هزار ردیف کند می‌شود. این ستون همان کارِ صورتحسابِ بانکی را
-- می‌کند و اختلافش با جمعِ تجمعی، خودش یک بررسیِ سلامت است.
--
-- ── چرا `reference_type` + `reference_id` بدونِ کلیدِ خارجی ──
--
-- به جدول‌های مختلفی اشاره می‌کنند (photo_card_codes، wheel_spins، …).
-- کلیدِ خارجیِ چندشکلی در Postgres ممکن نیست، و مهم‌تر: اگر کارتی حذف
-- شود، ردِ تاریخیِ امتیازش **نباید** پاک شود. تاریخچهٔ مالی باید از
-- دادهٔ زنده جان سالم به در ببرد.

CREATE TABLE IF NOT EXISTS point_transactions (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id         UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  -- مثبت = دریافت، منفی = کسر. صفر مجاز نیست: ردیفِ بی‌اثر فقط نویز است.
  delta           INTEGER NOT NULL CHECK (delta <> 0),

  -- موجودیِ `current_points` **بعد از** اعمالِ این تراکنش.
  balance_after   INTEGER NOT NULL CHECK (balance_after >= 0),

  source          VARCHAR(40) NOT NULL CHECK (source IN (
    'photo_card',      -- ثبتِ کارت با عکس
    'card_code',       -- ثبتِ کارت با کدِ تنها (سیستمِ قدیمی)
    'referral',        -- کمیسیونِ ۵٪ معرف
    'game',            -- بردن در بازی‌ها
    'pass_reward',     -- پاداشِ پلهٔ گذرِ نبرد
    'wheel',           -- گردونهٔ شانس
    'reward_claim',    -- خرجِ امتیاز برای گرفتنِ جایزه (منفی)
    'admin_adjust',    -- تنظیمِ دستیِ مدیر (مثبت یا منفی)
    'admin_deduct',    -- کسرِ انضباطیِ مدیر (همیشه منفی)
    'other'
  )),

  -- ارجاعِ چندشکلی به ردیفی که این امتیاز از آن آمده.
  reference_type  VARCHAR(48),
  reference_id    UUID,

  -- متنی که به کاربر نشان داده می‌شود. برای کسرِ مدیر، همان «دلیل».
  description     TEXT,

  -- کدام مدیر؟ فقط برای منابعِ admin_*. SET NULL تا حذفِ حسابِ مدیر
  -- تاریخچه را نبرد.
  admin_id        UUID REFERENCES admin_users(id) ON DELETE SET NULL,

  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── ایندکس‌ها ──
--
-- هر کدام یک کوئریِ مشخص در پنل را سریع می‌کند. ایندکسِ بی‌مصرف فقط
-- INSERT را کند می‌کند، پس هیچ‌کدام «برای احتیاط» اضافه نشده‌اند.

-- «ریز امتیازاتِ این کاربر، تازه‌ترین اول» — صفحهٔ جزئیاتِ کاربر.
CREATE INDEX IF NOT EXISTS idx_ptx_user_time
  ON point_transactions(user_id, created_at DESC);

-- «بزرگ‌ترین دریافت‌های تک‌باره» — خواستهٔ صریحِ مالک: «بیشترین امتیازی
-- که یدفه بدست اورده». فقط روی ردیف‌های مثبت، چون کسرها اینجا بی‌ربطند.
CREATE INDEX IF NOT EXISTS idx_ptx_biggest
  ON point_transactions(delta DESC) WHERE delta > 0;

-- «امتیاز از کدام منبع؟» — نمودارِ تفکیکِ منابع.
CREATE INDEX IF NOT EXISTS idx_ptx_source_time
  ON point_transactions(source, created_at DESC);

-- ردیابیِ کارِ مدیران: «چه کسی چه امتیازی کم کرد؟»
CREATE INDEX IF NOT EXISTS idx_ptx_admin
  ON point_transactions(admin_id, created_at DESC)
  WHERE admin_id IS NOT NULL;

COMMENT ON TABLE point_transactions IS
  'دفترِ ریزِ امتیازات. SUM(delta) هر کاربر باید برابرِ users.current_points باشد.';


-- ═══════════════════════════════════════════════════════════════════════════
-- تاریخِ لیگ به‌دستِ مدیر
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── خواستهٔ مالک ──
--
--   «تاریخ و پایان لیگ توسط مدیر مشخص میشه در پنل های مدیریت کل پلتفرم
--    و جوایز لیگ بعد از تایید مدیریت به کیف پول ها داده میشه»
--
-- ── وضعیتِ قبلی و چرا کافی نبود ──
--
-- `league_seasons` از قبل `starts_at` و `ends_at` داشت، ولی هیچ مسیرِ
-- APIای برای تغییرشان نبود: تاریخ‌ها را `jalaliMonthStart` خودکار از
-- تقویمِ شمسی می‌ساخت و `repairSeasonBounds` هر بار «تصحیح»شان می‌کرد.
-- یعنی اگر مدیر هم دستی در دیتابیس عوضشان می‌کرد، اولین درخواست
-- برشان می‌گرداند.
--
-- `manual_dates` می‌گوید «این تاریخ‌ها را مدیر گذاشته، دست نزن».

ALTER TABLE league_seasons
  ADD COLUMN IF NOT EXISTS manual_dates BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN league_seasons.manual_dates IS
  'اگر true باشد، repairSeasonBounds تاریخ‌ها را بازنویسی نمی‌کند — مدیر خودش تعیین کرده.';

-- ── پرداختِ جوایز فقط بعد از تأییدِ مدیر ──
--
-- تا امروز `closeActiveSeason` جایزه را **مستقیم** به کیفِ پول واریز
-- می‌کرد. خواستهٔ مالک این است که یک گامِ تأیید وسطش باشد.
--
-- `payment_status` از قبل روی `league_payouts` هست. چیزی که کم بود:
-- زمان و شناسهٔ مدیرِ تأییدکننده، تا معلوم باشد چه کسی و کِی پول را
-- آزاد کرده. بدونِ این، پرداختِ اشتباه قابلِ ردیابی نیست.

ALTER TABLE league_payouts
  ADD COLUMN IF NOT EXISTS approved_by UUID REFERENCES admin_users(id) ON DELETE SET NULL;

ALTER TABLE league_payouts
  ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ;

COMMENT ON COLUMN league_payouts.approved_by IS
  'مدیری که واریزِ این جایزه را تأیید کرد. NULL یعنی هنوز تأیید نشده.';


