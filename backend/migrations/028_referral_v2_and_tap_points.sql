-- بررسی سلامت: جمع وزن‌ها باید دقیقاً یک میلیون باشد.
--
-- این یک assertion در زمان مهاجرت است، نه یک کامنت آرزومندانه. اگر کسی
-- بعداً ردیفی اضافه یا ویرایش کند و جمع به هم بخورد، سرویس موقع بارگذاری
-- خطا می‌دهد — ولی بهتر است همین‌جا جلویش گرفته شود تا اصلاً مستقر نشود.
DO $$
DECLARE s BIGINT;
BEGIN
  SELECT SUM(weight) INTO s FROM wheel_prizes WHERE is_active;
  IF s <> 1000000 THEN
    RAISE EXCEPTION 'جمع وزن جوایز باید ۱٬۰۰۰٬۰۰۰ باشد ولی % است', s;
  END IF;
END $$;

