-- بازنگری سیستم دعوت + امتیاز بازی ضربه‌زن + احتمالات محتاطانه‌ترِ گردونه
--
-- ═════════════════════════════════════════════════════════════════════════
-- ۱. کد دعوت: چهار رقمی، فقط عدد
--
-- مالک: «کد دعوت ۴ رقمی اختصاصی بدون حروف انگلیسی که ممکنه اشتباه کنن، و
-- بزرگ کوچیکی حروف مهم نباشه».
--
-- فقط رقم یعنی مسئلهٔ بزرگی/کوچکی حروف اصلاً وجود ندارد — بهترین شکلِ
-- «مهم نباشد» این است که حرفی در کار نباشد. ارقام فارسی هم موقع ورود به
-- لاتین تبدیل می‌شوند (سمت سرور)، چون کاربر ایرانی با کیبورد فارسی ۱۲۳۴
-- تایپ می‌کند نه 1234.
--
-- فضای حالت: ۱۰۰۰..۹۹۹۹ = ۹٬۰۰۰ کد. این سقفِ سختِ تعداد کاربرانِ دارای کد
-- است. با ۳۷ کاربر فعلی جا هست، ولی اگر روزی به چند هزار برسید باید به ۵
-- رقم بروید — ستون VARCHAR(12) است پس مهاجرت بعدی درد ندارد.
-- برای همین `referral_code_len` در تنظیمات نیست: تغییرش باید آگاهانه و با
-- یک مایگریشن باشد، نه با یک کلیک در پنل.

-- کدهای هشت‌کاراکتری قبلی باطل می‌شوند. سه دلیل:
--   * هیچ‌کدام هنوز پخش نشده‌اند (سیستم دیروز مستقر شد و هیچ معرفی‌ای ثبت
--     نشده — کوئری روی referral_earnings صفر برگرداند)،
--   * نگه‌داشتن دو قالب هم‌زمان یعنی اعتبارسنجی باید هر دو را بپذیرد و
--     برای همیشه پیچیده بماند،
--   * کد قدیمی حرف دارد و دقیقاً همان چیزی است که مالک نمی‌خواهد.
UPDATE users SET referral_code = NULL;

DO $$
DECLARE
  u RECORD;
  candidate TEXT;
BEGIN
  FOR u IN SELECT id FROM users ORDER BY joined_at LOOP
    LOOP
      -- ۱۰۰۰ تا ۹۹۹۹ — هرگز با صفر شروع نمی‌شود تا «۰۴۲۷» و «۴۲۷» دو چیز
      -- متفاوت به‌نظر نرسند و کاربر صفر ابتدایی را جا نیندازد.
      candidate := (1000 + floor(random() * 9000))::int::text;
      EXIT WHEN NOT EXISTS (SELECT 1 FROM users WHERE referral_code = candidate);
    END LOOP;
    UPDATE users SET referral_code = candidate WHERE id = u.id;
  END LOOP;
END $$;

-- ═════════════════════════════════════════════════════════════════════════
-- ۲. چرخش‌های روزانهٔ اضافی از دعوت
--
-- مالک: «به ازای هر ۱۰ نفری که دعوت کنه ۱ شانس روزانه اضافه بشه ... و این
-- تا ۵۰ نفر ادامه پیدا میکنه».
--
-- یعنی: ۱۰ نفر → ۲ چرخش روزانه، ۲۰ → ۳، ۳۰ → ۴، ۴۰ → ۵، ۵۰ → ۶. بعد از
-- ۵۰ نفر دیگر اضافه نمی‌شود (دعوت کردن همچنان نامحدود است، فقط این پاداشِ
-- خاص سقف دارد).
--
-- ستون ذخیره نمی‌شود و هر بار از روی COUNT محاسبه می‌شود. دلیل: یک شمارندهٔ
-- ذخیره‌شده باید در هر ثبت‌نام، هر حذف کاربر و هر مسدودسازی به‌روز شود، و
-- اولین جایی که یادمان برود، عدد تا ابد غلط می‌ماند. COUNT روی یک ایندکس
-- با این ابعاد میکروثانیه‌ای است.

-- ═════════════════════════════════════════════════════════════════════════
-- ۳. جایزهٔ ثبت‌نام برای خودِ دعوت‌شونده
--
-- مالک: «هر دو کاربر یعنی هم کسی که دعوت شده هم کسی که دعوت کرده هر دو ۳
-- شانس گردونه بگیرند».
--
-- ستون جدا لازم نیست — همان bonus_spins است. ولی برای اینکه گزارش‌ها
-- بتوانند بگویند این چرخش‌ها از کجا آمده‌اند، منبع در referral_earnings
-- ثبت نمی‌شود (آنجا برای امتیاز است)، بلکه در خودِ لاگ چرخش با
-- spin_source='referral' دیده می‌شود.

-- ═════════════════════════════════════════════════════════════════════════
-- ۴. امتیاز بازی ضربه‌زن
--
-- مالک: «کل بازی ۵۰ هزار امتیاز میدهد» و «به جای تعداد تب، تعداد امتیاز
-- نشون داده بشه».
--
-- تصمیم: **هر ضربه دقیقاً ۱ امتیاز**. این ساده‌ترین مدل ممکن است و یک
-- خاصیت مهم دارد: عددی که کاربر روی صفحه می‌بیند، همان کاری است که کرده.
-- هیچ ضریب پنهانی نیست که بعداً باعث شود بپرسد «چرا ۱۰۰ ضربه زدم ولی ۴۰
-- امتیاز گرفتم؟».
--
-- برای اینکه جمع دقیقاً ۵۰٬۰۰۰ شود، منحنی سختی بازطراحی شد: رشد ۱.۰۵
-- به‌جای ۱.۱۵. منحنی قبلی جمعاً ۷۲۱٬۷۷۲ ضربه بود — روز چهاردهم ۲.۸ ساعت
-- ضربهٔ بی‌وقفه می‌خواست و عملاً هیچ‌کس تمامش نمی‌کرد.
--
-- ستون points_awarded جدا از total_taps است چون این دو یک چیز نیستند:
-- ضربه‌های ردشدهٔ ضدتقلب در total_taps نمی‌آیند ولی مهم‌تر اینکه اگر روزی
-- نرخ عوض شود، تاریخچهٔ امتیازِ داده‌شده نباید بازنویسی شود.
ALTER TABLE tap_game_progress
  ADD COLUMN IF NOT EXISTS points_awarded BIGINT NOT NULL DEFAULT 0
    CHECK (points_awarded >= 0);

-- سقف روزانه از ۳ به ۲ لول کاهش می‌یابد (خواستهٔ مالک).
-- مقدار در کد است نه دیتابیس؛ این کامنت فقط برای رد گرفتن است.

-- ═════════════════════════════════════════════════════════════════════════
-- ۵. احتمالات محتاطانه‌ترِ گردونه
--
-- مالک: «چون قراره پولی از کاربرها نگیریم، شانس جایزه‌ها و امتیازهای بزرگ
-- باید به احتمال خیلی خیلی کم نزدیک باشه».
--
-- سه چیز از دیروز عوض شده و هر سه هزینه را بالا می‌برند:
--   ۱. دعوت‌شونده هم ۳ چرخش می‌گیرد (قبلاً فقط معرف)
--   ۲. هر ۱۰ دعوت = یک چرخش روزانهٔ دائمی، تا ۶ چرخش در روز
--   ۳. دعوت نامحدود است
-- یعنی چرخش سرانه می‌تواند چند برابر شود. اگر وزن‌ها دست نخورند، هزینه
-- هم چند برابر می‌شود.
--
-- مخرج از ۱۰٬۰۰۰ به **۱٬۰۰۰٬۰۰۰** رفت تا بشود نرخ‌های خیلی کم را دقیق
-- بیان کرد. با مخرج ۱۰٬۰۰۰، کمترین نرخ ممکن ۱ در ۱۰٬۰۰۰ بود؛ حالا
-- ۱ در ۲۰۰٬۰۰۰ هم قابل بیان است.
--
--   جایزه          یک در هر      سهم از هزینه
--   ۱۰۰ امتیاز            ۱.۴     ۷۳.۵ امتیاز
--   ۵۰۰ امتیاز              ۵      ۱۰۰ امتیاز
--   ۱۰۰۰ امتیاز            ۱۶       ۶۰ امتیاز
--   ۲۰۰۰ امتیاز           ۲۵۰        ۸ امتیاز
--   ۱۰٬۰۰۰ تومان        ۱٬۱۱۱     ۹.۰۰ تومان
--   ۵۰۰۰ امتیاز        ۱۲٬۵۰۰      ۰.۴ امتیاز
--   ۵۰٬۰۰۰ تومان       ۶۶٬۶۶۶     ۰.۷۵ تومان
--   ۱۰۰٬۰۰۰ تومان     ۲۰۰٬۰۰۰     ۰.۵۰ تومان
--                              ─────────────
--                   هزینهٔ نقدی هر چرخش: ۱۰.۲۵ تومان
--
-- برای یک کاربر با ۲ چرخش در روز، جایزهٔ ۱۰۰ هزار تومانی یعنی به‌طور
-- میانگین یک بار در ۲۷۴ سال. این همان «خیلی خیلی کم» است.
--
-- «۵۰۰ امتیاز» اضافه شد تا بین ۱۰۰ و ۱۰۰۰ یک پلهٔ میانی باشد؛ بدون آن،
