-- ۶. برداشتن ایندکس یکتای «یک چرخش در روز»
--
-- این ایندکس وقتی ساخته شد که سهمیهٔ روزانه همیشه دقیقاً ۱ بود و کارش این
-- بود که مسابقهٔ دو درخواست هم‌زمان را ببندد.
--
-- حالا سهمیه بین ۱ تا ۶ متغیر است (۱ پایه + یکی به ازای هر ۱۰ دعوت تا سقف
-- ۵۰ نفر). با این ایندکس، کاربری که ۲۰ نفر دعوت کرده و باید ۳ چرخش داشته
-- باشد، در چرخش دوم خطای ۲۳۵۰۵ می‌گرفت — یعنی جایزه‌ای که برایش کار کرده
-- بی‌صدا از او دریغ می‌شد.
--
-- بار درستی به قفل ردیف کاربر منتقل شد: wheelService.spin() ابتدا
-- `SELECT ... FOR UPDATE` می‌زند و *بعد* سهمیهٔ امروز را می‌شمارد، پس دو
-- درخواست هم‌زمان پشت سر هم اجرا می‌شوند و دومی عدد به‌روز را می‌بیند.
DROP INDEX IF EXISTS uq_wheel_daily_spin;

-- ایندکس معمولی برای همان کوئری شمارش. بدون این، هر چرخش یک اسکن روی
-- تاریخچهٔ کامل کاربر می‌شد.
CREATE INDEX IF NOT EXISTS idx_wheel_spins_daily
  ON wheel_spins(user_id, spun_day) WHERE spin_source = 'daily';
