-- ============================================================================
--  هم‌اندازه کردنِ user_league_history.month_year با league_seasons.month_year
-- ============================================================================
--
-- ── باگ ──
--
-- `league_seasons.month_year` در گذشته به VARCHAR(32) پهن شد تا شناسهٔ
-- لیگ‌های غیرماهانه را جا بدهد (مثلاً `1405-W32` برای لیگِ هفتگی).
-- ولی `user_league_history.month_year` که همان مقدار را کپی می‌کند روی
-- VARCHAR(7) جا ماند — اندازه‌ای که فقط برای `1405-05` کافی بود.
--
-- نتیجه: `closeActiveSeason()` سرِ این INSERT می‌شکست:
--
--     value too long for type character varying(7)
--
-- یعنی **هیچ لیگِ هفتگی/فصلی/ویژه‌ای هرگز قابلِ بستن نبود**. کلِ تراکنش
-- rollback می‌شد: نه جایزه‌ای ثبت می‌شد، نه فصلی بسته می‌شد.
--
-- ── چرا تا حالا کسی ندید ──
--
-- کرونِ قبلی (`5 0 1 * *`) فقط تازه‌ترین لیگ را می‌بست و عملاً هیچ‌وقت به
-- لیگِ هفتگی نمی‌رسید، پس این خطا هیچ‌وقت اجرا نمی‌شد. به محضِ اینکه
-- کرونِ ساعتیِ جدید سراغِ «لیگ هفتگی قهرمانان» رفت، خودش را نشان داد.
--
-- ── چرا ۳۲ ──
--
-- دقیقاً همان اندازهٔ ستونِ مبدأ. هر مقداری که در `league_seasons` جا
-- شود اینجا هم جا می‌شود و این ناهماهنگی دوباره تکرار نمی‌شود.

ALTER TABLE user_league_history
  ALTER COLUMN month_year TYPE VARCHAR(32);
