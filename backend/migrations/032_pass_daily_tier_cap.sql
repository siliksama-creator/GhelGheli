-- سقف سخت: حداکثر ۲ پلهٔ گذر نبرد در هر روز
--
-- ═════════════════════════════════════════════════════════════════════════
-- ایرادی که مالک گرفت
-- ═════════════════════════════════════════════════════════════════════════
--
-- «افرادی که نخریدنش بیش از حد دارن امتیاز میگیرن»
-- «فقط دوتا بتل پس در روز باز میشه»
--
-- اندازه‌گیری شد و کاملاً درست بود:
--
--   کاربر معمولی (بازی + ورود) : ۱۸۵ XP در روز → پلهٔ ۱۰ در ۷ روز
--   کاربر فعال                  : ۲۸۵ XP در روز → پلهٔ ۱۴ در ۷ روز
--   حداکثر مطلق                 : ۸۲۵ XP در روز → **۷ پله در روز اول**
--
-- یعنی کاربری که هیچ پولی نداده بود، در چند روز کل مسیر ۵۰ پله‌ای را
-- تمام می‌کرد. وقتی مسیر رایگان این‌قدر سخاوتمند باشد، هیچ دلیلی برای
-- خرید پلاس نمی‌ماند — و بدتر، خودِ گذر نبرد بی‌ارزش می‌شود چون در یک
-- هفته تمام شده.
--
-- ═════════════════════════════════════════════════════════════════════════
-- چرا سقف روی «پله» و نه روی «XP»
-- ═════════════════════════════════════════════════════════════════════════
--
-- سقف XP قبلاً وجود داشت (۸۲۵ در روز) ولی کافی نبود، چون XP لازمِ
-- پله‌های اول کم است: ۱۰۰، ۱۰۵، ۱۱۰... پس همان ۸۲۵ XP در روز اول
-- هفت پله باز می‌کرد و در روزهای آخر فقط دو پله.
--
-- سقف روی **تعداد پله** مستقیماً چیزی را محدود می‌کند که مالک گفت، و
-- ضمناً منحنی را یکنواخت می‌کند: هر روز دقیقاً ۲ پله، از اول تا آخر.
--
-- XPِ اضافه **هدر نمی‌رود** — در `xp` ذخیره می‌ماند و فردا که سقف باز
-- می‌شود، بلافاصله تبدیل به پله می‌شود. این مهم است: اگر XP سوزانده
-- می‌شد، کاربری که یک روز زیاد بازی کرده حس می‌کرد سرش کلاه رفته.
--
-- شمارش به وقت تهران و نیمه‌شب ریست می‌شود — همان قاعده‌ای که گردونه و
-- بازی ضربه‌زن دارند، تا کاربر یک قانون را یاد بگیرد نه سه تا.

ALTER TABLE user_pass_progress
  ADD COLUMN IF NOT EXISTS tiers_day        DATE,
  ADD COLUMN IF NOT EXISTS tiers_today      INTEGER NOT NULL DEFAULT 0,
  -- پله‌ای که کاربر واقعاً «باز کرده» است. جدا از xp نگه داشته می‌شود
  -- چون xp می‌تواند از سقف روزانه جلو بزند ولی پله نه.
  ADD COLUMN IF NOT EXISTS unlocked_tier    INTEGER NOT NULL DEFAULT 0;

-- برای کاربران فعلی: پلهٔ باز شده را از روی XP فعلی حساب کن، وگرنه
-- کسی که تا پلهٔ ۷ رسیده ناگهان به صفر برمی‌گردد.
--
-- منحنی: need(n) = 100 + (n-1)*5  →  cum(n) = n*(195 + 5n)/2
-- بزرگ‌ترین n که cum(n) <= xp باشد.
UPDATE user_pass_progress p
SET unlocked_tier = LEAST(50, GREATEST(0, (
  SELECT COALESCE(MAX(n), 0) FROM generate_series(1, 50) AS n
   WHERE n * (195 + 5 * n) / 2 <= p.xp
)))
WHERE unlocked_tier = 0 AND xp > 0;

CREATE INDEX IF NOT EXISTS idx_pass_progress_day
  ON user_pass_progress(user_id, tiers_day);
