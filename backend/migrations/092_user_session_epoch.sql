--  ۰۹۲ — «جلسهٔ همیشگی» + کلیدِ خاموش‌کردن
-- ═══════════════════════════════════════════════════════════════════════════
--
-- خواستهٔ مالک (۲۶ شهریور): «وقتی ورودِ موفق با شماره داشتند، جلسه‌شان برای
-- همیشه فعال بماند.» پس توکنِ کاربر از ۳۰ روز به ۱۰ سال رفت (تقریباً همیشه)
-- و دیگر لازم نیست کاربر هر ماه دوباره شماره و کد بزند.
--
-- اما توکنِ طولانی یک ریسک دارد: اگر گوشی گم/دزدیده شود، آن توکن تا ۱۰ سال
-- کار می‌کند و تا حالا هیچ راهِ «خاموش‌کردن» نداشت. این ستون همان کلید است:
--
--   • هر توکن عددِ `session_epoch` را لحظهٔ صدور با خود می‌برد (`tv`).
--   • میان‌افزارِ auth این عدد را با مقدارِ *فعلیِ* کاربر مقایسه می‌کند؛
--     یکی نبود → توکن بی‌اعتبار (۴۰۱ → اپ خودش صفحهٔ ورود را می‌آورد).
--   • هر تغییرِ رمز — توسط خودِ کاربر، ریستِ ادمین، یا بازیابی با کد —
--     این عدد را یک واحد بالا می‌برد. یعنی «رمز را عوض کردم ⇒ بقیهٔ
--     دستگاه‌ها بیرون».
--
-- توکن‌های قدیمی که `tv` ندارند عمداً معتبر می‌مانند (کد `|| 0` می‌گذارد):
-- وگرنه هر کاربری که همین حالا وارد است، یک‌باره از حسابش پرت می‌شد.
-- چون پیش‌فرضِ این ستون هم ۰ است، سازگاری کامل است.
--
-- IF NOT EXISTS: اجرای دوباره روی سروری که این را دارد نباید دیپلوی را بشکند.
ALTER TABLE users ADD COLUMN IF NOT EXISTS session_epoch INTEGER NOT NULL DEFAULT 0;

-- جست‌وجو روی این ستون انجام نمی‌شود (کوئریِ auth با `id` می‌آید و کلِ سطر را
-- می‌خواند)، پس عمداً ایندکس اضافه نمی‌کنیم — ایندکسِ بی‌مصرف فقط هزینهٔ
-- نوشتنِ هر لاگین را بالا می‌برد.
