-- پلاس فقط یک باشگاه — نه بی‌نهایت.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- چه چیزی عوض شد و چرا
-- ═══════════════════════════════════════════════════════════════════════════
--
-- خواستهٔ صریح مالک: «دیگه پلاس اجازه عضویت در هر باشگاه رو نمیده، فقط
-- پلاس میتونه فقط یک باشگاه رو انتخاب کنه که به عنوان عکس پروفایلش قرار
-- داده بشه».
--
-- قانونِ قبلی (023_clubs.sql) به مشترکِ پلاس اجازه می‌داد بی‌نهایت باشگاه
-- جمع کند و در فهرستِ اعضای همهٔ آن‌ها ظاهر شود. دو مشکل داشت:
--
--   ۱. بی‌معنی بود. کسی که هوادارِ ۱۶ تیم است، هوادارِ هیچ‌کدام نیست، و
--      فهرستِ اعضای باشگاه‌ها را از اعتبار می‌انداخت.
--
--   ۲. ارزشِ خریدِ دائمیِ نشان را از بین می‌برد. چرا کسی نشان بخرد وقتی
--      اشتراک همه را با هم می‌دهد؟
--
-- ═══════════════════════════════════════════════════════════════════════════
-- چرا داده‌های موجود باید پاک شوند
-- ═══════════════════════════════════════════════════════════════════════════
--
-- تغییرِ کدِ سرویس فقط رفتارِ **آینده** را عوض می‌کند. کاربری که همین حالا
-- پنج باشگاهِ اشتراکی دارد، تا ابد در فهرستِ هر پنج تا می‌ماند و قانونِ
-- جدید هرگز شاملش نمی‌شود — یعنی دو دستهٔ کاربر با دو قانونِ متفاوت.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- چه چیزی حذف **نمی‌شود**
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ردیف‌های `source='purchase'` اصلاً دست نمی‌خورند. کاربر بابتشان پول
-- داده و مالکیتش دائمی است — این قانون فقط دربارهٔ باشگاه‌هایی است که
-- اشتراک موقتاً باز کرده بود.
--
-- از هر کاربر، **تازه‌ترین** باشگاهِ اشتراکی نگه داشته می‌شود. چرا
-- تازه‌ترین: همان چیزی است که کاربر آخرین بار انتخاب کرده، پس محتمل‌ترین
-- گزینه‌ای است که الان می‌خواهد.

BEGIN;

-- ── حذفِ باشگاه‌های اشتراکیِ اضافه ──
WITH keep AS (
  SELECT DISTINCT ON (user_id) id
    FROM user_clubs
   WHERE source = 'plus'
   ORDER BY user_id, joined_at DESC, id
)
DELETE FROM user_clubs uc
 WHERE uc.source = 'plus'
   AND uc.id NOT IN (SELECT id FROM keep);

-- ── نشانِ انتخاب‌شده‌ای که دیگر عضوش نیست پاک شود ──
--
-- بدون این، کاربر نشانِ باشگاهی را روی پروفایلش می‌بیند که دیگر عضوش
-- نیست — و بقیه آن را نمی‌بینند. یعنی یک تناقضِ دیداری که دقیقاً شبیهِ
-- باگ است.
UPDATE users u
   SET equipped_club = NULL, updated_at = NOW()
 WHERE u.equipped_club IS NOT NULL
   AND NOT EXISTS (
     SELECT 1 FROM effective_club_memberships m
      WHERE m.user_id = u.id AND m.club_slug = u.equipped_club);

COMMIT;
