-- ═══════════════════════════════════════════════════════════════════════════
--  سقفِ روزانهٔ امتیازِ کسب‌شده از بازی‌های شرطیِ آنلاین
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── خواستهٔ مالک (۴ مهر ۱۴۰۵) ───────────────────────────────────────────────
--
-- «کاربرها از بازی‌های آنلاین نهایت می‌تونن ۲۰۰۰ امتیاز در روز به دست
--  بیارن. اگه سقف پر بشه می‌تونن به بازی ادامه بدن، ولی برد دیگه امتیاز
--  نمی‌ده (سکهٔ همیشگی سرِ جایش است) و باخت دوباره از شمارندهٔ کسب‌شده
--  کم می‌کند تا جا باز شود. سقف هر کس مالِ خودش است و ربطی به حریف ندارد.»
--
-- ── چرا این جدول و نه ستون روی users ───────────────────────────────────────
--
-- شمارنده روزانه است (تقویم تهران، مثلِ `user_coin_quota`) و فردا صفر
-- می‌شود. ستونِ روی users نیاز به ریستِ شبانه داشت و تاریخ هم نگه
-- نمی‌داشت؛ ردیفِ تاریخ‌دار همان الگوی سهمیهٔ سکه است: خودبه‌خود با روزِ
-- تازه صفر می‌شود و کرون هفت‌روز یک‌بار ردیف‌های کهنه را پاک می‌کند.
--
-- ── قراردادِ شمارنده ────────────────────────────────────────────────────────
--
-- `earned` فقط **کسبِ مثبت** را نگه می‌دارد (سودِ خالصِ واریزشده، نه اصلِ
-- ورودیِ برگشتی). باخت از موجودی کم می‌کند ولی اینجا فقط «جا باز می‌کند»:
-- `earned` هرگز زیرِ صفر نمی‌رود تا باختِ عمدی نتواند فضایی بیش از خودِ
-- سقف بسازد (وگرنه کسی ۵۰۰۰ می‌باخت و ۷۰۰۰ مجوزِ کسب می‌گرفت).
--
-- کسرِ امتیاز از شکستِ تسویه در همان سندِ مسابقه ثبت می‌شود؛ این جدول فقط
-- می‌گوید «امروز چقدر از سقفِ کسب مصرف شده است».

CREATE TABLE IF NOT EXISTS user_point_quota (
  user_id    uuid     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  quota_date date     NOT NULL,
  earned     integer  NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, quota_date),
  CONSTRAINT user_point_quota_earned_check CHECK (earned >= 0)
);

CREATE INDEX IF NOT EXISTS idx_user_point_quota_date
  ON user_point_quota(quota_date);
