-- ═══════════════════════════════════════════════════════════════════
-- بازبینیِ جوایزِ گذر نبرد — دورِ بیست‌ودوم
-- ═══════════════════════════════════════════════════════════════════
--
-- مالک گزارش داد که «جوایز با شاپِ قدیم ساخته شده». بررسیِ دیتابیس سه
-- ایرادِ واقعی نشان داد:
--
--   ۱) پلهٔ ۵۰ (آخرین و بزرگ‌ترین جایزهٔ فصل) دقیقاً همان پلهٔ ۳۵ بود:
--      هر دو `color_rainbow`. کاربری که ۱۱٬۱۲۵ XP جمع می‌کرد، در پایان
--      چیزی می‌گرفت که پانزده پله قبل داشت. عملاً یعنی پاداشِ نهایی صفر.
--
--   ۲) پنج برچسب با نامِ واقعیِ آیتم در شاپ فرق داشت — «قاب آتش» در
--      برابر «قاب آتشین»، «قاب هولوگرام» در برابر «قاب هولوگرافیک
--      اختصاصی ۲۰۲۸» و... . کاربر در گذر نبرد یک اسم می‌دید و در
--      کمدش اسمی دیگر؛ این دقیقاً همان حسی است که «باگ» نامیده می‌شود.
--
--   ۳) یازده پله از پنجاه پله آیتمِ شاپ می‌دادند. مالک صریح گفت
--      «آیتم‌های شاپ رو خیلی کم بذار» — منطقی هم هست: وقتی گذر نبرد
--      کازمتیک را رایگان پخش می‌کند، خودِ شاپ بی‌ارزش می‌شود.
--
-- ── تصمیم ──
--
-- آیتمِ شاپ از ۱۱ به ۵ کاهش می‌یابد و فقط روی پله‌های گِرد و بامعنا
-- می‌نشیند (۱۰، ۲۰، ۳۰، ۴۰، ۵۰) و همه در مسیرِ پلاس. پله‌های آزادشده
-- به چرخشِ گردونه تبدیل می‌شوند: مصرف‌شدنی است، اقتصادِ کازمتیک را
-- خراب نمی‌کند، و برای کاربر ملموس‌تر از «۵۰۰ امتیاز» است.
--
-- برچسب‌ها با `shop_items.name` هم‌گام می‌شوند و از این به بعد
-- تک‌منبعِ حقیقت همان جدولِ شاپ است.
--
-- ایدمپوتنت: فقط فصلِ فعال را دست می‌زند و هر بار اجرا نتیجهٔ یکسان
-- می‌دهد. پله‌هایی که کاربران قبلاً دریافت کرده‌اند (`user_pass_claims`)
-- دست‌نخورده می‌مانند — این مایگریشن تعریفِ جایزه را عوض می‌کند، نه
-- تاریخچهٔ دریافت را.

DO $$
DECLARE
  sid UUID;
BEGIN
  SELECT id INTO sid FROM pass_seasons WHERE is_active LIMIT 1;
  IF sid IS NULL THEN
    RAISE NOTICE 'فصلِ فعالی نیست — از تغییرِ جوایز صرف‌نظر شد';
    RETURN;
  END IF;

  -- ── ۱) پله‌های شاپِ اضافی به چرخشِ گردونه تبدیل می‌شوند ──
  -- نگه‌داشته‌ها: ۱۰ (قاب نئون)، ۲۰ (اسم طلایی)، ۳۰ (قاب آتشین)،
  --                ۴۰ (قاب یخی)، ۵۰ (جایزهٔ نهایی، پایین‌تر ست می‌شود)
  UPDATE pass_tiers
     SET kind = 'spins', amount = 2, payload = NULL,
         label = '۲ چرخش گردونهٔ شانس'
   WHERE season_id = sid
     AND kind = 'shop_item'
     AND tier IN (5, 15, 25, 35, 45);

  -- ── ۲) پلهٔ ۵۰ باید منحصربه‌فرد و بهترینِ فصل باشد ──
  -- `frame_holo` (قاب هولوگرافیک اختصاصی ۲۰۲۸) نایاب‌ترین قابِ شاپ است
  -- و حالا فقط همین‌جا داده می‌شود — نه در پلهٔ ۴۵، نه جای دیگر.
  UPDATE pass_tiers
     SET kind = 'shop_item', amount = 0, payload = 'frame_holo'
   WHERE season_id = sid AND tier = 50 AND track = 'plus';

  -- ── ۳) برچسب‌ها از خودِ شاپ خوانده می‌شوند ──
  -- تک‌منبعِ حقیقت. اگر مدیر فردا نامِ آیتمی را در پنل عوض کند،
  -- گذر نبرد دیگر اسمِ قدیمی را نشان نمی‌دهد.
  UPDATE pass_tiers pt
     SET label = si.name
    FROM shop_items si
   WHERE pt.season_id = sid
     AND pt.kind = 'shop_item'
     AND si.slug = pt.payload
     AND pt.label IS DISTINCT FROM si.name;

  -- ── ۴) هیچ آیتمِ شاپی نباید در یک مسیر دو بار بیفتد ──
  -- گاردِ دفاعی: اگر روزی دستی چیزی اضافه شد و تکراری ساخت، همین‌جا
  -- سروصدا می‌کند به‌جای اینکه کاربر در پایانِ فصل کشفش کند.
  IF EXISTS (
    SELECT 1 FROM pass_tiers
     WHERE season_id = sid AND kind = 'shop_item'
     GROUP BY track, payload HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'جایزهٔ تکراری در گذر نبرد باقی مانده است';
  END IF;

  -- ── ۵) هر payload باید در شاپ واقعاً وجود داشته باشد و فعال باشد ──
  IF EXISTS (
    SELECT 1 FROM pass_tiers pt
     WHERE pt.season_id = sid AND pt.kind = 'shop_item'
       AND NOT EXISTS (
         SELECT 1 FROM shop_items si
          WHERE si.slug = pt.payload AND si.is_active = true)
  ) THEN
    RAISE EXCEPTION 'گذر نبرد به آیتمی اشاره می‌کند که در شاپ نیست';
  END IF;
END $$;
