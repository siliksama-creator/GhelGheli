-- قفلِ ۳ ساعته پس از ۵ کدِ غلط + انتخابِ دستیِ طرح توسط مدیر
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── چرا قفل لازم است ──
--
-- بانکِ کد ۱۵ هزارتایی است و کدها روی کارت چاپ می‌شوند. کسی که کارت
-- ندارد می‌تواند کد حدس بزند. محدودکنندهٔ نرخِ فعلی (۲۰ درخواست در
-- ساعت) جلوی حدسِ **انبوه** را می‌گیرد ولی جلوی حدسِ صبورانه را نه:
-- ۲۰ حدس در ساعت یعنی ۴۸۰ حدس در روز، و آن هم فقط برای یک حساب.
--
-- قفلِ ۳ ساعته بعد از ۵ خطای پشت‌سرهم، هزینهٔ حدس زدن را از «چند ثانیه»
-- به «ساعت‌ها» می‌برد، بدون اینکه کاربرِ درستکار — که نهایتاً یکی دو بار
-- کد را اشتباه می‌خواند — گرفتار شود.
--
-- ⚠️ فقط کدِ **غلط** شمرده می‌شود. عکسِ نامفهوم خطای کاربر نیست و
--    نباید به قفل منجر شود؛ آن پرونده به مدیر می‌رود.

CREATE TABLE IF NOT EXISTS photo_card_attempts (
  user_id      UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,

  -- شمارندهٔ خطاهای **پشت‌سرهم**. با اولین ثبتِ موفق صفر می‌شود.
  -- چرا پشت‌سرهم و نه مجموع: کاربری که در شش ماه ۵ بار اشتباه کرده
  -- مشکوک نیست؛ کسی که پنج بار پشت‌سرهم اشتباه می‌کند دارد حدس می‌زند.
  fail_streak  INTEGER NOT NULL DEFAULT 0,

  locked_until TIMESTAMPTZ,
  last_fail_at TIMESTAMPTZ,
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ───────────────────────────────────────────────────────────────────────────
-- علتِ رفتن به صف بررسی
-- ───────────────────────────────────────────────────────────────────────────
--
-- مدیر باید بداند **چرا** این پرونده روی میزش است، چون تصمیمش فرق می‌کند:
--
--   low_confidence   موتور طرحی پیدا کرده ولی مطمئن نیست. مدیر فقط
--                    تأیید/رد می‌کند.
--   image_unknown    کد معتبر است ولی عکس با هیچ طرحی جور نشد. اینجا
--                    مدیر باید **خودش انتخاب کند** کد مالِ کدام طرح
--                    است — که همان چیزی است که مالک خواست.
--
-- بدون این ستون، هر دو حالت یکسان دیده می‌شدند و مدیر نمی‌فهمید در
-- موردِ دوم باید طرح را انتخاب کند.
ALTER TABLE photo_card_submissions
  ADD COLUMN IF NOT EXISTS review_reason VARCHAR(24) NOT NULL DEFAULT 'low_confidence';

-- مدیر ممکن است طرحی غیر از حدسِ موتور انتخاب کند. حدسِ اولیه در
-- `matched_design_id` می‌ماند تا بعداً بشود دقتِ موتور را سنجید:
-- «چند بار مدیر حدس ما را عوض کرد؟» تنها راهِ فهمیدنِ این است که آیا
-- آستانه‌ها درست تنظیم شده‌اند یا نه.
ALTER TABLE photo_card_submissions
  ADD COLUMN IF NOT EXISTS chosen_design_id UUID
  REFERENCES photo_card_designs(id) ON DELETE SET NULL;
