--  رمزگذاریِ فیلدهای مالی: جا باز کردن برای مقدارِ رمزشده
-- ============================================================================
--
-- چرا این مایگریشن لازم است
-- -------------------------
-- از امروز شمارهٔ کارت و شبا با AES-256-GCM رمز می‌شوند و در همان ستونِ
-- قبلی می‌نشینند، با پیشوندِ `enc:v1:`. مقدارِ رمزشده از متنِ ساده بلندتر
-- است:
--
--     enc:v1:  +  base64( iv[12] + tag[16] + ciphertext )
--     = 7 + 60 = ۶۷ کاراکتر برای یک کارتِ ۱۶ رقمی
--
-- پس ستونِ VARCHAR(16) جا نمی‌دهد. این مایگریشن فقط **جا باز می‌کند** و
-- قیدهای قالبی را برمی‌دارد؛ خودِ رمزگذاریِ داده‌ها کارِ
-- `scripts/encrypt-existing-fields.js` است (اسکریپت، نه SQL — چون پستگرس
-- کلیدِ رمزِ برنامه را ندارد و نباید داشته باشد).
--
-- چرا قیدهای CHECK برداشته می‌شوند
-- --------------------------------
-- `users_bank_card_number_digits` می‌گفت «فقط ۱۶ رقم» و
-- `users_bank_card_sheba_format` می‌گفت «IR + ۲۴ رقم». مقدارِ رمزشده این
-- قالب را رعایت نمی‌کند، پس با وجودِ آن‌ها هر نوشتن خطا می‌داد.
--
-- ⚠️ اعتبارسنجیِ قالبی **حذف نشده** — جابه‌جا شده: به
--    `services/bankCardService.js` → `validateCardInput()` که پیش از
--    ذخیره، همان دو قالب به‌علاوهٔ چک‌سامِ Luhn و mod-97 شبا را می‌سنجد.
--    تفاوت مهم: آن اعتبارسنجی *بهتر* است (چک‌سام هم می‌گیرد) و روی هر سه
--    مسیرِ نوشتن اجرا می‌شود.
-- ============================================================================

-- کاربر: کارت، شبا، و ستونِ قدیمیِ آزادِ bank_account (که کاربر ممکن است
-- روزی شمارهٔ کارتش را در آن نوشته باشد).
ALTER TABLE users ALTER COLUMN bank_card_number TYPE VARCHAR(160);
ALTER TABLE users ALTER COLUMN bank_card_sheba  TYPE VARCHAR(200);
ALTER TABLE users ALTER COLUMN bank_account     TYPE VARCHAR(400);

-- اسنپ‌شاتِ کارت در لحظهٔ درخواست برداشت — همان مقدارها، همان طول‌ها.
ALTER TABLE withdrawal_requests ALTER COLUMN card_number TYPE VARCHAR(160);
ALTER TABLE withdrawal_requests ALTER COLUMN card_sheba  TYPE VARCHAR(200);

-- قیدهای قالبی که با مقدارِ رمزشده ناسازگارند.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_bank_card_number_digits;
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_bank_card_sheba_format;

