-- ═══════════════════════════════════════════════════════════════════════════
-- تفکیک «کدِ واقعی» از «کدِ تحملِ خطای خواندن»
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── مشکلی که این مایگریشن حل می‌کند ──
--
-- وقتی سیستم خودش کد می‌ساخت، الفبای تولید عمداً O، I و L نداشت. پس
-- نگاشتِ O→0 و I/L→1 در نرمال‌سازی بی‌خطر بود: هیچ کدِ واقعی‌ای این
-- حروف را نداشت.
--
-- حالا مدیر کدها را **خودش** وارد می‌کند و آن کدها از چاپخانه می‌آیند.
-- کدی مثل `QL-2026-0001` کاملاً معتبر است — ولی نرمال‌سازیِ قبلی آن را
-- به `Q1-2026-0001` تبدیل می‌کرد و کدِ مدیر بی‌سروصدا **خراب** می‌شد.
-- در تست واقعی دقیقاً همین اتفاق افتاد.
--
-- ── راه‌حل: دو ستون، دو کار ──
--
--   code       آنچه مدیر وارد کرده و روی کارت چاپ شده. دست‌نخورده.
--              این چیزی است که در CSV و گزارش‌ها دیده می‌شود.
--
--   code_fold  همان کد با حروفِ مبهم یکسان‌شده. فقط برای **پیدا کردن**
--              استفاده می‌شود، هرگز نمایش داده نمی‌شود.
--
-- کاربری که روی کارت `QL-2026-O001` می‌بیند ممکن است `QL-2026-0001`
-- تایپ کند (یا برعکس). هر دو به یک fold می‌رسند، پس کد پیدا می‌شود —
-- بدون اینکه کدِ اصلی خراب شود.
--
-- ── چرا ستونِ تولیدشده و نه محاسبه در کد ──
--
-- اگر fold در جاوااسکریپت محاسبه می‌شد، جست‌وجو نمی‌توانست از ایندکس
-- استفاده کند و با ۱۵ هزار کد هر ثبت یک اسکنِ کامل جدول می‌شد. ستونِ
-- STORED یک بار محاسبه می‌شود و ایندکس می‌گیرد.
--
-- مهم‌تر: تعریفِ fold در یک جا زندگی می‌کند (خودِ دیتابیس)، پس محال است
-- مسیرِ درج و مسیرِ جست‌وجو دو تعریفِ متفاوت داشته باشند.

ALTER TABLE photo_card_codes
  ADD COLUMN IF NOT EXISTS code_fold TEXT
  GENERATED ALWAYS AS (translate(upper(code::text), 'OIL', '011')) STORED;

-- ── چرا UNIQUE و نه ایندکس ساده ──
--
-- اگر مدیر هم `QL-2026-O001` و هم `QL-2026-0001` را وارد کند، کاربری که
-- کارت را در دست دارد نمی‌تواند بگوید کدام‌یک را دارد — روی چاپ یکسان
-- دیده می‌شوند. آن‌وقت ثبتِ یکی، دیگری را هم عملاً می‌سوزاند یا بدتر،
-- کاربر امتیازِ کارتِ اشتباه را می‌گیرد.
--
-- پس این حالت در سطح دیتابیس ممنوع می‌شود و مدیر همان لحظهٔ ورود
-- می‌فهمد، نه ماه‌ها بعد از روی شکایت کاربر.
CREATE UNIQUE INDEX IF NOT EXISTS idx_photo_codes_fold
  ON photo_card_codes(code_fold);
