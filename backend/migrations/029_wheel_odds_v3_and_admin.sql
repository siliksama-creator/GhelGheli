-- ۲. چرخش نامحدود برای تست
--
-- مالک: «تعداد گردونه شانس کاربر ادمین رو بی نهایت کن که بتونه تست بگیره».
--
-- یک پرچم روی خودِ کاربر، نه یک لیست سخت‌کدشده از شماره‌ها. سه دلیل:
--
--   * شمارهٔ ادمین می‌تواند عوض شود و یک ثابت در کد از قلم می‌افتد؛
--   * مالک ممکن است بخواهد یک حساب تست دیگر هم بسازد بدون انتشار نسخه؛
--   * پرچم در دیتابیس یعنی می‌شود در ممیزی دید چه کسی نامحدود است —
--     یک `WHERE unlimited_spins` و تمام.
--
-- جوایز نقدیِ این حساب‌ها هم واریز می‌شود (وگرنه تست واقعی نیست)، ولی
-- چون فقط دست مالک است، خطری ندارد.
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS unlimited_spins BOOLEAN NOT NULL DEFAULT FALSE;

-- حساب‌های مدیر در جدول جداگانه‌ای هستند (admin_users)، ولی مالک با یک
-- حساب کاربری معمولی هم وارد اپ می‌شود تا تست کند. پرچم روی همان حساب
-- کاربری می‌نشیند.
--
-- MAIN_ADMIN_USERNAME معمولاً 'Admin' است؛ اگر حساب کاربری‌ای با همین نام
-- مستعار وجود داشته باشد، پرچمش روشن می‌شود. اگر نبود، این UPDATE هیچ
-- ردیفی را عوض نمی‌کند و مالک می‌تواند بعداً از پنل روشنش کند.
UPDATE users SET unlimited_spins = TRUE
 WHERE nickname = 'Admin' OR mobile = 'Admin';

CREATE INDEX IF NOT EXISTS idx_users_unlimited_spins
  ON users(id) WHERE unlimited_spins = TRUE;

