-- ۱. چرا احتمالات دوباره پایین آمد
--
-- مالک: «ما قمار نساختیم که بخوایم در ازای چرخش پول از کاربر بگیریم».
--
-- این نکتهٔ کلیدی است و قبلاً درست وزن داده نشده بود. یک گردونهٔ پولی
-- می‌تواند سخاوتمند باشد چون ورودی دارد؛ گردونهٔ رایگان هر تومانی که
-- می‌دهد **خرجِ خالص** است. تنها ترمزِ موجود، سقفِ تعداد چرخش است:
--
--     ۱ چرخش پایه در روز
--   + ۱ چرخش به ازای هر ۱۰ دعوت، تا سقف ۵۰ دعوت   →  حداکثر ۶ در روز
--   + ۳ چرخش یک‌باره به ازای هر دعوت
--
-- پس احتمال‌ها باید طوری باشند که حتی کاربری که این سقف را کاملاً پر
-- می‌کند، در طول یک سال شانس ناچیزی برای جوایز بزرگ داشته باشد.
--
-- مخرج از یک میلیون به **ده میلیون** رفت تا «۱ در یک میلیون» قابل بیان
-- باشد.
--
--   جایزه            یک در هر      شانس یک کاربر در یک سال (۲ چرخش/روز)
--   ۱۰۰ امتیاز              ۱.۶     —
--   ۵۰۰ امتیاز              ۳.۶     —
--   ۱۰۰۰ امتیاز            ۱۱       —
--   ۲۰۰۰ امتیاز           ۱۲۵       —
--   ۵۰۰۰ امتیاز         ۱٬۰۰۰       ۵۳٪
--   ۱۰٬۰۰۰ تومان       ۲۰٬۰۰۰       ۳.۷٪
--   ۵۰٬۰۰۰ تومان      ۲۵۰٬۰۰۰       ۰.۳٪
--   ۱۰۰٬۰۰۰ تومان   ۱٬۰۰۰٬۰۰۰       ۰.۰۸٪
--                              ────────────────
--                   هزینهٔ نقدی هر چرخش: ۰.۸۰ تومان
--
-- با ۱۰٬۰۰۰ کاربر فعال و ۲ چرخش روزانه، ماهانه حدود ۴۸۰ هزار تومان — که
-- یک اشتراک پلاس هزینهٔ دو هزار کاربر را پوشش می‌دهد.
--
-- جایزه‌های امتیازی سخاوتمند ماندند (میانگین ۳۱۳ امتیاز در هر چرخش) چون
-- امتیاز ارز داخلی است و هزینهٔ واقعی ندارد؛ چیزی که سفت شد فقط بخش نقدی
-- است.

