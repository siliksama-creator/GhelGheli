-- ۳. ایندکس‌های سرعت
--
-- این‌ها از ممیزی کوئری‌های داغ آمده‌اند. هیچ‌کدام قابلیتی را عوض نمی‌کنند؛
-- فقط جلوی اسکن کامل جدول را در مسیرهایی می‌گیرند که با رشد داده کند
-- می‌شوند.

-- شمارش دعوت‌ها: در هر بار باز شدن گردونه و صفحهٔ دعوت صدا زده می‌شود.
-- ایندکس قبلی روی referred_by بود ولی شرط status='active' را پوشش نمی‌داد،
-- پس Postgres باید هر ردیف را می‌خواند تا وضعیتش را ببیند.
CREATE INDEX IF NOT EXISTS idx_users_referred_active
  ON users(referred_by) WHERE status = 'active' AND referred_by IS NOT NULL;

-- تاریخچهٔ چرخش کاربر — با ایندکس ترکیبی، ORDER BY هم از خود ایندکس
-- می‌آید و مرتب‌سازی جداگانه لازم نیست.
CREATE INDEX IF NOT EXISTS idx_wheel_spins_user_time
  ON wheel_spins(user_id, created_at DESC);

-- جمع کمیسیون معرف: صفحهٔ دعوت هر بار SUM می‌گیرد.
CREATE INDEX IF NOT EXISTS idx_referral_earnings_sum
  ON referral_earnings(referrer_id) INCLUDE (earned_points);
