-- ════════════════════════════════════════════════════════════════════════════
--  برنامه‌های پیشنهادی — کادرهای معرفیِ اپ/سایت در «بیشتر»
-- ════════════════════════════════════════════════════════════════════════════
--
-- ── خواستهٔ مالک (۲۶ شهریور) ────────────────────────────────────────────────
--
--   «یک قسمت برنامهٔ پیشنهادی برایم بساز در قسمت (بیشتر) وب و اندروید که از
--    پنل ادمین مدیریت بشه و در صورتی که ادمین تیک فعال رو زد، این قسمت در
--    اپلیکیشن و وب‌سایت نمایش داده بشه. ادمین می‌تونه برنامه یا سایت معرفی
--    کنه با لینک دانلود یا لینک ورود به وب‌سایت، به همراه عکس و توضیحات...
--    بدونِ نیاز به آپدیت اندروید و وب‌سایت.»
--
-- ── چرا جدول لازم است و از `app_settings` کافی نبود ───────────────────────
--
-- محتوای این بخش **فهرستِ متغیرالطول** است: امروز دو برنامه، فردا بیست‌تا.
-- گذاشتنش داخلِ JSONِ تنظیمات یعنی ذخیرهٔ آرایه در یک ردیف و از دست دادنِ
-- چیزهایی که همین محصول به آن‌ها عادت کرده: شناسهٔ ردیف برای ویرایشِ تک‌موردی،
-- مرتب‌سازی بدونِ بازنویسیِ کلِ آرایه، و شمارش/صفحه‌بندیِ سرور-طرف که کلاینت
-- برای «بیشتر از ۱۰ تا» لازم دارد.
--
-- ── شکلِ ردیف ─────────────────────────────────────────────────────────────
--
--   sort_order  شمارهٔ نمایش (کوچک‌تر = بالاتر). دو کار می‌کند: ترتیبِ
--               دستیِ ادمین با دکمه‌های بالا/پایین، و ترتیبِ پایدارِ
--               صفحه‌بندی (بدونِ آن، ترتیبِ ردیف‌ها بین دو درخواست می‌تواند
--               عوض شود و کاربر یک برنامه را دو بار یا صفر بار ببیند).
--   kind        «برنامه» یا «سایت» — فقط برای برچسبِ فارسی؛ لینک در هر دو
--               حالت یکسان باز می‌شود (وب هم می‌تواند لینکِ دانلود باشد).
--   image_url   مثلِ بقیهٔ تصاویرِ محصول «مسیرِ نسبی» (‎/uploads/images/…)؛
--               پس انتقالِ دامنه هیچ ردیفی را نمی‌شکند.
--   is_active   تیکِ هر ردیف: خاموش‌کردنِ یک برنامه بدونِ حذفِ آن.
--
-- ⚠️ بدونِ `user_id`: این جدول محتوای محصول است، نه دادهٔ کاربر. پس در
--    `tools/reset_for_launch.py` باید در فهرستِ «نگه‌دار» باشد (اگر پاک شود،
--    صبحِ عرضه پنلِ خالی داریم) و ستونِ تصویرش هم باید در `KEEP_FILES` باشد
--    وگرنه پاک‌کنندهٔ فایل‌های یتیم، عکس‌های معرفی را قربانی می‌کند.
--
-- گاردِ `backend/scripts/testResetGuard.js` همین را قفل می‌کند.
-- ⚠️ شناسه **UUID** است، نه SERIAL — و این تصمیم دو دلیلِ محکم دارد:
--
--   ۱. **گاردِ امنیتیِ پروژه.** `backend/scripts/testValidation.js` هر مسیرِ
--      `:id` را ملزم می‌کند نگهبانِ UUID داشته باشد (`validateUuid`)، چون
--      شناسهٔ جعلی اگر به کوئری برسد، از دیتابیس یک ۵۰۰ بیرون می‌آید به‌جای
--      یک ۴۰۰ تمیز. با `SERIAL`، همان نگهبان **همهٔ** شناسه‌های درست را هم
--      رد می‌کرد (پنل هیچ‌وقت نمی‌توانست ویرایش/حذف کند) و بدونِ نگهبان هم
--      گارد قرمز می‌شد. UUID هر دو طرف را هم‌راستا می‌کند.
--   ۲. هم‌شکلِ بقیهٔ جدول‌های «موجودیت»ِ محصول (کارت‌ها، جوایز، کاربران)
--      که همه UUID‌اند؛ یک نوعِ متفاوت فقط برای این جدول، یک استثنای
--      به‌یادماندنی می‌سازد.
CREATE TABLE IF NOT EXISTS recommended_apps (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  title       TEXT        NOT NULL,
  description TEXT        NOT NULL DEFAULT '',
  link_url    TEXT        NOT NULL,
  kind        TEXT        NOT NULL DEFAULT 'app',
  image_url   TEXT        NOT NULL DEFAULT '',
  is_active   BOOLEAN     NOT NULL DEFAULT TRUE,
  sort_order  INTEGER     NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- ⚠️ UUID و با کلیدِ خارجی به `admin_users`. نسخهٔ اولِ این مایگریشن
  --    `INTEGER` بود و **همهٔ** ثبت/ویرایش‌های پنل را در تولید می‌شکست
  --    (شناسهٔ ادمین در این پروژه UUID است). گاردِ
  --    `testRecommendedApps.js` حالا همین را قفل می‌کند.
  updated_by_admin_id UUID REFERENCES admin_users(id) ON DELETE SET NULL,

  -- تنها دو نوعِ مجاز. CHECK اینجا هست (برخلافِ منابعِ سکه در ۰۹۱) چون این
  -- فهرست بسته است و مقدارِ نامعتبر یعنی برچسبِ خام روی کارتِ کاربر.
  CONSTRAINT recommended_apps_kind_check CHECK (kind IN ('app', 'website')),

  -- لینک باید http(s) باشد. بدونِ این، ادمینِ خسته «www.example.com» می‌نویسد
  -- و لینکِ بی‌scheme در وب به آدرسِ خودمان باز می‌شود (رفتارِ مرورگر) — یعنی
  -- کارتِ معرفی، کاربر را به صفحهٔ خانهٔ خودمان می‌برد.
  CONSTRAINT recommended_apps_link_check CHECK (link_url ~* '^https?://'),

  CONSTRAINT recommended_apps_title_len CHECK (char_length(title) BETWEEN 2 AND 60)
);

-- کوئریِ کاربر «فقط فعال‌ها، به ترتیبِ نمایش» است؛ همین ایندکس هر دو شرط
-- و ترتیبِ صفحه‌بندی را پوشش می‌دهد.
CREATE INDEX IF NOT EXISTS recommended_apps_order_idx
  ON recommended_apps (is_active, sort_order, id);

-- تیکِ «نمایش در اپ و وب» عمداً مایگریشن نمی‌خواهد: داخلِ همان JSONِ
-- `client_config` و زیرِ کلیدِ `features.recommendedApps` ذخیره می‌شود تا
-- کلاینت‌های قدیمی کلیدِ ناشناخته را نادیده بگیرند و یک اهرمِ موجود
-- («اهرمِ بدون‌آپدیت») دوباره ساخته نشود.
--
-- ثبتِ خودِ این مایگریشن کارِ `scripts/migrate.js` است (ستون‌های
-- `filename`/`executed_at`)؛ اینجا دستی INSERT نمی‌کنیم.
