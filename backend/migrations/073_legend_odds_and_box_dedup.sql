-- ═══════════════════════════════════════════════════════════════════════════
-- کاهش شانس لجند + پشتیبانی از صندوقِ بدونِ تکرار
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── چرا شانس لجند کم می‌شود ──
--
-- شبیه‌سازی با موتور واقعی (`resolveRound`) و کارت‌های واقعیِ تولید نشان داد
-- کاربرِ بدونِ کارت در برابرِ کسی که فقط **یک** صندوق خریده ۹۵٪ می‌بازد.
-- لجند با بونسِ کمیابیِ ۲۴ (بالاترین در `RARITY_BONUS`) سهمِ بزرگی در این
-- شکاف دارد. ۳٪ برای کارتی با این وزن، زیاد بود.
--
-- ۳٪ ⇒ ۱٪ یعنی یک لجند تقریباً هر ۲۰ صندوق به‌جای هر ۷ صندوق. هم شکافِ
-- قدرت کمتر می‌شود، هم لجند واقعاً حسِ «کمیاب» می‌دهد — که پیش از این
-- نمی‌داد.
--
-- ── وزنِ آزادشده کجا می‌رود ──
--
-- خواستهٔ مالک: «به کلاس تعریف شده خود کارت». یعنی تناسبِ فعلیِ کلاس‌ها
-- نباید به هم بخورد. ۲۰ واحدِ آزادشده **به نسبتِ وزنِ فعلیِ هر کلاس** پخش
-- شده، نه یکنواخت:
--
--   normal  400 ⇒ 409   (۴۰.۰٪ ⇒ ۴۰.۹٪)
--   silver  300 ⇒ 306   (۳۰.۰٪ ⇒ ۳۰.۶٪)
--   gold    150 ⇒ 153   (۱۵.۰٪ ⇒ ۱۵.۳٪)
--   premium 120 ⇒ 122   (۱۲.۰٪ ⇒ ۱۲.۲٪)
--   legend   30 ⇒  10   ( ۳.۰٪ ⇒  ۱.۰٪)
--                ────
--                 1000
--
-- ⚠️ جمع باید دقیقاً ۱۰۰۰ بماند. `normal` یک واحد گردکردن را جذب می‌کند
--    (۴۰۸.۱ ⇒ ۴۰۹) چون بزرگ‌ترین سطل است و یک‌دهم درصد در آن نامحسوس است.

UPDATE card_box_odds SET weight_permille = 409, updated_at = NOW() WHERE rarity = 'normal';
UPDATE card_box_odds SET weight_permille = 306, updated_at = NOW() WHERE rarity = 'silver';
UPDATE card_box_odds SET weight_permille = 153, updated_at = NOW() WHERE rarity = 'gold';
UPDATE card_box_odds SET weight_permille = 122, updated_at = NOW() WHERE rarity = 'premium';
UPDATE card_box_odds SET weight_permille =  10, updated_at = NOW() WHERE rarity = 'legend';

-- گاردِ جمع: اگر روزی کسی دستی وزنی را عوض کرد و جمع از ۱۰۰۰ در رفت،
-- همین‌جا بفهمیم نه در قرعه‌کشیِ یک خریدِ ۱۰۰٬۰۰۰ تومانی.
DO $$
DECLARE s INTEGER;
BEGIN
  SELECT COALESCE(SUM(weight_permille), 0) INTO s FROM card_box_odds;
  IF s <> 1000 THEN
    RAISE EXCEPTION 'جمع شانس‌های صندوق باید ۱۰۰۰ باشد، الان % است', s;
  END IF;
END $$;

-- ── ستونِ «این صندوق بدونِ تکرار بود» ──────────────────────────────────
--
-- خواستهٔ مالک: «بین کارت‌هایی که به کاربر بدون کارت داده میشه تکراری
-- نباشه». یعنی قاعده فقط برای **اولین** صندوقِ کاربرِ بی‌کارت است، نه همهٔ
-- صندوق‌ها — تکرار در صندوق‌های بعدی عمدی است چون جوایزِ پلکانی
-- (`reward_tier_cards`) چند نسخه از یک کارت می‌خواهند.
--
-- این ستون فقط سند است، نه منطق: منطق در `grantBox` است. اما بدونِ آن،
-- بعداً هیچ راهی نیست بفهمیم یک صندوقِ قدیمی با کدام قاعده قرعه خورده —
-- دقیقاً همان دلیلی که `odds_snapshot` وجود دارد.
ALTER TABLE card_box_purchases
  ADD COLUMN IF NOT EXISTS distinct_cards BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN card_box_purchases.distinct_cards IS
  'آیا این صندوق با قاعدهٔ «بدون کارت تکراری» قرعه خورد (اولین صندوقِ کاربرِ بی‌کارت).';
