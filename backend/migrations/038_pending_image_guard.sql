-- ═══════════════════════════════════════════════════════════════════════════
-- جلوگیری از ارسالِ دوبارهٔ عکسی که هنوز در صف بررسی است
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── سناریوی واقعی که این را لازم می‌کند ──
--
-- کاربر ۱۰ کارت دارد با ۱۰ کد. عکسِ کارتِ اول را می‌فرستد، کیفیت پایین
-- است و پرونده به صف بررسی می‌رود. کاربر منتظر نمی‌ماند: **همان عکس**
-- را با **کدِ دوم** دوباره می‌فرستد.
--
-- بدون محافظ، این کار می‌کند و کاربر دو کارت می‌گیرد در حالی که فقط
-- یکی دارد — و کدِ دوم هم بی‌دلیل سوخته است.
--
-- برای گرفتنِ این حالت باید بدانیم «عکسی که الان آمد، همان عکسی است که
-- قبلاً فرستاده؟». مقایسهٔ بایت‌به‌بایت کافی نیست: کاربر ممکن است همان
-- عکس را دوباره فشرده کند یا کمی برش بزند. پس اثر انگشتِ ادراکی لازم
-- است — همان چیزی که موتور تطبیق می‌سازد.
--
-- ⚠️ فقط برای پرونده‌های `pending` مهم است. بعد از تعیین تکلیف، کد
--    یا مصرف شده (پس دیگر قابل استفاده نیست) یا آزاد شده (پس کاربر
--    حق دارد دوباره تلاش کند).

ALTER TABLE photo_card_submissions
  ADD COLUMN IF NOT EXISTS img_dhash BYTEA,
  ADD COLUMN IF NOT EXISTS img_phash BYTEA,
  ADD COLUMN IF NOT EXISTS img_color REAL[],
  ADD COLUMN IF NOT EXISTS img_tex   REAL[];

-- مسیرِ داغ: «آیا این کاربر پروندهٔ در انتظاری دارد؟» در هر ثبت اجرا
-- می‌شود، پس ایندکسِ جزئی می‌گیرد. جزئی چون فقط pending مهم است و
-- اکثر ردیف‌ها بعد از مدتی approved/rejected می‌شوند.
CREATE INDEX IF NOT EXISTS idx_photo_sub_user_pending
  ON photo_card_submissions(user_id) WHERE status = 'pending';
