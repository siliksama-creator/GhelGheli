-- ── باگی که این مایگریشن رفع می‌کند ──
--
-- در کامیت «سیگنال چهارم» یک سیگنالِ جدید (`texSig`) به موتورِ تطبیق
-- اضافه شد و وزن‌ها بر اساسِ آن بازتنظیم شدند. ولی **ستونِ دیتابیس
-- اضافه نشد**.
--
-- نتیجه‌اش بی‌سروصدا و بدتر از یک کرشِ آشکار بود:
--
--   • اثرانگشتِ عکسِ کاربر `texSig` **داشت** (تازه محاسبه می‌شود)
--   • اثرانگشتِ طرحِ ذخیره‌شده `texSig` **نداشت** (از DB می‌آید)
--   • `similarity` شرطِ `hasTex` را رد می‌کرد و به فرمولِ جایگزین
--     می‌افتاد: ۰.۳۵/۰.۱۸/۰.۴۷ به‌جای ۰.۳۰/۰.۱۵/۰.۴۰/۰.۱۵
--
-- یعنی آستانه‌هایی که با دقت روی فرمولِ چهارسیگناله کالیبره شده بودند،
-- روی فرمولِ سه‌سیگناله اعمال می‌شدند. در تستِ زنده دیده شد: یک کارت
-- تأیید خودکار گرفت و کارتِ دیگر با همان کیفیتِ عکس به صف بررسی رفت.
--
-- درسِ این مورد: وقتی یک سیگنال به اثرانگشت اضافه می‌شود، **مسیرِ
-- ماندگاری‌اش** هم باید همان لحظه اضافه شود. تستِ واحد این را نمی‌گرفت
-- چون آنجا هر دو طرف در حافظه ساخته می‌شوند و هر دو `texSig` دارند —
-- فقط مسیرِ واقعیِ «ذخیره در DB و خواندنِ دوباره» آن را آشکار می‌کند.

-- NULL مجاز است تا طرح‌های موجود بشکنند: `similarity` وقتی یک طرف
-- بافت ندارد به فرمولِ سه‌سیگناله برمی‌گردد. اسکریپتِ
-- `scripts/backfillTextureSig.js` آن‌ها را پر می‌کند.
ALTER TABLE photo_card_designs
  ADD COLUMN IF NOT EXISTS tex_sig REAL[];
