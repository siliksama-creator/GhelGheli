-- توکن‌های متنیِ خوانده‌شده از روی کارت (OCR)
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── چرا این ستون لازم است ──
--
-- خواستهٔ صریح مالک: «کاش سیستمی که شباهت عکس رو داره پیدا میکنه،
-- متن‌های روی عکس رو زمان آپلود ادمین و آپلود کاربر سعی کنه بخونه که
-- اینطوری درصد اشتباه کمتر شه».
--
-- اندازه‌گیری روی عکسِ واقعیِ یک کاربر (کارتِ دمبله روی میزِ چوبی) که
-- در پنل با حدسِ اشتباه ظاهر شده بود:
--
--     مرجع        تصویر   متن     نهایی
--     Hakimi-B    ۰.۵۳۳   ۰.۰۰    ۰.۳۸۳   ← از رتبهٔ ۱ به ۳
--     Dembélé-B   ۰.۵۰۰   ۰.۵۰    ۰.۵۳۵   ← برندهٔ درست
--     Dembélé-A   ۰.۳۱۵   ۱.۰۰    ۰.۴۶۵
--     Hakimi-A    ۰.۳۶۷   ۰.۰۰    ۰.۲۱۷
--
-- تصویر به‌تنهایی کارتِ اشتباه را با حاشیهٔ ۰.۰۳۳ برنده کرده بود. با
-- افزودنِ متن، کارتِ درست برنده شد و حاشیه به ۰.۰۷۰ رسید.
--
-- ⚠️ درسی که با `tex_sig` و بعد `rgb_sig` گرفته شد و اینجا تکرار
--    نمی‌شود: سیگنال به اثرانگشت اضافه شد ولی ستونش به دیتابیس نه.
--    مقدار محاسبه می‌شد، دور ریخته می‌شد، و موتور بی‌صدا به فرمولِ
--    قدیمی برمی‌گشت. هیچ خطایی هم در کار نبود.
--
--    `scripts/testFingerprintWiring.js` حالا این اتصال را می‌سنجد و
--    اگر ستونی جا بیفتد قرمز می‌شود.
--
-- ── چرا TEXT[] و نه یک رشتهٔ ساده ──
--
-- تطبیق روی **مجموعهٔ توکن‌ها** انجام می‌شود، نه روی متنِ کامل. خروجیِ
-- خامِ OCR پر از نویز است (`~EMBELE`, `PR AN oc.`) و ترتیبِ خطوط بین
-- دو عکس از یک کارت هم فرق می‌کند. ذخیرهٔ آرایه یعنی مقایسه بدونِ
-- تجزیهٔ دوباره در هر درخواست.
--
-- ── چرا nullable ──
--
-- OCR ممکن است روی عکسِ تارِ شدید هیچ چیزی نخواند، یا tesseract اصلاً
-- روی سرور نصب نباشد. آرایهٔ خالی و NULL هر دو یعنی «متنی نداریم» و
-- موتور در آن حالت فقط به تصویر تکیه می‌کند — دقیقاً مثلِ قبل.

ALTER TABLE photo_card_designs
  ADD COLUMN IF NOT EXISTS text_tokens TEXT[];

ALTER TABLE photo_card_submissions
  ADD COLUMN IF NOT EXISTS img_text TEXT[];

-- ── ایندکس برای جست‌وجوی آیندهٔ «کدام کارت این نام را دارد؟» ──
--
-- هنوز استفاده نمی‌شود، ولی GIN روی آرایه ارزان است و وقتی کاتالوگ به
-- صدها کارت برسد، فیلترِ اولیه بر پایهٔ متن می‌تواند مقایسهٔ تصویری را
-- فقط روی چند نامزد اجرا کند به‌جای کلِ کاتالوگ.
CREATE INDEX IF NOT EXISTS idx_photo_designs_text
  ON photo_card_designs USING GIN (text_tokens);
