-- کدهایی که از قبل می‌دانیم مالِ کدام کارت‌اند.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- مسئله‌ای که مالک توصیف کرد
-- ═══════════════════════════════════════════════════════════════════════════
--
-- «یک سری کارت‌ها را قدیم دادیم تو بازار، دقیقاً نمی‌دانستیم که هر کد
--  روی کدام کارت قرار گرفته — برای همین سیستم تشخیص عکس را راه انداختیم.
--  ولی یک سری کارت‌های جدید هم دادیم که آن‌ها را می‌دانیم دقیقاً چه کدی
--  برای چه کارتی است.»
--
-- یعنی بانکِ کد از این به بعد **دو جنس** دارد و هر کدام رفتار متفاوتی
-- می‌خواهد:
--
--   ۱. کدِ «بی‌نام» (وضع موجود) — نمی‌دانیم مالِ کدام کارت است. تنها
--      راهِ تشخیص، موتورِ تصویر است. آستانه باید سخت‌گیر بماند وگرنه
--      کاربر می‌تواند عکسِ کارتِ ارزان را با کدِ کارتِ گران بفرستد.
--
--   ۲. کدِ «نام‌دار» (جدید) — می‌دانیم برای کدام کارت چاپ شده. اینجا
--      خودِ کد مدرکِ مالکیت است؛ عکس فقط باید ثابت کند کاربر کارتِ
--      فیزیکی را در دست دارد، نه اینکه هویتِ کارت را تعیین کند.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- چرا یک ستون، و نه یک جدولِ جدید
-- ═══════════════════════════════════════════════════════════════════════════
--
-- وسوسه‌کننده بود که جدولِ `photo_card_batches` بسازیم و کدها را به آن
-- گره بزنیم. ولی رابطه واقعاً «هر کد → حداکثر یک نوع کارت» است، نه
-- چیزی پیچیده‌تر. یک ستونِ nullable دقیقاً همین را می‌گوید و هیچ JOINِ
-- اضافه‌ای به مسیرِ داغِ ثبت تحمیل نمی‌کند.
--
-- NULL معنیِ روشنی دارد: «نمی‌دانیم» — یعنی همان رفتارِ امروز. پس هر
-- ۵۱۴ کدِ موجود بدون هیچ backfill ای دقیقاً مثل قبل کار می‌کنند.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- چرا ON DELETE RESTRICT
-- ═══════════════════════════════════════════════════════════════════════════
--
-- اگر مدیر نوعِ کارتی را حذف کند که هزار کد به آن گره خورده، آن هزار
-- کد بی‌صدا به حالتِ «بی‌نام» برمی‌گشتند (با SET NULL) یا کلاً پاک
-- می‌شدند (با CASCADE). هر دو فاجعه است: کدهایی که در دستِ مشتری‌اند.
-- RESTRICT مدیر را مجبور می‌کند اول تکلیفِ کدها را روشن کند.

BEGIN;

ALTER TABLE photo_card_codes
  ADD COLUMN IF NOT EXISTS expected_card_type_id UUID
    REFERENCES card_types(id) ON DELETE RESTRICT;

-- ایندکسِ جزئی: فقط ردیف‌هایی که واقعاً گره خورده‌اند.
--
-- چرا جزئی: اکثریتِ قاطعِ کدها NULL می‌مانند (کارت‌های قدیمی). ایندکسِ
-- کامل روی ستونی که ۹۰٪ NULL است، فضا می‌گیرد و هیچ کوئری‌ای را سریع
-- نمی‌کند. تنها پرس‌وجوی واقعی «کدهای این نوع کارت کدام‌اند؟» است که
-- ذاتاً NOT NULL را می‌خواهد.
CREATE INDEX IF NOT EXISTS idx_photo_codes_expected_type
  ON photo_card_codes(expected_card_type_id)
  WHERE expected_card_type_id IS NOT NULL;

-- ── ردِ تصمیم روی خودِ پرونده ──
--
-- بدونِ این، بعداً نمی‌شود فهمید یک ثبت از چه راهی تأیید شده. وقتی
-- مالک بپرسد «چند درصدِ ثبت‌ها خودکار شد؟» یا وقتی بخواهیم بفهمیم
-- آستانهٔ نرم باعثِ سوءاستفاده شده یا نه، این ستون تنها منبع است.
--
-- مقادیر:
--   'code_bound'  کد از پیش به این کارت گره خورده بود؛ عکس فقط تأیید کرد
--   'image_match' کدِ بی‌نام + تشخیصِ قاطعِ تصویر (رفتارِ قدیمی)
--   'admin'       مدیر دستی تأیید کرد
ALTER TABLE photo_card_submissions
  ADD COLUMN IF NOT EXISTS decision_path VARCHAR(16);

COMMENT ON COLUMN photo_card_codes.expected_card_type_id IS
  'اگر بدانیم این کد برای کدام کارت چاپ شده. NULL = کدِ بی‌نامِ قدیمی.';
COMMENT ON COLUMN photo_card_submissions.decision_path IS
  'code_bound | image_match | admin — چگونه تصمیم گرفته شد.';

COMMIT;
