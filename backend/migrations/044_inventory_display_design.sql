-- ═══════════════════════════════════════════════════════════════════════════
-- طرحِ نمایشیِ اینونتوری — «رو یا پشت، تصادفی»
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ── خواستهٔ مالک ──
--
--   «وقتی کاربر کارت رو ثبت میکنه بصورت تصادفی پشت و یا روی کارت انتخاب
--    بشه، اینطوری زیبایی اینونتوری بیشتر میشه»
--
-- ── چرا یک ستونِ تازه لازم شد و نه یک `ORDER BY random()` در کوئری ──
--
-- وسوسه‌کننده است که هنگامِ **خواندنِ** اینونتوری تصادفی انتخاب کنیم. آن
-- راه‌حل خراب است و دلیلش ظریف است: کاربر هر بار صفحه را باز کند، کارتش
-- ورق می‌خورد. کارتِ Hakimi صبح «رو» است و ظهر «پشت». این نه زیبایی که
-- حسِ خرابی می‌دهد — و مهم‌تر، **کشِ سمتِ کلاینت را بی‌اثر می‌کند**:
-- درخواستِ بعدی URL دیگری می‌خواهد، پس دانلودِ دوباره. یعنی دقیقاً همان
-- چیزی که در همین جلسه قرار است حل شود را می‌شکند.
--
-- پس انتخاب باید **یک بار، در لحظهٔ ثبت** انجام شود و ثابت بماند.
--
-- ── چرا ارجاع به `photo_card_designs` و نه کپیِ متنِ URL ──
--
-- اگر مدیر عکسِ طرح را عوض کند (کیفیتِ بهتر، برشِ درست‌تر)، ارجاع خودش
-- به‌روز می‌شود ولی کپیِ متنی به فایلِ حذف‌شده اشاره می‌کند و کاربر
-- تصویرِ شکسته می‌بیند. ارجاع همیشه صادق می‌ماند.
--
-- `ON DELETE SET NULL` عمدی است: اگر آن طرحِ خاص حذف شود، اینونتوری
-- نباید بشکند — به تصویرِ پیش‌فرضِ `card_types.image_url` برمی‌گردد.
-- این همان رفتاری است که قبل از این مایگریشن وجود داشت، پس بدترین حالت
-- «مثل قبل» است نه «خراب».
--
-- ── چرا NULL برای ردیف‌های موجود مشکلی نیست ──
--
-- کوئری‌های خواننده از `COALESCE(d.image_url, t.image_url)` استفاده
-- می‌کنند. ردیفِ قدیمی که این ستون را ندارد دقیقاً همان تصویری را نشان
-- می‌دهد که تا امروز می‌داد. هیچ backfill لازم نیست.

ALTER TABLE user_card_inventory
  ADD COLUMN IF NOT EXISTS display_design_id UUID
    REFERENCES photo_card_designs(id) ON DELETE SET NULL;

-- ایندکس عمداً ساخته **نمی‌شود**.
--
-- این ستون هرگز در WHERE یا JOIN-به‌عنوان-فیلتر استفاده نمی‌شود؛ فقط در
-- یک LEFT JOIN روی کلیدِ اصلیِ خودِ `photo_card_designs` دنبال می‌شود که
-- ایندکسِ pkey دارد. ایندکسِ اضافه فقط هر INSERT را کندتر می‌کند.

COMMENT ON COLUMN user_card_inventory.display_design_id IS
  'طرحی (رو یا پشت) که برای نمایش در اینونتوری تصادفی انتخاب شده. NULL یعنی از card_types.image_url استفاده شود.';
