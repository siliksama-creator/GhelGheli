-- کارت‌های کلکسیونی: کارت‌هایی که برای بازی نیستند
--
-- ═══════════════════════════════════════════════════════════════════════════
-- خواستهٔ مالک
-- ═══════════════════════════════════════════════════════════════════════════
--
-- «قسمت ثبت کارت توسط ادمین در پنل وب و اندروید باید دقیقا به همین سبک
--  کارت اضافه کند ولی بدون استاتس برای بازی یعنی کارت هایی که برای بازی
--  نیستن»
--
-- یعنی کاتالوگ از این به بعد **دو جنس** کارت دارد:
--
--   ۱. کارتِ بازی (وضع موجود) — استاتس دارد، در آرنا قابل انتخاب است.
--   ۲. کارتِ کلکسیونی (جدید) — فقط عکس و امتیاز. کاربر جمعش می‌کند، در
--      اینونتوری می‌بیند، برای جوایز پلکانی استفاده می‌شود، ولی **هرگز**
--      در ترکیب دوئل ظاهر نمی‌شود.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- چرا یک ستونِ boolean و نه حذفِ استاتس
-- ═══════════════════════════════════════════════════════════════════════════
--
-- وسوسه‌کننده بود که استاتس‌ها را nullable کنیم و «NULL یعنی کلکسیونی».
-- سه دلیل که نکردم:
--
--   • ستون‌های duel_* همگی NOT NULL با DEFAULT و CHECK (0..100) هستند.
--     nullable کردنشان یعنی هر کوئری‌ای که جمع/مقایسه می‌کند باید COALESCE
--     بگیرد — ده‌ها نقطه، و هر کدام یک جای فراموش‌شدنی.
--
--   • «استاتس ندارد» و «استاتس‌اش صفر است» دو چیزِ متفاوت‌اند. یک کارتِ
--     بازیِ خیلی ضعیف می‌تواند واقعاً صفر داشته باشد.
--
--   • قصدِ مدیر باید صریح ذخیره شود، نه از غیابِ داده استنتاج شود. اگر
--     فردا کارتی کلکسیونی را به کارتِ بازی تبدیل کنیم، استاتسِ قبلی‌اش
--     هنوز آنجاست و از دست نرفته.
--
-- پیش‌فرض `false` است، پس هر ۲۹ کارتِ موجود دقیقاً مثل قبل کار می‌کنند و
-- هیچ backfill ای لازم نیست.

ALTER TABLE card_types
  ADD COLUMN IF NOT EXISTS is_collectible BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN card_types.is_collectible IS
  'true = کارت فقط کلکسیونی است و در دوئل قابل استفاده نیست (استاتس بی‌معنی است)';

-- ایندکسِ جزئی برای مسیرِ داغِ آرنا.
--
-- `playableCards` در هر بار باز شدنِ صفحهٔ دوئل اجرا می‌شود و حالا شرطِ
-- `is_collectible = false` هم دارد. ایندکسِ جزئی فقط ردیف‌های قابلِ بازی
-- را نگه می‌دارد، پس هم کوچک است هم دقیقاً همان چیزی که کوئری می‌خواهد.
CREATE INDEX IF NOT EXISTS idx_card_types_playable
  ON card_types (id) WHERE is_collectible = false AND is_active = true;

