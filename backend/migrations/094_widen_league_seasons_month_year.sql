-- ════════════════════════════════════════════════════════════════════════════
--  پهن‌کردنِ league_seasons.month_year — وصله‌ای که فقط روی تولید بود
-- ════════════════════════════════════════════════════════════════════════════
--
-- ── باگ ──
--
-- `001_initial_schema.sql` این ستون را `VARCHAR(7)` ساخته است؛ اندازه‌ای که
-- فقط برای کلیدِ «ماهِ» شمسی کافی بود: `1405-06`.
--
-- بعد قابلیتِ «۲ لیگِ هم‌زمان» (خواستهٔ مالک) آمد و `POST
-- /api/admin/league/seasons` شناسهٔ متمایزی می‌سازد:
--
--     monthly-2026-09-17   (۱۷ نویسه)
--
-- روی دیتابیسِ **تولیدی** این ستون دستی به `VARCHAR(32)` پهن شد (خودِ
-- مایگریشن ۰۶۵ در توضیحش به همین اشاره می‌کند: «`league_seasons.month_year`
-- در گذشته به VARCHAR(32) پهن شد»)، ولی همان `ALTER` هرگز به پوشهٔ
-- `migrations/` اضافه نشد.
--
-- نتیجه: روی تولید همه‌چیز کار می‌کرد و روی **هر دیتابیسِ تازه‌ای** که فقط
-- از مایگریشن‌ها ساخته شود (CI، بازیابی از بکاپ، نصبِ تازه) ساختنِ لیگ از
-- پنل ادمین با خطای زیر می‌شکست:
--
--     error: value too long for type character varying(7)
--       at async src/routes/adminLeague.js  (INSERT INTO league_seasons …)
--
-- ── چرا CI تا حالا نگرفته بود ──
--
-- تا امروز در CI هیچ مسیری لیگ نمی‌ساخت: تنها سازندهٔ فصل،
-- `ensureActiveSeason()` بود که با `currentMonthYear()` (مثلِ `1405-06`،
-- دقیقاً ۷ نویسه) درج می‌کرد و به سقفِ ستون می‌خورد.
--
-- با خواستهٔ مالک («بدونِ ساختِ تنظیماتِ لیگ توسطِ ادمین هیچ لیگی نباید در
-- جریان باشه») حالا **ساختنِ لیگ از پنل، مسیرِ اصلی است** — پس این واگرایی
-- باید در همین جایی که هست (مایگریشن‌ها) بسته شود، نه با یک ALTER دستیِ
-- دیگر روی سرور.
--
-- ⚠️ روی تولید این دستور بی‌خطر است: ستون از قبل ۳۲ است و فقط یک
--    بازنویسیِ بی‌اثر انجام می‌شود (جدول چند ردیف بیشتر ندارد).
ALTER TABLE league_seasons
  ALTER COLUMN month_year TYPE VARCHAR(32);

-- `user_league_history.month_year` در مایگریشن ۰۶۵ هم‌اندازه شد، ولی آن فایل
-- فرض کرده بود ستونِ مبدأ از قبل ۳۲ است. اگر این مایگریشن روی دیتابیسی
-- اجرا شود که ترتیب/وضعیتش متفاوت بوده، این خط هم‌اندازه‌بودن را تضمین
-- می‌کند تا مقدارِ `monthly-2026-09-17` هنگامِ بستنِ فصل در تاریخچه هم جا
-- شود (همان کلاسِ باگی که ۰۶۵ توصیفش کرده).
-- (DDL داخلِ بلوکِ PL/pgSQL فقط با EXECUTE مجاز است.)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public'
                AND table_name = 'user_league_history'
                AND column_name = 'month_year') THEN
    EXECUTE 'ALTER TABLE user_league_history ALTER COLUMN month_year TYPE VARCHAR(32)';
  END IF;
END $$;
