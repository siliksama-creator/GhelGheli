--
-- همان درسی که با `tex_sig` گرفته شد: وقتی سیگنالی به اثرانگشت اضافه
-- می‌شود، **مسیرِ ماندگاری‌اش** باید همان لحظه اضافه شود. وگرنه عکسِ
-- کاربر آن را دارد و طرحِ ذخیره‌شده نه، و `similarity` بی‌سروصدا به
-- فرمولِ دیگری می‌افتد که آستانه‌ها برایش کالیبره نشده‌اند.
--
-- تستِ `هر فیلدِ اثرانگشت مسیرِ ماندگاری دارد` دقیقاً برای همین نوشته
-- شد و اگر این ستون فراموش می‌شد، قرمز می‌شد.

ALTER TABLE photo_card_designs
  ADD COLUMN IF NOT EXISTS luma_sig REAL[];

-- گاردِ «عکسِ در انتظار» هم باید همین سیگنال را داشته باشد، وگرنه
-- مقایسهٔ عکسِ جدید با پرونده‌های در انتظار با فرمولِ ناقص انجام
-- می‌شود و ممکن است عکسِ تکراری را نگیرد.
ALTER TABLE photo_card_submissions
  ADD COLUMN IF NOT EXISTS img_luma REAL[];
