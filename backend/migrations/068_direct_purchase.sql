-- ═══════════════════════════════════════════════════════════════════════════
-- ۰۶۸ — خرید مستقیم از کافه‌بازار (حذف شارژ کیف پول)
-- ═══════════════════════════════════════════════════════════════════════════
--
-- تصمیم مالک که این مایگریشن اجرا می‌کند
-- ─────────────────────────────────────────────────────────────────────────
-- مایگریشن ۰۶۷ فرض کرده بود کاربر اول کیف پولش را از بازار شارژ می‌کند و
-- بعد با موجودی کیف پول، آیتم شاپ و پلاس می‌خرد. مالک این مدل را رد کرد:
--
--     «کیف پول اصلاً قرار نیست توسط کافه‌بازار شارژ بشه. فقط توسط کارت‌های
--      خاص نقدی یا یکسری جوایز لیگ و غیره شارژ میشه. مستقیماً باید توسط
--      بازار آیتم‌های شاپ و پلاس رو بخرن.»
--
-- پس دو جریان پول کاملاً از هم جدا می‌شوند:
--
--   کیف پول (پولِ کاربر، فقط ورودی + برداشت)
--     ورودی : کارت نقدی · جایزهٔ لیگ · گردونه · کمیسیون ۵٪ · واریز ادمین
--     خروجی : فقط درخواست برداشت
--     ✗ دیگر هرگز بابت خرید شاپ/پلاس کم نمی‌شود
--
--   خرید (پولِ کاربر → کافه‌بازار → ما)
--     آیتم شاپ و پلاس ۱۰۰٪ از پرداخت درون‌برنامه‌ای بازار
--     ✗ هرگز از موجودی کیف پول
--
-- چرا این تفکیک از نظر فنی هم درست‌تر است
-- ─────────────────────────────────────────────────────────────────────────
-- مدل قبلی کیف پول را به «پولِ قابل خرجِ داخلی» تبدیل می‌کرد. یعنی جایزهٔ
-- لیگ و کمیسیون معرفی می‌توانستند خرجِ آیتم شوند و درآمد واقعی ما را
-- جابه‌جا کنند بدون اینکه ریالی وارد شود. حالا هر آیتمِ فروخته‌شده دقیقاً
-- یک پرداخت واقعی پشتش دارد.

-- ── ۱. سفارش‌های پرداخت: از «شارژ» به «خرید» ──────────────────────────
--
-- جدول `payment_orders` از مایگریشن ۰۶۷ می‌ماند ولی معنایش عوض می‌شود:
-- دیگر «چقدر شارژ شد» را ثبت نمی‌کند، بلکه «چه چیزی خریداری شد».

-- چه چیزی خریداری شده. تا وقتی سفارش pending است NULL نیست — از همان
-- لحظهٔ ساخت مشخص است کاربر دنبال چه آیتمی بوده.
ALTER TABLE payment_orders
  ADD COLUMN IF NOT EXISTS purchase_kind VARCHAR(16);

-- به کدام ردیف `shop_items` اشاره دارد (برای آیتم‌های شاپ).
-- ON DELETE SET NULL نه CASCADE: اگر آیتمی از فروشگاه حذف شود، سابقهٔ
-- مالیِ خریدش نباید پاک شود — آن سند حسابرسی است.
ALTER TABLE payment_orders
  ADD COLUMN IF NOT EXISTS shop_item_id UUID
    REFERENCES shop_items(id) ON DELETE SET NULL;

-- برای پلاس: monthly | annual
ALTER TABLE payment_orders
  ADD COLUMN IF NOT EXISTS plus_cycle VARCHAR(16);

-- بعد از تحویل موفق، به رکورد نهایی وصل می‌شود تا بشود از سفارش به
-- مالکیت رسید و برعکس.
ALTER TABLE payment_orders
  ADD COLUMN IF NOT EXISTS granted_reference_id UUID;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'payment_orders'::regclass
       AND conname  = 'payment_orders_kind_check'
  ) THEN
    ALTER TABLE payment_orders
      ADD CONSTRAINT payment_orders_kind_check
      CHECK (purchase_kind IS NULL OR purchase_kind IN
             ('shop_item', 'plus_monthly', 'plus_annual'));
  END IF;
END $$;

-- سفارش‌های قدیمیِ «شارژ» (اگر روی محیطی مانده باشند) دیگر معنا ندارند.
-- فقط pendingها بی‌خطر باطل می‌شوند؛ paidها دست نمی‌خورند چون سند مالیِ
-- پول واقعی‌اند و پاک‌کردنشان دفترکل را ناتراز می‌کند.
UPDATE payment_orders
   SET status = 'failed',
       gateway_payload = COALESCE(gateway_payload, '{}'::jsonb)
                         || '{"voided_by":"068_direct_purchase"}'::jsonb,
       updated_at = NOW()
 WHERE status = 'pending'
   AND purchase_kind IS NULL;

CREATE INDEX IF NOT EXISTS payment_orders_kind_idx
  ON payment_orders (purchase_kind, status, created_at DESC);

-- ── ۲. دفترکل: منابعِ خرید دیگر تولید نمی‌شوند ────────────────────────
--
-- `shop`, `subscription`, `topup`, `topup_refund` در CHECK **باقی
-- می‌مانند** — چون ردیف‌های تاریخیِ دیتابیس این مقادیر را دارند و حذفشان
-- از CHECK یعنی جدول موجود دیگر معتبر نیست و مایگریشن می‌ترکد.
--
-- جلوگیری از تولیدِ تازه در لایهٔ کد است (`walletService.VALID_SOURCES`)،
-- نه اینجا. این تقسیم عمدی است: دیتابیس گذشته را نگه می‌دارد، کد آینده
-- را می‌سازد.
--
-- تنها منبع جدید: `purchase_referral` که از قبل هست و حالا تنها راهی است
-- که یک خرید می‌تواند به کیف پول پول اضافه کند (کمیسیون ۵٪ معرف).

-- ── ۳. کمیسیون: مبلغِ مرجع باید قیمتِ کاملِ بازار باشد ────────────────
--
-- مالک صریحاً «۵٪ از قیمت کامل» را انتخاب کرد نه از سهم خالص بعد از کسر
-- ۳۰٪ بازار. یعنی روی پلاس ۵۹٬۰۰۰ تومانی، معرف ۲٬۹۵۰ تومان می‌گیرد در
-- حالی که سهم ما از بازار ۴۱٬۳۰۰ است. این آگاهانه سخاوتمندانه است:
-- عددی که کاربر می‌بیند همان عددی است که ۵٪ رویش حساب می‌شود، و توضیح
-- «۵٪ از سهم ما بعد از کسر کارمزد» برای کاربر قابل فهم نیست.
--
-- ستون برای شفافیت حسابرسی: چقدر واقعاً به ما رسیده.
ALTER TABLE purchase_referral_commissions
  ADD COLUMN IF NOT EXISTS gateway_provider VARCHAR(32);

COMMENT ON COLUMN purchase_referral_commissions.gateway_provider IS
  'درگاهی که خرید از آن انجام شد (cafebazaar). NULL = خریدهای تاریخیِ کیف‌پولی.';
