ALTER TABLE league_seasons
  ADD COLUMN IF NOT EXISTS prize_note TEXT NOT NULL DEFAULT '';

COMMENT ON COLUMN league_seasons.prize_note IS
  'متن توضیحی جوایز. فقط اگر show_prize_list روشن باشد و این متن خالی نباشد در وب و اندروید دیده می‌شود.';

COMMENT ON COLUMN league_seasons.show_prize_list IS
  'اگر true باشد و prize_note خالی نباشد، متن توضیحی جوایز در وب و اندروید دیده می‌شود. جایزهٔ هر رتبه جداگانه روی همان رتبه است.';
