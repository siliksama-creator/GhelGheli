-- ═══════════════════════════════════════════════════════════════════
-- دورِ بیست‌وسوم: پاک‌سازیِ ایموجی از پک‌های ایموتِ فروشگاه
-- ═══════════════════════════════════════════════════════════════════
--
-- ── چرا این مایگریشن لازم شد ──
--
-- حذفِ ایموجی از کدِ کلاینت‌ها کافی نبود. سه پکِ ایموت در جدولِ
-- `shop_items` ستونِ `metadata` دارند و **محتوایشان از دیتابیس** به هر
-- دو کلاینت می‌رود:
--
--   metadata->>'icon'      →  آیکونِ تبِ پک در صفحهٔ چت
--   metadata->'messages'   →  پیام‌هایی که کاربر واقعاً می‌فرستد
--
-- یعنی حتی با کدِ تمیز، سرور همچنان «🎉» را برمی‌گرداند. این دقیقاً
-- همان الگویی است که در `missionService` هم دیدیم: ایموجی فقط در
-- کلاینت نیست، در داده هم هست.
--
-- ── چه چیزی عوض می‌شود و چه چیزی نه ──
--
--   ۱) `icon` از ایموجی به **نامِ آیکونِ مشترک** تبدیل می‌شود
--      (`handshake` / `bolt` / `party`). هر سه نام هم در
--      `IconAsset.jsx` هستند و هم در `ui_icon.dart` — گاردِ
--      `icon-parity.mjs` این را در CI تضمین می‌کند.
--
--   ۲) ایموجیِ چسبیده به **متنِ** دو پیام حذف می‌شود:
--      «گوووول! ⚽» ⇒ «گوووول!»   و   «فقط گرم کرده بودم 😄» ⇒ بدونِ 😄
--      این‌ها متنِ آمادهٔ فروشگاه‌اند، نه ایموجیِ انتخابیِ کاربر؛ پس
--      مشمولِ همان قاعده‌اند. آینهٔ همین تغییر در `shop_page.dart`
--      (فهرستِ پیش‌نمایش) هم اعمال شد.
--
-- ── چه چیزی عمداً دست نمی‌خورد ──
--
-- پالتِ ایموجیِ صفحهٔ چت (`_emojis` در فلاتر و `EMOJIS` در وب).
-- آن‌ها محتوایی‌اند که کاربر خودش انتخاب و ارسال می‌کند، نه عنصرِ
-- رابطِ کاربری. تنها استثنای مصوبِ این دور همان است.
--
-- ── چرا UPDATE و نه ویرایشِ ۰۵۲ ──
--
-- مایگریشنِ ۰۵۲ روی تولید **اجرا شده**. ویرایشِ فایلِ اجراشده هیچ
-- اثری روی دیتابیسِ زنده ندارد و فقط تاریخچه را دروغین می‌کند. پس
-- فایلِ ۰۵۲ دست‌نخورده می‌ماند و اصلاح به شکلِ مایگریشنِ تازه می‌آید.
-- (همان درسی که در ۰۶۲ ثبت شد.)
--
-- ── ایمنی ──
--
-- `jsonb_set` فقط کلیدهای هدف را عوض می‌کند؛ بقیهٔ `metadata` سرِ
-- جایش می‌ماند. هر سه دستور idempotent‌اند: اجرای دوباره تغییری
-- نمی‌دهد، چون شرطِ `WHERE` روی مقدارِ فعلی است.
-- ═══════════════════════════════════════════════════════════════════

BEGIN;

-- ── ۱) نامِ آیکون به‌جای ایموجی ──
UPDATE shop_items
   SET metadata = jsonb_set(metadata, '{icon}', '"handshake"'::jsonb, true)
 WHERE slug = 'emote_respect'
   AND metadata->>'icon' IS DISTINCT FROM 'handshake';

UPDATE shop_items
   SET metadata = jsonb_set(metadata, '{icon}', '"bolt"'::jsonb, true)
 WHERE slug = 'emote_comeback'
   AND metadata->>'icon' IS DISTINCT FROM 'bolt';

UPDATE shop_items
   SET metadata = jsonb_set(metadata, '{icon}', '"party"'::jsonb, true)
 WHERE slug = 'emote_goal_club'
   AND metadata->>'icon' IS DISTINCT FROM 'party';

-- ── ۲) ایموجیِ چسبیده به متنِ پیام‌ها ──
--
-- کلِ آرایه بازنویسی می‌شود چون فقط دو عضوش عوض می‌شود و نوشتنِ
-- آرایهٔ کامل از دستکاریِ ایندکسی خواناتر و کم‌خطاتر است.
UPDATE shop_items
   SET metadata = jsonb_set(
         metadata,
         '{messages}',
         '["گوووول!","باشگاه من همیشه آماده‌ست!","خوش بردی؛ بازی بعدی با من!","فقط گرم کرده بودم"]'::jsonb,
         true)
 WHERE slug = 'emote_goal_club';

COMMIT;
