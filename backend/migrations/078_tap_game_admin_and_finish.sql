-- دورِ ۳۳ — مدیریت کامل بازی ضربه‌زن توسط ادمین + حالتِ «پایان بازی»
--
-- چرا این دو ستون:
--
-- coins_awarded: تا امروز سکهٔ لول‌آپ در دفترِ سکه (coinService) ثبت می‌شد ولی
-- خودِ جدولِ پیشرفت هیچ ردی از مجموعِ سکهٔ ضربه‌زن نداشت. خواستهٔ مالک:
-- «وقتی لول به ۵۰ رسید … تمامی امتیازات و سکه‌ها نمایش داده شود» و
-- «آمار لول ۵۰ شدن کاربرها در پنل». بدون این ستون، هر دو فقط با کوئریِ
-- سنگین روی دفترِ سکه ممکن بود و ردیفِ کاربرانی که سکه‌ای نگرفته‌اند
-- (لیگِ غیرفعال) کلاً غایب می‌شد.
--
-- finished_at: خواستهٔ مالک صریح است: «تا زمانی که ادمین بازی رو رست نداده
-- کاربر نمی‌تونه دیگه بازی کنه». level > levelCount هم همین را می‌گوید، ولی
-- سطحِ نهایی با تغییرِ تنظیمِ «تعداد لول» از پنل می‌تواند جابه‌جا شود؛
-- یک مهرِ زمانی مستقل یعنی «این کاربر بازی را در نسخهٔ فعلی تمام کرده»
-- و با ریستِ ادمین پاک می‌شود — نه با تغییرِ منحنی.
ALTER TABLE tap_game_progress
  ADD COLUMN IF NOT EXISTS coins_awarded BIGINT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS finished_at TIMESTAMPTZ;

-- ایندکسِ آماری برای پنل ادمین: «چه کسانی لولِ آخر را تمام کرده‌اند».
-- بدون ایندکس، هر باز شدنِ صفحهٔ آمار یک sequential scan کامل می‌زد؛
-- جدول به ازای هر بازیکن یک ردیف دارد و بزرگ می‌شود.
CREATE INDEX IF NOT EXISTS tap_game_progress_finished_idx
  ON tap_game_progress (finished_at)
  WHERE finished_at IS NOT NULL;
