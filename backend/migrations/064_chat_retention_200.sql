-- ============================================================================
--  نگه‌داریِ فقط ۲۰۰ پیامِ آخرِ چتِ عمومی
-- ============================================================================
--
-- ── خواستهٔ مالک ──
--
--   «چت کاربر هارو هم کل کاربرا بیشتر از ۲۰۰ چت مجموع چت نگه داری نشه
--    چون این سیستم پیام آماده داره، اصلا چت اونقدر مهم نیست»
--
-- ── چرا این تصمیم درست است ──
--
-- `chat_messages` تنها جدولِ سیستم بود که **هیچ سقفی نداشت**: نه TTL،
-- نه کرونِ پاک‌سازی، نه حدِ تعداد. جدول‌های مشابه همه محافظ دارند
-- (`tap_nonces` ساعتی پاک می‌شود، `card_duel_battles` دو هفته‌ای).
-- چت تنها موردِ جامانده بود و برای همیشه رشد می‌کرد.
--
-- ── چرا حذفِ فیزیکی و نه `is_deleted` ──
--
-- مالک صریحاً «نگه داری نشه» خواست. `is_deleted=true` پیام را از دید
-- کاربر پنهان می‌کند ولی ردیف و ایندکس‌هایش سرِ جا می‌مانند — یعنی
-- مشکلِ رشدِ جدول اصلاً حل نمی‌شود و فقط ظاهرش عوض می‌شود.
--
-- ── ایمنیِ حذف ──
--
-- کلیدهای خارجیِ وابسته از قبل درست تعریف شده‌اند و بررسی شدند:
--   • `chat_message_likes.message_id` → ON DELETE CASCADE  (لایک‌ها می‌روند)
--   • `chat_messages.reply_to_message_id` → ON DELETE SET NULL
--        (پیامِ جدیدی که به پیامِ حذف‌شده ریپلای کرده بود باقی می‌ماند و
--         فقط نقلِ‌قولش خالی می‌شود — نه خطا، نه حذفِ زنجیره‌ای)
-- پس یک DELETE ساده امن است و هیچ ردیفِ یتیمی جا نمی‌گذارد.
--
-- ── چرا ایندکس اضافه می‌شود ──
--
-- کوئریِ پاک‌سازی «۲۰۰ تای آخر را نگه دار» به مرتب‌سازی روی `sent_at`
-- نیاز دارد. `idx_chat_sent` از مایگریشنِ ۰۰۱ دقیقاً همین است، پس
-- ایندکسِ تازه‌ای لازم نیست و عمداً اضافه نمی‌شود.

-- پاک‌سازیِ اولیه: هر چه هست جز ۲۰۰ تای آخر.
--
-- ⚠️ `IN (SELECT ...)` با زیرکوئریِ `OFFSET` نوشته شده، نه
--    `NOT IN (SELECT ... LIMIT 200)`. دلیل: در حالتِ دوم اگر جدول کمتر
--    از ۲۰۰ ردیف داشته باشد کوئری بی‌ضرر است، ولی روی جدولِ بزرگ
--    Postgres باید کلِ ۲۰۰ ردیف را برای هر ردیفِ کاندید بررسی کند.
--    نسخهٔ `OFFSET 200` مستقیماً همان ردیف‌هایی را می‌دهد که باید بروند.
DELETE FROM chat_messages
 WHERE id IN (
   SELECT id FROM chat_messages
    ORDER BY sent_at DESC, id DESC
   OFFSET 200
 );
