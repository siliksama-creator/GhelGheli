-- سیستم لول‌بندیِ دائمیِ بازیکن.
--
-- ═══════════════════════════════════════════════════════════════════════════
-- چرا یک سیستمِ جدا و نه استفاده از XP گذر نبرد
-- ═══════════════════════════════════════════════════════════════════════════
--
-- درخواست مالک: «یک سیستم لول بندی هم در قسمت بازی ها اضافه کن که این
-- سیستم مجموع exp دریافتی از همه بازی های آنلاین با کاربر واقعی رو نشون
-- بده».
--
-- گذر نبرد از قبل XP دارد، ولی برای این کار مناسب نیست:
--
--   ۱. **فصلی است.** هر فصل صفر می‌شود. لولِ بازیکن باید دائمی باشد،
--      وگرنه «نشان‌دهندهٔ مجموعِ همهٔ بازی‌ها» نیست.
--   ۲. **سقفِ روزانه دارد** (۹۰ برای game_play). این عمدی است تا کسی
--      نتواند در یک روز کل گذر را تمام کند — ولی برای لول، سقف یعنی
--      بازیکنِ پرکار بعد از بازیِ ششم هیچ پیشرفتی نمی‌بیند.
--   ۳. **منابعِ غیربازی هم دارد** (چرخش، دعوت، ورود روزانه). مالک
--      صریحاً «از همه بازی های آنلاین» گفت.
--
-- پس یک ستونِ جدا: بدون فصل، بدون سقف، فقط بازیِ آنلاین با آدمِ واقعی.

-- ── ستونِ XP دائمی ────────────────────────────────────────────────────────
--
-- روی خودِ users و نه یک جدولِ جدا: این مقدار در **هر** صفحه‌ای که نام
-- کاربر را نشان می‌دهد لازم است (لیگ، چت، پروفایل عمومی، نوار حریف).
-- یک JOIN اضافه در آن مسیرهای داغ، هزینه‌ای است که با یک ستونِ ساده
-- قابل اجتناب است.
--
-- BIGINT چون سقفِ نظری ~۲ میلیون است ولی هیچ دلیلی برای ریسکِ سرریز
-- نداریم اگر روزی ضریب‌ها عوض شوند.
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS game_xp BIGINT NOT NULL DEFAULT 0;

-- ــ چرا ستونِ لول ذخیره **نمی‌شود** ───────────────────────────────────────
--
-- وسوسه‌انگیز است که `level` را هم ذخیره کنیم تا محاسبه نشود. ولی
-- آن‌وقت دو منبعِ حقیقت داریم که می‌توانند از هم جدا بیفتند: اگر روزی
-- منحنی تنظیم شود، همهٔ ردیف‌ها باید دوباره محاسبه شوند و تا آن لحظه
-- کاربران لولِ اشتباه می‌بینند.
--
-- لول یک **تابعِ محضِ** XP است و محاسبه‌اش یک حلقهٔ حداکثر ۹۹تایی روی
-- عددهای صحیح است — در حد نویز. تنها منبعِ حقیقت `game_xp` می‌ماند.

-- ــ ایندکس برای جدولِ رتبه‌بندی ───────────────────────────────────────────
--
-- «بالاترین لول‌ها» همان «بالاترین XP»هاست چون لول یکنواختِ صعودی است.
-- بدون ایندکس، هر بار خواندنِ آن صفحه یک sequential scan روی کل جدول
-- کاربران است.
CREATE INDEX IF NOT EXISTS idx_users_game_xp
  ON users (game_xp DESC)
  WHERE game_xp > 0;

-- ── دفترِ رخدادهای XP ─────────────────────────────────────────────────────
--
-- چرا یک جدولِ جدا و نه فقط جمع زدن روی ستون:
--
--   • **پشتیبانی.** وقتی کاربری می‌گوید «چرا لولم بالا نرفت»، بدون
--     دفتر هیچ راهی برای جواب دادن نیست.
--   • **تشخیصِ سوءاستفاده.** اگر روزی الگویی مثل «۲۰۰ بازی در یک
--     ساعت با همان حریف» ظاهر شود، فقط از روی همین جدول قابل دیدن
--     است.
--   • **بازسازی.** اگر ضریب‌ها عوض شوند، می‌شود XP همه را از روی
--     تاریخچه دوباره ساخت.
--
-- عمداً سبک است: بدون متنِ آزاد، فقط شناسه و عدد.
-- ═══════════════════════════════════════════════════════════════════════════
-- نکته: کلیدِ کاربر در این پروژه **UUID** است، نه INTEGER
-- ═══════════════════════════════════════════════════════════════════════════
--
-- نسخهٔ اولِ این مایگریشن `INTEGER` نوشته بود و روی سرورِ واقعی شکست
-- خورد. حدس زدنِ نوعِ کلید یکی از رایج‌ترین راه‌های شکستنِ یک مایگریشن
-- است؛ همیشه باید از `\d users` خوانده شود.
CREATE TABLE IF NOT EXISTS game_xp_log (
  id          BIGSERIAL PRIMARY KEY,
  user_id     UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  game_id     TEXT    NOT NULL,
  -- 'play' یا 'win'
  reason      TEXT    NOT NULL,
  amount      INTEGER NOT NULL,
  -- شناسهٔ حریف، برای تشخیصِ تبانی (دو حساب که فقط با هم بازی کنند)
  opponent_id UUID REFERENCES users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- برای پرس‌وجوی «XP اخیرِ این کاربر» در صفحهٔ پشتیبانی.
CREATE INDEX IF NOT EXISTS idx_game_xp_log_user
  ON game_xp_log (user_id, created_at DESC);

-- ═══════════════════════════════════════════════════════════════════════════
-- پرکردنِ اولیه از تاریخچهٔ موجود
-- ═══════════════════════════════════════════════════════════════════════════
--
-- کاربرانی که ماه‌هاست بازی می‌کنند نباید از لول صفر شروع کنند — آن
-- یک پیامِ بد است: «هرچه تا امروز کردی حساب نیست».
--
-- منبع: جدولِ نتایجِ بازی که از قبل وجود دارد. فقط بازی‌های **آنلاین**
-- (نه مقابل ربات) شمرده می‌شوند، هماهنگ با قانونِ اصلی.
--
-- در یک بلوکِ DO با بررسیِ وجودِ جدول، چون نامِ جدولِ نتایج ممکن است در
-- نصب‌های قدیمی‌تر نباشد و مایگریشن نباید به‌خاطر آن شکست بخورد.
DO $$
DECLARE
  has_results BOOLEAN;
BEGIN
  SELECT EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name = 'game_results'
  ) INTO has_results;

  IF has_results THEN
    -- ۲۰ برای هر بازی + ۱۵ اضافه برای برد، همان ضریب‌های سرویس.
    --
    -- نکته: ستونِ نتیجه `outcome` است با مقادیر win/loss/draw — نه یک
    -- بولینِ `won`. و «آنلاین بودن» از روی `opponent_user_id IS NOT
    -- NULL` تشخیص داده می‌شود، چون بازیِ مقابل ربات حریفِ ثبت‌شده
    -- ندارد. هر دو از روی schema واقعی خوانده شدند، نه حدس.
    WITH tally AS (
      SELECT user_id,
             COUNT(*) * 20
               + COUNT(*) FILTER (WHERE outcome = 'win') * 15 AS xp
      FROM game_results
      WHERE opponent_user_id IS NOT NULL
      GROUP BY user_id
    )
    UPDATE users u
    SET game_xp = t.xp
    FROM tally t
    WHERE u.id = t.user_id AND u.game_xp = 0;
    RAISE NOTICE 'game_xp از تاریخچهٔ بازی‌ها پر شد';
  ELSE
    RAISE NOTICE 'جدول game_results نیست؛ همه از صفر شروع می‌کنند';
  END IF;
END $$;
