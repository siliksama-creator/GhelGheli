-- دورِ بیست‌ودوم: هدیهٔ امتیازِ عضویت + خریدِ شاپ با کیف پول
-- ═══════════════════════════════════════════════════════════════════
--
-- ── ۱) `signup_gift` ──
--
-- منبعِ تازه در `point_transactions`. مدیر مبلغی تعیین می‌کند و هر
-- کاربرِ جدید همان را می‌گیرد. بدونِ این ردیف، اولین ثبت‌نامِ پس از
-- روشن‌کردنِ قابلیت با خطای CHECK می‌شکست — یعنی قابلیتی که برای
-- خوش‌آمدگویی ساخته شده، جلوی ورودِ کاربر را می‌گرفت.
--
-- ── ۲) خریدِ شاپ با کیف پول ──
--
-- محدودیتِ `wallet_transactions_source_check` بررسی شد و مقدارِ `shop`
-- از قبل در آن مجاز است، پس **دست‌کاری نمی‌شود**. بازنویسیِ متنیِ یک
-- CHECK موجود کارِ پرخطری است و وقتی لازم نیست، نباید انجام شود.
--
-- خریدِ کیف‌پولی با `source='shop'` و `direction='debit'` ثبت می‌شود و
-- برگشتِ احتمالی با همان `source` ولی `direction='credit'`.
--
-- ── قاعدهٔ کمیسیون (خواستهٔ صریحِ مالک) ──
--
-- خریدی که از کیف پول پرداخت می‌شود **نباید** به معرف کمیسیون بدهد.
-- دلیل: پولِ کیف پول خودش از کمیسیون و جایزهٔ لیگ آمده؛ اگر دوباره
-- کمیسیون بدهد، حلقه‌ای می‌سازد که در آن پول از هیچ زاده می‌شود.
-- اجرای این قاعده در `shopService.deliverItem` است (پارامترِ
-- `payCommission`)، ولی همین‌جا ثبت می‌شود تا هر کسی که این مایگریشن
-- را می‌خواند بداند چرا دو مسیرِ پرداخت رفتارِ متفاوت دارند.

ALTER TABLE point_transactions
  DROP CONSTRAINT IF EXISTS point_transactions_source_check;

ALTER TABLE point_transactions
  ADD CONSTRAINT point_transactions_source_check
  CHECK (source IN (
    'photo_card', 'card_code', 'referral', 'game', 'pass_reward',
    'wheel', 'login_streak', 'mission', 'reward_claim',
    'admin_adjust', 'admin_deduct',
    'signup_gift',
    'other'
  ));

-- مقدارِ پیش‌فرضِ تنظیم: خاموش. یک نصبِ تازه نباید بی‌آنکه کسی خواسته
-- باشد امتیاز پخش کند؛ مدیر باید آگاهانه روشنش کند.
INSERT INTO app_settings(key, value, updated_at)
VALUES (
  'signup_gift',
  '{"enabled": false, "points": 0, "message": "به قلقلی خوش آمدی! این امتیاز هدیهٔ عضویت توست."}'::jsonb,
  NOW()
)
ON CONFLICT (key) DO NOTHING;

-- ── ۳) سهمِ کیف پول در سفارشِ ترکیبی ──
--
-- وقتی موجودیِ کیف پول کمتر از قیمت است، همان مقدار همان لحظه کسر
-- می‌شود و باقی‌مانده از بازار گرفته می‌شود. این ستون یادش می‌ماند چقدر
-- از کیف پول آمده، برای دو کار:
--
--   • هنگامِ تحویل، کمیسیونِ معرف فقط روی سهمِ بازار حساب شود.
--   • اگر سفارش نیمه‌کاره رها شد، دقیقاً همان مبلغ به کیف پول برگردد.
ALTER TABLE payment_orders
  ADD COLUMN IF NOT EXISTS wallet_amount INTEGER NOT NULL DEFAULT 0;

COMMENT ON COLUMN payment_orders.wallet_amount IS
  'سهمِ پرداخت‌شده از کیف پول (تومان). صفر یعنی خریدِ کاملاً بازاری.';
