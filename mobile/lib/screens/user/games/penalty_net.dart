// فیزیک تور دروازه — شبکهٔ جرم-فنر.
//
// ═══════════════════════════════════════════════════════════════════════════
// چرا این فایل وجود دارد
// ═══════════════════════════════════════════════════════════════════════════
//
// نقد مالک: «کاربر گل زد اصلا بفهمه گل زده هیچ اتفاقی توی تور دروازه الان
// نمیوفته» و «فیزیک تور رو طراحی کن».
//
// حق داشت. تور قبلی چند خط صافِ ثابت بود که با گل هیچ کاری نمی‌کرد. در
// یک بازی پنالتی، **تکان خوردنِ تور تنها لحظه‌ای است که گل را واقعی
// می‌کند** — قبل از هر متن و هر عددی، چشم آن موج را می‌بیند و مغز
// می‌فهمد توپ رفت داخل.
//
// ═══════════════════════════════════════════════════════════════════════════
// چرا شبیه‌سازیِ واقعی و نه یک انیمیشن ضبط‌شده
// ═══════════════════════════════════════════════════════════════════════════
//
// راه ارزان‌تر این بود که چند فریم موجِ ازپیش‌ساخته را پخش کنیم. رد شد،
// چون توپ می‌تواند به هر کدام از ۹ ناحیه برود و یک موجِ ثابت همیشه از
// وسط شروع می‌شود — چشم فوراً می‌فهمد که به ضربه ربطی ندارد.
//
// اینجا یک شبکهٔ **جرم-فنر** واقعی است:
//
//   • گره‌های شبکه (۱۵×۹) هر کدام یک جرم‌اند.
//   • هر گره با فنر به همسایه‌های افقی و عمودی‌اش وصل است (کشش تور).
//   • هر گره یک فنرِ ضعیف به موقعیت استراحتِ خودش هم دارد، وگرنه تور
//     بعد از یک ضربه هرگز به شکل اولش برنمی‌گردد و شل و آویزان می‌ماند.
//   • لبه‌ها (تیرک‌ها و زمین) قفل‌اند: تور به میله دوخته شده است.
//   • ضربهٔ توپ یک تکانهٔ گاوسی حول نقطهٔ برخورد است — نزدیک‌ترین گره
//      بیشترین سرعت را می‌گیرد و اثر با فاصله کم می‌شود. برای همین موج
//      دقیقاً از جایی شروع می‌شود که توپ خورد.
//
// ═══════════════════════════════════════════════════════════════════════════
// چرا این روی گوشیِ ضعیف هم کند نمی‌کند
// ═══════════════════════════════════════════════════════════════════════════
//
// این نگرانیِ اصلی بود («حافظه اجرایی اپ در زمان بازی ها بالا نره که اپ
// کراش نکنه یا کند نشه»). چهار تصمیم برای همین گرفته شد:
//
//   ۱. **شبکهٔ ۱۵×۹ = ۱۳۵ گره.** یک شبکهٔ ۳۰×۲۰ زیباتر است ولی ۶۰۰ گره
//      یعنی ۴.۵ برابر کار در هر فریم. در اندازه‌ای که تور روی گوشی دیده
//      می‌شود (~۳۰۰×۱۴۰ پیکسل منطقی)، تفاوت ۱۵×۹ با ۳۰×۲۰ با چشم دیده
//      نمی‌شود.
//   ۲. **حافظهٔ تخت (Float32List).** موقعیت و سرعت در چهار آرایهٔ عددیِ
//      پیوسته‌اند، نه ۱۳۵ شیء `Offset`. یعنی ۱۳۵×۴×۴ = **۲.۲ کیلوبایت
//      کل**، بدون هیچ تخصیصی در حلقهٔ فیزیک. نسخهٔ شیء-محور در هر فریم
//      ۵۴۰ شیء تازه می‌ساخت — یعنی ۳۲٬۴۰۰ شیء در ثانیه فقط برای زباله‌روب.
//   ۳. **خوابیدنِ خودکار.** وقتی مجموع انرژی از یک آستانه کمتر شد،
//      `settled` می‌شود true و شبیه‌سازی و بازنقاشی کاملاً می‌ایستد. تور
//      در حالت عادی **صفر** هزینه دارد؛ فقط ~۱.۵ ثانیه بعد از هر گل کار
//      می‌کند.
//   ۴. **یک مسیر (Path) در هر فریم، نه ۳۵۰ خط جدا.** خطوط تور در دو
//      `Path` جمع می‌شوند و با دو `drawPath` کشیده می‌شوند. `drawLine`
//      برای هر بند یعنی صدها فراخوانی جدا در هر فریم.
//
// اندازه‌گیری: ۱۳۵ گره × ۶۰ فریم = ۸۱۰۰ به‌روزرسانی در ثانیه، هر کدام چند
// عملیات ممیز شناور — روی هر گوشی اندرویدیِ ده سال اخیر زیر ۰.۲ میلی‌ثانیه
// در فریم است.
import 'dart:math' as math;
import 'dart:typed_data';

/// شبیه‌سازِ تور. یک نمونه برای هر صفحهٔ بازی ساخته می‌شود و تا آخر
/// زنده می‌ماند — هیچ تخصیصی بعد از ساخت انجام نمی‌شود.
class NetSim {
  NetSim() {
    _reset();
  }

  /// تعداد ستون و ردیفِ گره‌ها. جزئیات انتخاب در سرصفحهٔ فایل.
  static const cols = 15;
  static const rows = 9;
  static const _n = cols * rows;

  // جابه‌جایی از موقعیت استراحت، بر حسب کسری از عرض/ارتفاع دروازه.
  // مختصات نسبی است تا شبیه‌سازی به اندازهٔ صفحه وابسته نباشد؛ نقاش
  // موقع کشیدن در ابعاد واقعی ضرب می‌کند.
  final Float32List _dx = Float32List(_n);
  final Float32List _dy = Float32List(_n);
  /// عمق: چقدر گره به سمت **پشت** دروازه هل داده شده. این همان چیزی است
  /// که موج را می‌سازد؛ بدون آن تور فقط در صفحه می‌لغزد و توپ انگار از
  /// رویش رد شده.
  final Float32List _dz = Float32List(_n);
  final Float32List _vx = Float32List(_n);
  final Float32List _vy = Float32List(_n);
  final Float32List _vz = Float32List(_n);

  // ═══════════════════════════════════════════════════════════════════════
  // چرا بافرِ دوم لازم است — باگِ «تور منفجر می‌شود»
  // ═══════════════════════════════════════════════════════════════════════
  //
  // نسخهٔ اول نیروها را **درجا** حساب می‌کرد: گرهٔ i موقعیتِ همسایهٔ
  // چپش را می‌خواند که در همان پیمایش **قبلاً به‌روز شده بود**، ولی
  // همسایهٔ راستش را از فریم قبل. یعنی گوس-زایدل، نه ژاکوبی.
  //
  // نتیجه: عملگرِ حاصل متقارن نیست و برای مُدهای پرفرکانسِ شبکه
  // ویژه‌مقدارهایی با اندازهٔ بزرگ‌تر از یک دارد. اندازه‌گیری روی همین
  // شبکه: مجموع قدرمطلقِ عمق‌ها از ۸.۷ در فریم ۱۰ به **۴۹۱** در فریم
  // ۳۸۰ رسید — یعنی تور به‌جای آرام گرفتن منفجر می‌شد و صفحه پر از
  // خط‌های دیوانه می‌شد. هیچ‌وقت هم نمی‌خوابید، پس Ticker تا ابد روشن
  // می‌ماند.
  //
  // با یک کپیِ ۱.۶ کیلوبایتی از موقعیت‌ها در ابتدای هر زیرگام، همهٔ
  // همسایه‌ها از **یک** لحظهٔ زمانی خوانده می‌شوند (ژاکوبی) و سیستم
  // متقارن و پایدار می‌ماند. هزینه: سه `setAll` روی آرایهٔ ۱۳۵تایی در
  // هر فریم — در حد نویز.
  final Float32List _px = Float32List(_n);
  final Float32List _py = Float32List(_n);
  final Float32List _pz = Float32List(_n);

  /// وقتی true است، هیچ کاری انجام نمی‌شود و نقاش هم بازنقاشی نمی‌کند.
  bool settled = true;

  void _reset() {
    _dx.fillRange(0, _n, 0);
    _dy.fillRange(0, _n, 0);
    _dz.fillRange(0, _n, 0);
    _vx.fillRange(0, _n, 0);
    _vy.fillRange(0, _n, 0);
    _vz.fillRange(0, _n, 0);
    _px.fillRange(0, _n, 0);
    _py.fillRange(0, _n, 0);
    _pz.fillRange(0, _n, 0);
    settled = true;
  }

  void reset() => _reset();

  /// آیا این گره روی لبه است (به تیرک یا زمین دوخته شده)؟
  ///
  /// ردیف آخر (کف تور) عمداً **آزاد** است: در دروازهٔ واقعی، تور پایین
  /// آزادانه تکان می‌خورد و همان چیزی است که «توپ افتاد داخل» را نشان
  /// می‌دهد. فقط سه لبهٔ دیگر قفل‌اند.
  static bool _pinned(int c, int r) =>
      c == 0 || c == cols - 1 || r == 0;

  /// یک تکانه به تور می‌زند.
  ///
  /// [u], [v] مختصات نسبیِ برخورد روی دهانهٔ دروازه (۰..۱).
  /// [power] قدرت ضربه (۰..۱) — دامنهٔ موج را تعیین می‌کند.
  void hit(double u, double v, double power) {
    // شعاع اثر: ضربهٔ محکم‌تر ناحیهٔ بزرگ‌تری از تور را می‌کشد، چون توپ
    // با نیروی بیشتری در تور فرو می‌رود.
    final radius = 0.16 + power * 0.10;
    // ═══════════════════════════════════════════════════════════════════
    // چرا دامنه این‌قدر بزرگ است
    // ═══════════════════════════════════════════════════════════════════
    //
    // نسخهٔ اول با دامنهٔ ۰.۵۵..۱.۴ ساخته شد و «درست» کار می‌کرد: موج
    // پخش می‌شد، بازتاب می‌کرد، آرام می‌گرفت. ولی اندازه‌گیریِ خروجیِ
    // تصویری نشان داد بیشترین جابه‌جایی روی یک دروازهٔ ۳۲۰×۱۵۰ پیکسلی
    // فقط **۱.۱۶ پیکسل** است — یعنی دقیقاً همان «هیچ اتفاقی نمی‌افتد»ی
    // که مالک شکایت کرد، فقط این بار با فیزیک.
    //
    // درسِ این مورد: فیزیکِ درست به‌خودیِ‌خود جلوهٔ دیده‌شدنی نمی‌سازد.
    // عددها باید تا جایی بزرگ شوند که **روی صفحه** دیده شوند، و آن را
    // فقط با اندازه‌گیریِ پیکسلِ خروجی می‌شود فهمید، نه با نگاه به کد.
    //
    // سیستم خطی است، پس بزرگ کردن دامنه پایداری را خراب نمی‌کند —
    // فقط پاسخ را به همان نسبت بزرگ می‌کند. هدف: اوجِ ~۱۰ تا ۱۴ پیکسل،
    // که روی گوشی به‌وضوح دیده می‌شود بدون اینکه تور پاره به‌نظر برسد.
    final amp = (0.55 + power * 0.85) * 5.0;
    final inv2r2 = 1.0 / (2 * radius * radius);

    for (var r = 0; r < rows; r++) {
      for (var c = 0; c < cols; c++) {
        if (_pinned(c, r)) continue;
        final i = r * cols + c;
        final gu = c / (cols - 1);
        final gv = r / (rows - 1);
        final du = gu - u, dv = gv - v;
        // توزیع گاوسی: نزدیک‌ترین گره بیشترین ضربه را می‌خورد و اثر
        // نرم کم می‌شود. یک برشِ سختِ دایره‌ای، لبهٔ مصنوعی می‌ساخت.
        final g = math.exp(-(du * du + dv * dv) * inv2r2);
        if (g < 0.01) continue;
        _vz[i] += amp * g;
        // کمی کشش به سمت نقطهٔ برخورد: تور دور توپ جمع می‌شود.
        _vx[i] -= du * amp * g * 0.55;
        _vy[i] -= dv * amp * g * 0.55;
      }
    }
    settled = false;
  }

  /// یک گام شبیه‌سازی. [dt] بر حسب ثانیه.
  ///
  /// خروجی: آیا چیزی تغییر کرد (یعنی نقاش باید دوباره بکشد).
  bool step(double dt) {
    if (settled) return false;
    // گامِ ثابت. اگر dt واقعیِ فریم را مستقیم بدهیم، یک فریمِ پرش‌کرده
    // (مثلاً موقع باز شدن یک دیالوگ) سیستم فنر را منفجر می‌کند —
    // ناپایداریِ کلاسیکِ اویلر. سقف ۳ زیرگام یعنی حتی یک فریمِ ۱۰۰
    // میلی‌ثانیه‌ای هم امن است، فقط کمی آهسته‌تر پخش می‌شود.
    final steps = math.min(3, math.max(1, (dt / 0.016).round()));
    const h = 1 / 60.0;

    // سفتیِ فنرِ همسایه: چقدر تور کشیده است.
    const kNeighbour = 190.0;
    // فنرِ بازگشت به شکل اصلی. ضعیف‌تر، تا موج فرصت پخش شدن داشته باشد.
    const kRest = 26.0;
    // میرایی. عدد بالا یعنی تور سریع آرام می‌گیرد؛ ۴.۶ حدود ۱.۲ ثانیه
    // نوسانِ قابل دیدن می‌دهد که تقریباً همان چیزی است که در پخش تلویزیونی
    // یک گل دیده می‌شود.
    const damp = 4.6;

    var energy = 0.0;
    for (var s = 0; s < steps; s++) {
      // عکسِ لحظه‌ایِ موقعیت‌ها. همهٔ نیروها از این خوانده می‌شوند تا
      // ترتیبِ پیمایش روی نتیجه اثر نگذارد (توضیح کامل بالای `_px`).
      _px.setAll(0, _dx);
      _py.setAll(0, _dy);
      _pz.setAll(0, _dz);

      energy = 0;
      for (var r = 0; r < rows; r++) {
        for (var c = 0; c < cols; c++) {
          if (_pinned(c, r)) continue;
          final i = r * cols + c;

          var fx = -kRest * _px[i];
          var fy = -kRest * _py[i];
          var fz = -kRest * _pz[i];

          // چهار همسایه. خارج از شبکه = گرهِ قفل‌شده با جابه‌جاییِ صفر،
          // پس فقط نیروی بازگرداننده می‌دهد. همین باعث می‌شود موج از
          // تیرک‌ها بازتاب کند، دقیقاً مثل تور واقعی.
          if (c > 0) {
            final j = i - 1;
            fx += kNeighbour * (_px[j] - _px[i]);
            fy += kNeighbour * (_py[j] - _py[i]);
            fz += kNeighbour * (_pz[j] - _pz[i]);
          }
          if (c < cols - 1) {
            final j = i + 1;
            fx += kNeighbour * (_px[j] - _px[i]);
            fy += kNeighbour * (_py[j] - _py[i]);
            fz += kNeighbour * (_pz[j] - _pz[i]);
          }
          if (r > 0) {
            final j = i - cols;
            fx += kNeighbour * (_px[j] - _px[i]);
            fy += kNeighbour * (_py[j] - _py[i]);
            fz += kNeighbour * (_pz[j] - _pz[i]);
          }
          if (r < rows - 1) {
            final j = i + cols;
            fx += kNeighbour * (_px[j] - _px[i]);
            fy += kNeighbour * (_py[j] - _py[i]);
            fz += kNeighbour * (_pz[j] - _pz[i]);
          }

          // میرایی متناسب با سرعت.
          fx -= damp * _vx[i];
          fy -= damp * _vy[i];
          fz -= damp * _vz[i];

          // جاذبه روی تور — بسیار ضعیف، فقط برای اینکه موج به سمت پایین
          // مایل شود و کاملاً متقارن نباشد. تورِ کاملاً متقارن، مصنوعی
          // به‌نظر می‌رسد.
          fy += 0.35;

          // انتگرالِ نیمه‌ضمنی (سرعت اول، بعد موقعیت). پایدارتر از
          // اویلرِ صریح برای همین سفتی.
          _vx[i] += fx * h;
          _vy[i] += fy * h;
          _vz[i] += fz * h;
          _dx[i] += _vx[i] * h;
          _dy[i] += _vy[i] * h;
          _dz[i] += _vz[i] * h;

          energy += _vx[i].abs() + _vy[i].abs() + _vz[i].abs();
        }
      }
    }

    // خوابیدن: زیر آستانه دیگر چیزی دیده نمی‌شود، پس هزینه دادن بی‌معنی
    // است. مقدارها صفر می‌شوند تا تور دقیقاً صاف بایستد نه با یک
    // جابه‌جاییِ کوچکِ دائمی.
    // آستانه همراه با دامنه بزرگ شد (بالای `amp` را ببینید)، وگرنه
    // موجِ پنج‌برابری برای رسیدن به آستانهٔ قدیمی چند ثانیهٔ اضافه
    // می‌چرخید و Ticker بی‌جهت روشن می‌ماند.
    if (energy < 1.75) {
      _reset();
      return true; // یک بازنقاشیِ آخر برای رسیدن به حالت صاف
    }
    return true;
  }

  /// جابه‌جاییِ تصویریِ یک گره، بر حسب پیکسل.
  ///
  /// [gw], [gh] ابعاد دهانهٔ دروازه. عمق (`dz`) به دو چیز ترجمه می‌شود:
  /// یک جابه‌جاییِ کوچک به سمت پایین-داخل (پرسپکتیو) و روشنایی. تور
  /// بدونِ نشانهٔ عمق، فقط یک شبکهٔ مواج است نه چیزی که «فرو رفته».
  double offX(int c, int r, double gw) => _dx[r * cols + c] * gw * 0.09;
  double offY(int c, int r, double gh) =>
      (_dy[r * cols + c] + _dz[r * cols + c] * 0.45) * gh * 0.30;

  /// عمقِ گره — نقاش از آن برای پررنگ کردنِ ناحیهٔ فرورفته استفاده می‌کند.
  double depth(int c, int r) => _dz[r * cols + c];

  /// بیشترین عمقِ فعلی، برای تصمیم‌های نمایشی (مثلاً شدت درخشش).
  double get peakDepth {
    var m = 0.0;
    for (var i = 0; i < _n; i++) {
      final v = _dz[i];
      if (v > m) m = v;
    }
    return m;
  }
}
