// واکنش به فشارِ حافظهٔ سیستم.
//
// ═══════════════════════════════════════════════════════════════════════════
// چرا این لازم است — و چرا نبودش دقیقاً همان چیزی است که اپ را می‌کشد
// ═══════════════════════════════════════════════════════════════════════════
//
// نگرانیِ مالک: «حافظه اجرایی اپ در زمان بازی ها و استفاده ازش بالا نره
// که اپ کراش نکنه یا کند نشه».
//
// وقتی رمِ گوشی کم می‌آید، اندروید **پیش از** کشتنِ اپ یک هشدار
// می‌فرستد (`onTrimMemory`). فلاتر آن را به `didHaveMemoryPressure`
// ترجمه می‌کند. این آخرین فرصتِ اپ است که داوطلبانه حافظه پس بدهد.
//
// اپ تا امروز این هشدار را کاملاً نادیده می‌گرفت. یعنی:
//
//   • کشِ تصویرِ ۴۰ مگابایتی دست‌نخورده می‌ماند،
//   • سیستم چیزی برای بازپس‌گیری پیدا نمی‌کند،
//   • و ارزیابِ کم‌حافظگیِ اندروید اپ را می‌کشد.
//
// کاربر این را به‌صورت «اپ خودش بسته شد» یا «برگشتم دیدم از اول باز
// شد» می‌بیند — و روی گوشیِ ۲ گیگابایتی که مخاطبِ اصلیِ این اپ است،
// این اتفاق واقعاً می‌افتد.
//
// ═══════════════════════════════════════════════════════════════════════════
// چرا پاک کردنِ کش «از دست دادنِ امکانات» نیست
// ═══════════════════════════════════════════════════════════════════════════
//
// کشِ تصویر فقط یک **حافظهٔ موقت** است: هر تصویری که پاک شود، دفعهٔ
// بعد از فایلِ داخلِ APK دوباره decode می‌شود. تنها هزینه‌اش چند
// میلی‌ثانیه تأخیر در اولین نمایش است.
//
// معامله روشن است: چند میلی‌ثانیه تأخیر، در برابر کشته شدنِ اپ.
//
// ═══════════════════════════════════════════════════════════════════════════
// دو سطحِ واکنش، و چرا فقط یکی کافی نیست
// ═══════════════════════════════════════════════════════════════════════════
//
//   • **فشارِ حافظه** (`didHaveMemoryPressure`): تهاجمی پاک می‌کنیم،
//     چون گزینهٔ دیگر مرگ است.
//   • **رفتن به پس‌زمینه** (`paused`): فقط تصاویرِ زنده را رها می‌کنیم
//     و خودِ کش را نگه می‌داریم. یک اپِ پس‌زمینه اولین قربانیِ
//     بازپس‌گیریِ حافظه است، پس سبک‌تر بودن یعنی احتمالِ بیشترِ زنده
//     ماندن؛ ولی چون کاربر معمولاً برمی‌گردد، پاک کردنِ کامل باعث
//     می‌شد بازگشت کند و پرش‌دار به‌نظر برسد.
//
// این تفکیک عمدی است: یک واکنشِ یکسان برای هر دو حالت یا در فشارِ
// واقعی کم می‌آورد، یا هر بار جابه‌جایی بین اپ‌ها را کند می‌کند.
import 'package:flutter/widgets.dart';

/// به رخدادهای حافظه و چرخهٔ عمر گوش می‌دهد و کشِ تصویر را مدیریت می‌کند.
///
/// چرا `WidgetsBindingObserver` را با `with` نمی‌گیریم و یک کلاسِ جدا
/// می‌سازیم: آن اینترفیس بین نسخه‌های فلاتر عضو تازه می‌گیرد و
/// پیاده‌سازیِ دستی‌اش در هر ارتقا بیلد را می‌شکند. همان دلیلی که
/// `LifecyclePoller` هم یک پلِ داخلی دارد.
class MemoryGuard with WidgetsBindingObserver {
  MemoryGuard._();

  static final MemoryGuard instance = MemoryGuard._();

  bool _installed = false;

  /// شمارندهٔ تشخیصی — در تست استفاده می‌شود تا ثابت شود واکنش رخ داده.
  @visibleForTesting
  int pressureEvents = 0;

  /// شمارندهٔ رفتن به پس‌زمینه.
  @visibleForTesting
  int backgroundEvents = 0;

  void install() {
    if (_installed) return;
    _installed = true;
    WidgetsBinding.instance.addObserver(this);
  }

  /// فقط برای تست: ناظر را برمی‌دارد تا نشتی بین تست‌ها نماند.
  @visibleForTesting
  void uninstall() {
    if (!_installed) return;
    _installed = false;
    WidgetsBinding.instance.removeObserver(this);
    pressureEvents = 0;
    backgroundEvents = 0;
  }

  @override
  void didHaveMemoryPressure() {
    pressureEvents++;
    // `clear` ورودی‌های کش‌شده را می‌برد؛ `clearLiveImages` آن‌هایی را
    // که هنوز ارجاعِ زنده دارند رها می‌کند.
    //
    // هر دو لازم‌اند: بدون دومی، تصویری که همین حالا روی صفحه است در
    // حافظه می‌ماند و در یک صفحهٔ پر از تصویر (فروشگاه، جوایز) بخش
    // بزرگی از کش دست‌نخورده باقی می‌ماند.
    PaintingBinding.instance.imageCache
      ..clear()
      ..clearLiveImages();
    debugPrint('MemoryGuard: فشار حافظه — کش تصویر پاک شد');
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    if (state == AppLifecycleState.paused ||
        state == AppLifecycleState.detached) {
      backgroundEvents++;
      // فقط ارجاع‌های زنده رها می‌شوند، نه خودِ کش — توضیح در سرصفحه.
      PaintingBinding.instance.imageCache.clearLiveImages();
    }
  }
}
