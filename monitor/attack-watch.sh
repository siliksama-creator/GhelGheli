#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
#  نگهبانِ حمله — «اگر موجی به سرور آمد، در تلگرام خبر بده»
# ═══════════════════════════════════════════════════════════════════════════
#
# خواستهٔ مالک (۲۶ شهریور):
#
#   «اگر هم حمله‌ای به سرور شد در تلگرام بهم گزارش داده بشه که من به سرعت
#    برم کلادفلر رو از پنل ادمین فعال کنم.»
#
# ── چرا این اسکریپت جدا از نگهبانِ سلامت است ──────────────────────────────
#
# نگهبانِ سلامت (health.sh) هر ۳۰ ثانیه یک نگاه می‌اندازد که «سرویس‌ها
# روشن‌اند» و در لاگ می‌نویسد همه‌چیز آرام است. ولی یک حملهٔ رباتی می‌تواند
# دقیقاً همان لحظه همه چیزش «سالم» باشد — سرویس روشن است، فقط هزار ربات به
# آن می‌کوبند. تشخیصش از لاگِ درخواست‌ها می‌آید، نه از سلامتِ سرویس.
#
# ── چه چیزی را «حمله» می‌شماریم ───────────────────────────────────────────
#
# چهار نشانه، هر کدام با آستانه و پیامِ خودش (هر ۶۰ ثانیه یک‌بار سنجیده
# می‌شود؛ آستانه‌ها عمداً جا برای ترافیکِ واقعیِ پرمصرف باز می‌کنند):
#
#   ۱. سرعتِ کلِ درخواست‌ها  ≥ ۶۰ در ثانیه   → یعنی ۳۶۰۰ درخواست در دقیقه؛
#      سرورِ ما در روزِ عادی به‌زور به ۵ می‌رسد.
#   ۲. پاسخ‌های ۴۲۹          ≥ ۸۰ در دقیقه    → یعنی سقفِ ضدِرباتِ ما دارد
#      کار می‌کند و کسی پشتش ایستاده؛ خودِ این عدد از هر چیز دیگری گویاتر است.
#   ۳. یک آی‌پیِ تنها        ≥ ۲۴۰ در دقیقه   → موجِ متمرکز از یک منبع.
#   ۴. خطای سرور (۵xx)       ≥ ۵۰ در دقیقه    → فشار آن‌قدر بوده که سرور
#      دارد خطا می‌دهد؛ این از همه فوری‌تر است.
#
# ── چرا «۵ دقیقه سکوت» بین دو هشدارِ هم‌نوع ───────────────────────────────
#
# حمله دقیقه‌ها طول می‌کشد. بدونِ سکوت، هر دقیقه یک پیام می‌آمد و تلگرام
# به یک دریای پیام تبدیل می‌شد — دقیقاً همان چیزی که باعث می‌شود آدم هشدارها
# را جدی نگیرد. پس هر نشانه بعد از هشدار، ۵ دقیقه ساکت می‌ماند؛ اگر موج
# ادامه داشت، پیامِ بعدی هم می‌آید (یعنی «هنوز ادامه دارد»).
#
# اجرا: توسط systemd timer هر ۶۰ ثانیه (ghelgheli-attackwatch.timer)
# دستی:  bash monitor/attack-watch.sh [--dry-run]
#          --dry-run = فقط گزارش در ترمینال، هیچ پیامی به تلگرام نرود

set -Eeuo pipefail

# کمکیِ مشترکِ تلگرام (خواندنِ تنظیمات با تحملِ کوتیشن — باگِ ۲۶ شهریور)
# shellcheck source=lib/telegram.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/telegram.sh"

LOG_FILE="${LOG_FILE:-/var/log/nginx/access.log}"
STATE_FILE="${STATE_FILE:-/run/ghelgheli-attack-watch.state}"
STATE_LOG="${STATE_LOG:-/var/log/ghelgheli-attack-watch.log}"
TG_CONF="${TG_CONF:-/root/ghelgheli-backups/.telegram.conf}"
ADMIN_URL="${ADMIN_URL:-https://admin.ghelghelishop.ir}"
WEB_URL="${WEB_URL:-https://ghelghelishop.ir}"
DRY_RUN=0
[ "${1:-}" = "--dry-run" ] && DRY_RUN=1

# آستانه‌ها (قابلِ بازنویسی با متغیرِ محیطی، برای آزمون)
WINDOW_SECONDS="${WINDOW_SECONDS:-60}"
TH_RPS="${TH_RPS:-60}"                 # درخواست در ثانیه
TH_429="${TH_429:-80}"                 # پاسخِ ۴۲۹ در پنجره
TH_ONE_IP="${TH_ONE_IP:-240}"          # درخواستِ یک آی‌پی در پنجره
TH_5XX="${TH_5XX:-50}"                 # خطای سرور در پنجره
COOLDOWN=300                           # ۵ دقیقه سکوت بین دو هشدارِ هم‌نوع

# نامِ دسته‌ها — همان کلیدِ فایلِ حالت
readonly K_RPS=rps K_429=satur K_IP=ip K_5XX=err

log() { printf '[%s] %s\n' "$(date '+%Y-%m-%dT%H:%M:%S%:z')" "$*" >> "$STATE_LOG" 2>/dev/null || true; }

# ═══════════════════════════════════════════════════════════════════════════
#  تشخیصِ «آیا در پنجرهٔ آخر بود؟» با فهرستِ ثانیه‌ها، نه با پارسِ ساعت
# ═══════════════════════════════════════════════════════════════════════════
#
# چرا این‌طور: هر خطِ لاگ یک مُهرِ «17/Sep/2026:16:41:19 +0330» دارد. اگر
# بخواهیم برای هر خط تاریخ را به عدد تبدیل کنیم، ۶۰ هزار بار `date` صدا
# می‌خورد و خودِ نگهبان به یک بار روی سرور تبدیل می‌شود.
#
# به‌جایش ۶۰ مُهرِ ثانیهٔ آخر را می‌سازیم و با «تطبیقِ رشته‌ای» فیلتر
# می‌کنیم: کارِ grep روی متنِ ثابت، تقریباً بی‌هزینه است.
window_stamps() {
  local now; now=$(date +%s)
  local i
  for ((i = WINDOW_SECONDS - 1; i >= 0; i--)); do
    LC_ALL=C date -d "@$((now - i))" '+%d/%b/%Y:%H:%M:%S'
  done
}

# ── آمارِ پنجره: تعدادِ کل، ۴۲۹، ۵xx و پرتکرارترین آی‌پی ────────────────────
# ⚠️ شمارشِ کدِ وضعیت با «فیلدِ دوازدهم» انجام نمی‌شود: اگر آدرسِ درخواست
# فاصله داشته باشد (که در حمله‌ها کم نیست)، شمارشِ فیلد جابه‌جا می‌شود.
# الگوی درست، «رشتهٔ درخواستِ بسته‌شده با " و بعد سه رقمِ کد» است.
collect_stats() {
  awk '
    {
      # کدِ وضعیت: اولین «" NNN » بعد از درخواست
      if (match($0, /" [0-9][0-9][0-9] /)) {
        code = substr($0, RSTART + 2, 3)
        total++
        if (code == "429") c429++
        else if (code ~ /^5/) c5xx++
      } else {
        total++
      }
      ip = $1
      if (ip ~ /^[0-9a-fA-F:.]/) { cnt[ip]++ ; if (cnt[ip] > max) { max = cnt[ip]; top = ip } }
    }
    END { printf "%d %d %d %d %s\n", total, c429, c5xx, max, (top == "" ? "-" : top) }
  '
}

# پرتکرارترین مسیرهای یک آی‌پی در پنجرهٔ جاری — برای «چه می‌خواست؟».
# قالبِ لاگ: `IP - - [تاریخ] "GET /مسیر HTTP/1.1" 200 ...` — استخراج با sed،
# بدونِ پارسِ سنگین. سه ردیفِ اول، با شمارش.
top_paths() {
  local ip="$1" limit="${2:-3}"
  [ -s "${WIN_FILE:-}" ] || return 0
  grep -F -- "$ip " "$WIN_FILE" 2>/dev/null \
    | sed -nE 's/.*"(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS) ([^ ]*)[^"]*".*/\1 \2/p' \
    | sort | uniq -c | sort -rn | head -n "$limit" \
    | sed -E 's/^[[:space:]]*([0-9]+)[[:space:]]+/\1× /'
}

main() {
  [ -r "$LOG_FILE" ] || { log "log not readable: $LOG_FILE"; exit 0; }

  local stamps; stamps=$(window_stamps)

  # چرا tail: لاگ می‌تواند صدها مگابایت باشد؛ پنجرهٔ ۶۰ ثانیه‌ای همیشه در
  # انتهای فایل است. ۴۰۰ هزار خط = سقفِ امنی که یک حملهٔ سنگین هم از آن رد
  # نمی‌شود بی‌آنکه دیده شود.
  # خطوطِ پنجره یک‌بار در فایلِ موقت می‌نشیند: هم آمار از آن درمی‌آید و هم
  # (اگر هشدار لازم شد) پرتکرارترین مسیرهای همان آی‌پی. قبلاً یک پاسِ واحد
  # بود و «چه می‌خواست؟» جوابی نداشت — مالک باید خودش لاگ را می‌گشت.
  WIN_FILE="$(mktemp -t gg-attack.XXXXXX 2>/dev/null || echo /tmp/gg-attack-window)"
  trap 'rm -f "$WIN_FILE"' EXIT
  tail -n 400000 "$LOG_FILE" 2>/dev/null | grep -F -f <(printf '%s\n' "$stamps") -- 2>/dev/null > "$WIN_FILE" || true

  local stats
  stats=$(collect_stats < "$WIN_FILE" || true)
  stats="${stats:-0 0 0 0 -}"
  read -r total c429 c5xx top_count top_ip <<<"$stats"

  local rps; rps=$(awk -v t="$total" -v w="$WINDOW_SECONDS" 'BEGIN { printf "%d", t / (w > 0 ? w : 60) }')

  local fired=0
  local msg=""

  # ═══════════════════════════════════════════════════════════════════════
  #  سکوتِ ۵ دقیقه‌ای — بر اساسِ فایلِ حالتِ داخلِ /run (روی RAM)
  # ═══════════════════════════════════════════════════════════════════════
  # /run انتخاب شده تا با ری‌استارتِ سرور پاک شود: بعد از یک ری‌استارت،
  # دانستنِ «قبلاً هشدار دادم» بی‌فایده است و آدم باید وضعیتِ تازه را ببیند.
  local now; now=$(date +%s)
  can_fire() {
    local key="$1" last=0
    if [ -f "$STATE_FILE" ]; then
      last=$(grep -m1 "^${key}=" "$STATE_FILE" 2>/dev/null | cut -d= -f2 || true)
      last="${last:-0}"
    fi
    [ $((now - last)) -ge "$COOLDOWN" ]
  }
  mark_fired() {
    local key="$1"
    touch "$STATE_FILE" 2>/dev/null || true
    if grep -q "^${key}=" "$STATE_FILE" 2>/dev/null; then
      sed -i "s/^${key}=.*/${key}=${now}/" "$STATE_FILE" 2>/dev/null || true
    else
      printf '%s=%s\n' "$key" "$now" >> "$STATE_FILE" 2>/dev/null || true
    fi
  }

  # ── نشانهٔ ۱: سرعتِ کل ──
  if [ "$rps" -ge "$TH_RPS" ] && can_fire "$K_RPS"; then
    fired=1; mark_fired "$K_RPS"
    msg+="<b>سرعتِ درخواست‌ها بالا رفته</b>\nدر ۶۰ ثانیهٔ گذشته <b>${total}</b> درخواست رسید (حدودِ <b>${rps} در ثانیه</b>).\nحالتِ عادیِ این سرور چند درخواست در ثانیه است.\n\n"
    log "ALERT rps rps=$rps total=$total"
  fi

  # ── نشانهٔ ۲: سقفِ ضدِربات دارد می‌گیرد ──
  if [ "$c429" -ge "$TH_429" ] && can_fire "$K_429"; then
    fired=1; mark_fired "$K_429"
    msg+="<b>سقفِ ضدِربات فعال شد</b>\n<b>${c429}</b> درخواست در یک دقیقه با پاسخِ «زیادی درخواست دادی» (۴۲۹) برگشت — یعنی یک منبع دارد پشتِ‌سرهم می‌کوبد و سقفِ ۳۰/ثانیه دارد مهارش می‌کند.\n\n"
    log "ALERT 429 count=$c429"
  fi

  # ── نشانهٔ ۳: موجِ متمرکز از یک آی‌پی ──
  #
  # پیام عمداً «چه می‌خواست؟» را هم می‌گوید. تجربهٔ ۲۹ شهریور: هشدارِ «۲۶۳
  # درخواست از یک آی‌پی» بدونِ این خط، سؤالِ «چرا به اپی که عمومی نشده حمله
  # شده؟» را بی‌جواب می‌گذاشت؛ با فهرستِ مسیرها یک نگاه کافی است تا معلوم
  # شود اسکنرِ خودکارِ وردپرس/PHP است یا چیزِ جدی‌تر.
  if [ "$top_count" -ge "$TH_ONE_IP" ] && can_fire "$K_IP"; then
    fired=1; mark_fired "$K_IP"
    local paths scanner=1
    paths=$(top_paths "$top_ip" 3 || true)
    msg+="<b>یک منبعِ پرترافیک</b>\nآی‌پیِ <code>${top_ip}</code> در یک دقیقه <b>${top_count}</b> درخواست فرستاده.\n"
    if [ -n "$paths" ]; then
      # `$paths` خودش خط‌به‌خط است و خطِ خالیِ انتهایی ندارد؛ همان را داخل
      # <code> می‌گذاریم (نسخهٔ اول با sed خطِ اضافه می‌ساخت و پیام شلخته شد).
      msg+="پرتکرارترین درخواست‌هایش:\n<code>${paths}</code>\n"
      # اگر همهٔ مسیرها الگویِ اسکنِ CMS/فایل‌های حساس داشتند، صریح بگو.
      while IFS= read -r line; do
        case "$line" in
          *".env"*|*".git"*|*"wp-"*|*"wordpress"*|*".php"*|*"phpinfo"*|*"zend"*|*"yii"*|*"/vendor/"*|*"composer"*|*"xmlrpc"*) : ;;
          *) scanner=0 ;;
        esac
      done <<<"$paths"
      if [ "$scanner" = "1" ]; then
        msg+="الگو: <b>اسکنرِ خودکارِ آسیب‌پذیری</b> — دنبالِ فایل‌های وردپرس/PHP و فایل‌های حساس می‌گردد؛ ربطی به این که اپ عمومی شده یا نه ندارد. اگر واژهٔ «اسکنر» در پاسخ‌ها زیاد شد (۴۰۴)، خودش می‌رود.\n"
      fi
    fi
    msg+="\n"
    log "ALERT single-ip ip=$top_ip count=$top_count paths=$(printf '%s' "$paths" | tr '\n' ';')"
  fi

  # ── نشانهٔ ۴: خطای سرور ──
  if [ "$c5xx" -ge "$TH_5XX" ] && can_fire "$K_5XX"; then
    fired=1; mark_fired "$K_5XX"
    msg+="<b>سرور دارد خطا می‌دهد</b>\n<b>${c5xx}</b> پاسخِ خطای سرور (۵xx) در یک دقیقه. این از بقیه فوری‌تر است — ممکن است فشار از توانِ سرور گذشته باشد یا سرویسِ دیگری خراب شده باشد.\n\n"
    log "ALERT 5xx count=$c5xx"
  fi

  [ "$fired" -eq 1 ] || { exit 0; }

  local text
  text="<b>هشدارِ حمله — قلقلی</b>\n\n${msg}این لحظه چه کار کنی:\n۱) اپ و وب را یک بار باز کن و ببین کند نشده (اگر کند شده، موج جدی است).\n۲) اگر ادامه داشت، <b>کلادفلر را از پنل ادمین روشن کن</b>: ${ADMIN_URL}\n۳) پنل ادمین: ${WEB_URL}\n\n(اگر موج ادامه داشت، ۵ دقیقهٔ دیگر دوباره خبر می‌دهم.)"

  if [ "$DRY_RUN" -eq 1 ]; then
    printf '%s\n' "──── متنِ هشدار (آزمایشی، ارسال نشد) ────"
    printf '%b\n' "$text"
    exit 0
  fi

  # ── ارسالِ تلگرام — همان فایلِ تنظیماتیِ پشتیبان‌گیری، از راهِ کمکیِ مشترک ──
  local TOKEN CHAT
  TOKEN=$(tg_conf_get "$TG_CONF" TELEGRAM_BOT_TOKEN)
  CHAT=$(tg_conf_get "$TG_CONF" TELEGRAM_CHAT_ID)
  if [ -z "$TOKEN" ] || [ -z "$CHAT" ]; then
    log "telegram config missing; alert not sent ($TG_CONF)"
    exit 0
  fi
  local err
  if err=$(tg_send_message "$TOKEN" "$CHAT" "$text"); then
    log "telegram alert sent"
  else
    # دلیلِ شکست در لاگ می‌ماند — «send failed»ِ بی‌توضیح، یک ساعت عیب‌یابی است.
    log "telegram send failed: ${err:0:300}"
  fi
}

main "$@"
