#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
#  کمکیِ مشترکِ تلگرام برای نگهبان‌ها — یک جا، یک رفتار
# ═══════════════════════════════════════════════════════════════════════════
#
# ── چرا این فایل وجود دارد (یک باگِ واقعی، ۲۶ شهریور) ─────────────────────
#
# فایلِ تنظیماتِ تلگرامِ سرور مقدارها را با کوتیشن نگه می‌دارد:
#
#     TELEGRAM_BOT_TOKEN="88154..."
#     TELEGRAM_CHAT_ID="21297..."
#
# ولی هر دو نگهبان آن را با `cut -d= -f2-` می‌خواندند، یعنی **با کوتیشن**.
# نتیجه: آدرسِ API می‌شد `/bot"88154..."/sendMessage` و تلگرام ۴۰۴ می‌داد.
#
# چرا کسی متوجه نشده بود: نگهبانِ سلامت فقط *هنگامِ خرابی* پیام می‌فرستد و
# تا حالا خرابی‌ای پیش نیامده بود — یعنی این باگ درست در همان شبی که لازم
# می‌شد (نصفِ شب، سرور خوابیده، هیچ پیامی به مالک نرسیده) خودش را نشان
# می‌داد. این‌طور باگ‌ها بدترین نوع‌اند: مسیرِ هشدار که بی‌صدا خراب است، از
# نداشتنِ هشدار بدتر است چون آدم فکر می‌کند پشتش گرم است.
#
# پس خواندنِ تنظیمات یک‌جا و مقاوم شد: کوتیشنِ تک/جفت و فاصلهٔ اضافه هر دو
# تحمل می‌شوند، و `scripts/test-monitor-alerts.sh` (که در CI اجرا می‌شود)
# جلوی برگشتنِ همین اشتباه را می‌گیرد.
#
# مصرف:
#     source "$(dirname "$0")/lib/telegram.sh"
#     TOKEN=$(tg_conf_get "$CONF" TELEGRAM_BOT_TOKEN)
#     CHAT=$(tg_conf_get  "$CONF" TELEGRAM_CHAT_ID)
#     tg_send_message "$TOKEN" "$CHAT" "<b>متن</b>"

# مقدارِ یک کلید را از فایلِ تنظیمات می‌خواند؛ کوتیشن و فاصله را می‌بُرد.
tg_conf_get() {
  local file="$1" key="$2" raw=""
  [ -r "$file" ] || return 0
  raw=$(grep -m1 -E "^[[:space:]]*${key}=" "$file" 2>/dev/null | cut -d= -f2- || true)
  # ترتیب مهم است: اول فاصله، بعد کوتیشن — وگرنه `"  abc  "` نصفه بریده می‌شود.
  printf '%s' "$raw" \
    | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' \
    | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\\(.*\\)'\$/\1/" \
    | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//'
}

# ارسالِ پیام. کدِ خروج: ۰ = رفت (یا «لازم نبود»)، ۱ = واقعاً نرفت.
# متنِ خطا در فایلِ لاگِ صداکننده ثبت می‌شود؛ سکوتِ محض در مسیرِ هشدار ممنوع.
tg_send_message() {
  local token="$1" chat="$2" text="$3"
  [ -n "$token" ] && [ -n "$chat" ] || return 1
  local body
  body=$(curl -sS --max-time 20 -X POST \
    "https://api.telegram.org/bot${token}/sendMessage" \
    --data-urlencode "chat_id=${chat}" \
    --data-urlencode "text=${text}" \
    -d "parse_mode=HTML" 2>&1) || { printf '%s' "$body"; return 1; }
  case "$body" in
    *'"ok":true'*) return 0 ;;
    *) printf '%s' "$body"; return 1 ;;
  esac
}
