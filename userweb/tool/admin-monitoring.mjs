#!/usr/bin/env node
//
// گاردِ همسانیِ «صفحهٔ مانیتورینگ سرور» در پنل ادمین با بک‌اند.
//
// باگی که این فایل برایش نوشته شد: وقتی هیچ خطایی در لاگ PM2 نبود، اندپوینتِ
// /api/admin/metrics یک رشتهٔ خالی در `pm2Logs` برمی‌گرداند و فرانت هم
// رشتهٔ خالی را با «در حال بارگذاری لاگ‌ها…» یکی می‌گرفت (فالسی)؛ یعنی
// سرور کاملاً سالم بود ولی پنل تا ابد «در حال بارگذاری» نشان می‌داد.
//
// این گارد دو چیز را قفل می‌کند:
//   ۱) بک‌اند هرگز pm2Logs خالی برنمی‌گرداند؛ وضعیت «بدون خطا» یک متنِ
//      صریح است (و هر دو گرهٔ تولید game/http خوانده می‌شوند).
//   ۲) فرانت حالت «در حال بارگذاری» را فقط تا رسیدنِ داده نشان می‌دهد و
//      بعد از آن، نبودِ خطا را به‌صورت «سالم» می‌نمایاند نه «در حال بارگذاری».
//
// کامنت‌ها با strip حذف می‌شوند تا این توضیحات خودِ تست را سبز نکنند.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..', '..');

function strip(src) {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^[ \t]*\/\/\/?.*$/gm, '')
    .replace(/([^:])\/\/.*$/gm, '$1');
}
const read = p => strip(fs.readFileSync(path.join(root, p), 'utf8'));

const server = read('backend/src/server.js');
const admin = read('admin/src/pages/metrics.jsx');

let checks = 0;
const ok = (label, cond) => {
  assert.ok(cond, `❌ ${label}`);
  checks += 1;
  console.log(`  ✓ ${label}`);
};

console.log('\n== اندپوینت لاگ PM2 در بک‌اند ==');
// هر دو گره خوانده شوند؛ وگرنه خطای گره http در پنل دیده نمی‌شود.
ok('هر دو گرهٔ game و http خوانده می‌شوند',
  /ghelgheli-api-http/.test(server) && /ghelgheli-api/.test(server));
// «لاگ خالی» باید به یک متنِ صریحِ «بدون خطا» تبدیل شود، نه رشتهٔ خالی.
ok('حالتِ بدونِ خطا متنِ صریح برمی‌گرداند (نه رشتهٔ خالی)',
  /هیچ خطایی در لاگ نیست|هیچ خطایی در لاگ سرور ثبت نشده/.test(server));

console.log('\n== صفحهٔ مانیتورینگ در پنل ادمین ==');
// بارگذاری فقط تا رسیدنِ داده، نه تا پر شدنِ لاگ.
ok('حالتِ بارگذاری به loading اولیه گره خورده (نه به پربودنِ لاگ)',
  /loading\s*&&\s*!data/.test(admin) || /loading\s*\)\s*&&\s*!data/.test(admin));
// بعد از داده، نبودِ خطا باید پیامِ سالم بدهد.
ok('نبودِ خطا پیامِ «سالم» می‌دهد (نه «در حال بارگذاری»)',
  /هیچ خطایی در لاگ سرور ثبت نشده|گره‌ها سالم/.test(admin));
// متنِ «در حال بارگذاری» نباید شاخهٔ شرطِ پربودنِ لاگ باشد.
ok('«در حال بارگذاری لاگ‌ها» شاخهٔ فالسیِ pm2Logs نیست',
  !/pm2Logs\s*\?[\s\S]{0,80}در حال بارگذاری لاگ/.test(admin));

console.log(`\n══════════════════════════════════════════`);
console.log(`  نتیجه: ${checks} بررسیِ مانیتورینگ موفق`);
console.log(`══════════════════════════════════════════`);
