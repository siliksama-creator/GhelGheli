// گذرگاهِ «جشنِ دریافت» — یک منبعِ واحد برای هر جایزه‌ای که به کاربر می‌رسد.
//
// ── چرا گذرگاه و نه props ─────────────────────────────────────────────────
//
// جایزه در جاهای مختلفی واریز می‌شود: ماموریت روزانه/هفتگی، ماموریتِ
// اختصاصی، جایزهٔ تکمیل روزانه، گردونه، و زنجیرهٔ ورود. هر کدام از این‌ها
// در یک صفحهٔ متفاوت است و چند تای‌شان (گردونه، بازی‌ها) تمام‌صفحه‌اند.
// اگر جشن را با props به تک‌تکِ آن صفحه‌ها می‌دادیم، اولین صفحه‌ای که
// فراموش می‌شد یعنی تجربهٔ ناهمگون — همان چیزی که مالک از آن شکایت داشت
// («همیشه یک جایی دور از دید نوشته می‌شود»). اینجا یک فراخوانیِ ساده کافی
// است و میزبانِ جشن یک‌بار در ریشهٔ اپ سوار می‌شود.
//
// ── چرا پیامِ `toast` را حذف نمی‌کنیم ─────────────────────────────────────
//
// `toast` برای پیام‌های «انجام شد» (کپیِ متنِ دعوت، ارسالِ درخواست دوستی)
// هنوز درست است. فقط مسیرهای **جایزه‌ای** به این گذرگاه منتقل می‌شوند،
// چون آن‌ها لحظهٔ «چیزی گرفتم» هستند و باید جلوی چشم باشند.

const listeners = new Set();

/**
 * عضویت در رویدادِ جایزه. خروجی، تابعِ لغوِ عضویت است.
 * @param {(payload: object) => void} fn
 */
export function onReward(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/**
 * ثبتِ یک جایزه برای نمایشِ جشن.
 *
 * @param {object} payload
 * @param {'mission'|'daily'|'custom'|'wheel'|'streak'} [payload.source]
 *        کلید عنوان از قراردادِ متنِ زنده (`reward.<source>`).
 * @param {number} [payload.points] امتیازی که واریز شد
 * @param {number} [payload.coins]  سکهٔ واریزشده
 * @param {number} [payload.xp]     تجربهٔ واریزشده
 * @param {string} [payload.note]   متنِ تازه‌مخصوص این جایزه (مثل برچسبِ
 *        جایزهٔ گردونه). اگر بیاید، به‌جای مقدارهای عددی نشان داده می‌شود.
 */
export function celebrateReward(payload) {
  if (!payload || typeof payload !== 'object') return;
  const hasAmount =
    Number(payload.points) > 0 || Number(payload.coins) > 0 || Number(payload.xp) > 0;
  // جشنِ بی‌مقدار بی‌معناست: نه عددی هست که کاربر ببیند، نه برچسبی.
  if (!hasAmount && !payload.note) return;
  for (const fn of listeners) {
    try { fn(payload); } catch { /* یک شنوندهٔ خراب نباید بقیه را بخواباند */ }
  }
}
