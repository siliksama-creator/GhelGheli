// گذرگاهِ «لحظهٔ جایزه» — یک منبعِ واحد برای هر چیزی که کاربر به دست می‌آورد
// ═══════════════════════════════════════════════════════════════════════════
//
// ── خواستهٔ مالک (۲۹ شهریور) ──────────────────────────────────────────────
//
// «هر وقت که امتیازی یا سکه‌ای — چه تو ماموریت، چه تو بازی‌ها، چه چرخش یا
// گذر نبرد، اصلاً هر جور ریوارد و هدیه‌ای — یه نفر به دست می‌آورد، دیگه یه
// گوشه ننویسه "شما بازی رو بردید" یا "شما ۱۰۰۰ امتیاز دریافت کردید" یا
// "شما باختید". به‌جاش یه سیستمِ خوشگلِ زیبای انیمیشنیِ جذاب، یکپارچه در وب
// و اندروید بساز که یه لحظه اون چیزی که به دست آورده رو نشون بده… بعد چند
// ثانیه بره، اصلاً اگه یکم دیرتر هم بره هیچ اختلالی در ادامهٔ کار کاربر
// ایجاد نکنه.»
//
// ── چه چیزی این‌جا تصمیم گرفته می‌شود (و چه چیزی نه) ──────────────────────
//
// این فایل فقط *گذرگاه* است: هر مسیرِ جایزه‌دار یک فراخوانی می‌کند و
// میزبانِ واحد (`components/RewardMoment.jsx`) روی کلِ اپ نمایش می‌دهد.
// چرا گذرگاه و نه props: گردونه و بازی‌ها تمام‌صفحه‌اند، ماموریت‌ها داخلِ
// تبِ باشگاه، خرید داخلِ فروشگاه. با props، اولین صفحه‌ای که فراموش شود
// یعنی «وب جشن دارد، جای دیگر ندارد» — همان ناهمگونیِ شکایت‌شده.
//
// ── چرا «جشنِ باخت» هم از همین گذرگاه می‌آید ──────────────────────────────
//
// مالک گفت برای باخت نمی‌داند چه بنویسد. تصمیمِ محصولی: سه حالت:
//   • win  — بردی (جام + کاغذرنگی)
//   • loss — «این دور تمام شد» با لحنِ آرام، بدونِ کلمهٔ باخت، بدونِ قرمز،
//            و با تأکید بر چیزی که کاربر *نگه* داشته (سکه هرگز کم نمی‌شود)
//   • draw — پایاپای
// متنِ هر سه از پنل قابلِ تغییر است (`reward.*`)، پس اگر لحن را نپسندید
// بدونِ آپدیت عوضش می‌کنید.
//
// ── بازی‌های مستثنا ──────────────────────────────────────────────────────
//
// دوئل کارت و پنالتی از این سیستم **بیرون**اند (خواستهٔ صریح مالک): صحنهٔ
// نتیجهٔ خودشان سرِ جایش می‌ماند. برای همین `memory` (جفت‌یاب) و ضربه‌زن
// این‌جا هستند و آن دو نه.

export const REWARD_MOMENTS = Object.freeze({
  /** بردِ مسابقه — فقط بازی‌هایی که مستثنا نیستند. */
  WIN: 'win',
  /** پایانِ دور بدونِ برد — لحنِ آرام، بدونِ «باخت». */
  LOSS: 'loss',
  /** تساوی. */
  DRAW: 'draw',
  /** هر جایزهٔ دیگر: امتیاز/سکه/تجربه/آیتم. */
  GAIN: 'gain',
});

/**
 * منابعِ جایزه (عنوانِ هرکدام از پنل: کلیدِ `reward.<source>`).
 *
 * ⚠️ این فهرست **قرارداد** است: گاردِ `tool/reward-parity.mjs` همین آرایه را
 *    در اندروید (`reward_moment.dart`) هم می‌خواند و اگر یکی اضافه شود و
 *    دیگری نه، قرمز می‌شود. دلیلش ساده است: عنوانِ گم‌شده یعنی کاربرِ اپ
 *    کارتِ جایزه را با متنِ پیش‌فرض می‌بیند و کاربرِ وب با متنِ ادیت‌شدهٔ
 *    ادمین — همان واگرایی‌ای که مالک از آن شکایت داشت.
 */
export const MOMENT_SOURCES = Object.freeze([
  'mission', 'daily', 'custom', 'wheel', 'streak', 'pass', 'shop', 'tap', 'memory', 'league',
]);

const listeners = new Set();

/** عضویت در رویدادِ جایزه. خروجی، تابعِ لغوِ عضویت است. */
export function onRewardMoment(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/**
 * ثبتِ یک لحظهٔ جایزه برای نمایش.
 *
 * @param {object} payload
 * @param {string} [payload.kind]   یکی از `REWARD_MOMENTS` (پیش‌فرض `gain`)
 * @param {string} [payload.source] یکی از `MOMENT_SOURCES`
 * @param {number} [payload.points] امتیازِ واریزشده
 * @param {number} [payload.coins]  سکهٔ واریزشده
 * @param {number} [payload.xp]     تجربهٔ واریزشده
 * @param {string} [payload.item]   نامِ آیتم (خریدِ فروشگاه/پاداشِ گذر)
 * @param {string} [payload.note]   جملهٔ کوتاهِ همین لحظه (مثل برچسبِ گردونه)
 */
export function rewardMoment(payload) {
  if (!payload || typeof payload !== 'object') return;
  const kind = REWARD_MOMENTS[String(payload.kind || '').toUpperCase()] || REWARD_MOMENTS.GAIN;
  const hasAmount =
    Number(payload.points) > 0 || Number(payload.coins) > 0 || Number(payload.xp) > 0;
  const hasItem = Boolean(String(payload.item || '').trim());
  // لحظهٔ بی‌مقدار و بی‌آیتم بی‌معناست — همان قاعده‌ای که نسخهٔ قبلی داشت:
  // جشنِ دروغ بدتر از نبودِ جشن است. (مسیرهای بی‌جایزه مثل «درخواستِ دوستی
  // فرستاده شد» از همین تابع رد می‌شوند و باید ساکت بمانند.)
  //
  // ⚠️ استثنا: برد/باخت/تساوی **همیشه** نمایش داده می‌شوند، حتی با صفر
  //    امتیاز — چون خودِ «نتیجهٔ بازی» پیامی است که کاربر منتظرش است.
  const isOutcome = kind !== REWARD_MOMENTS.GAIN;
  if (!isOutcome && !hasAmount && !hasItem && !payload.note) return;
  const event = { ...payload, kind, source: String(payload.source || 'mission') };
  for (const fn of listeners) {
    try { fn(event); } catch { /* یک شنوندهٔ خراب نباید بقیه را بخواباند */ }
  }
}

/** میان‌بُرِ خوانا برای نتیجهٔ مسابقه. */
export function matchMoment({ won, draw, source = 'memory', points, coins, xp, note } = {}) {
  rewardMoment({
    kind: won ? REWARD_MOMENTS.WIN : draw ? REWARD_MOMENTS.DRAW : REWARD_MOMENTS.LOSS,
    source, points, coins, xp, note,
  });
}
